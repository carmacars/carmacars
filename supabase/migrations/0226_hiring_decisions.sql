-- Emails to send: change one (the outcome, the email on or off, the personal note); the rubric follows
create or replace function app.hiring_decide(p_by uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  a job_applications := app.hiring_lock(p_by, (p ->> 'id')::uuid);
  d hiring_decisions;
  v_outcome text := coalesce(nullif(p ->> 'outcome', ''), (select outcome from hiring_decisions where application_id = a.id));
begin
  if v_outcome = 'sales_shortlist' then v_outcome := 'sales'; end if;
  if v_outcome = 'no_show' and a.status not in ('booked', 'interviewed', 'no_show') then raise exception 'No show is for a booked call' using errcode = '23514'; end if;
  d := app.hiring_decision_set(a.id, v_outcome, (p ->> 'send_email')::boolean, case when p ? 'note' then coalesce(p ->> 'note', '') end, p_by);
  perform set_config('app.hiring_decide', 'on', true);
  insert into interview_scores (application_id, decision, interviewer)
  values (a.id, case v_outcome when 'decline' then 'no' else v_outcome end, p_by)
  on conflict (application_id) do update set decision = excluded.decision, updated_at = now();
  perform set_config('app.hiring_decide', '', true);
  return to_jsonb(d);
end $$;

create or replace function app.hiring_decision_undo(p_by uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  a job_applications := app.hiring_lock(p_by, (p ->> 'id')::uuid);
  d hiring_decisions;
begin
  select * into d from hiring_decisions where application_id = a.id for update;
  if d.application_id is null then return jsonb_build_object('undone', false); end if;
  if d.sent_at is not null then raise exception 'The decision email was sent already: it cannot be undone' using errcode = '23514'; end if;
  delete from hiring_decisions where application_id = a.id;
  -- the rubric goes back to Maybe
  perform set_config('app.hiring_decide', 'on', true);
  update interview_scores set decision = 'maybe', updated_at = now() where application_id = a.id;
  perform set_config('app.hiring_decide', '', true);
  return jsonb_build_object('undone', true);
end $$;

-- one decision carried out: the status, then the email (dedupe per application: never twice)
create or replace function app.hiring_decision_apply(p_app uuid, p_by uuid) returns boolean
language plpgsql security definer set search_path = public, app as $$
declare
  d hiring_decisions;
  a job_applications;
  s hiring_roles;
  v_event bigint;
begin
  select * into d from hiring_decisions where application_id = p_app for update;
  if d.application_id is null or d.sent_at is not null then return false; end if;
  select * into a from job_applications where id = p_app for update;
  if a.id is null or a.purged_at is not null then
    update hiring_decisions set sent_at = now(), sent_by = p_by, email_code = null where application_id = p_app;
    return false;
  end if;
  if d.outcome = 'sales' then
    select * into s from hiring_roles where id = d.sales_role_id;
    update job_applications set status = 'referred', referred_role_id = s.id, slot_id = null, decided_at = now(), decided_by = p_by, updated_at = now()
     where id = a.id returning * into a;
    if d.send_email then
      v_event := app.hiring_emit('applicant_referred', a, jsonb_build_object('reason_text', 'We have chosen another candidate for this role',
        'other_role_title', s.title, 'other_role_summary', s.summary,
        'apply_url', app.hiring_url('/careers/' || s.slug || '/apply?ref=' || a.token || '&src=referral'), 'alt_role_title', '', 'alt_apply_url', ''),
        'hiring_decision:' || a.id);
    end if;
  elsif d.outcome = 'sales_shortlist' then
    update job_applications set status = case when status in ('booked', 'interviewed', 'no_show') then 'rejected' else 'declined' end,
           decided_at = now(), decided_by = p_by, updated_at = now() where id = a.id;
    update job_applications x set note = concat_ws(E'\n', x.note, format('Shortlist: recommended for Sales after the %s call.', (select short_title from hiring_roles where id = a.role_id))),
           updated_at = now()
     where x.role_id = d.sales_role_id and lower(x.email) = lower(a.email) and x.id <> a.id and x.purged_at is null;
  elsif d.outcome = 'decline' then
    update job_applications set status = case when status in ('booked', 'interviewed', 'no_show') then 'rejected' else 'declined' end, slot_id = null,
           decided_at = now(), decided_by = p_by, updated_at = now() where id = a.id returning * into a;
    if d.send_email then v_event := app.hiring_emit('applicant_declined', a, jsonb_build_object('decline_reason', ''), 'hiring_decision:' || a.id); end if;
  elsif d.outcome = 'no_show' then
    update job_applications set status = 'no_show', decided_at = now(), decided_by = p_by, updated_at = now() where id = a.id returning * into a;
    if d.send_email then v_event := app.hiring_emit('applicant_no_show', a, jsonb_build_object('personal_note', coalesce(d.personal_note, '')), 'hiring_decision:' || a.id); end if;
  elsif d.outcome = 'hire' then
    if d.send_email then v_event := app.hiring_emit('applicant_hired', a, jsonb_build_object('personal_note', coalesce(d.personal_note, '')), 'hiring_decision:' || a.id); end if;
  end if;
  update hiring_decisions set sent_at = now(), sent_by = p_by, event_id = v_event where application_id = p_app;
  insert into audit_log (actor_user_id, action, entity_table, entity_id, after)
  values (p_by, 'hiring_decision_sent', 'job_applications', a.id::text, jsonb_build_object('outcome', d.outcome, 'email', d.email_code));
  return true;
end $$;

create or replace function app.hiring_decisions_send(p_by uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  v_at timestamptz;
  r record;
  n integer := 0;
begin
  if p_by is not null then perform app.assert_admin(p_by); end if;
  begin v_at := coalesce(nullif(p ->> 'at', ''), nullif(p ->> 'when', ''))::timestamptz; exception when others then raise exception 'Check the time' using errcode = '22023'; end;
  if v_at is not null and v_at > now() + interval '1 minute' then
    update hiring_decisions set send_after = v_at where sent_at is null;
    get diagnostics n = row_count;
    return jsonb_build_object('scheduled', n, 'at', v_at);
  end if;
  for r in select d.application_id from hiring_decisions d where d.sent_at is null and (p_by is not null or d.send_after <= now()) order by d.decided_at loop
    if app.hiring_decision_apply(r.application_id, p_by) then n := n + 1; end if;
  end loop;
  return jsonb_build_object('sent', n);
end $$;

create or replace function app.hiring_decisions_read(p_by uuid, p jsonb) returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
begin
  perform app.assert_admin(p_by);
  return jsonb_build_object(
    'rows', coalesce((select jsonb_agg(jsonb_build_object('application_id', a.id, 'full_name', a.full_name, 'email', a.email, 'status', a.status,
               'role', r.short_title, 'outcome', d.outcome, 'send_email', d.send_email, 'email_code', d.email_code,
               'subject', (select c.subject from notification_catalogue c where c.code = d.email_code), 'personal_note', d.personal_note,
               'sales_role', (select s.short_title from hiring_roles s where s.id = d.sales_role_id), 'decided_at', d.decided_at,
               'decided_by', (select u.full_name from users u where u.id = d.decided_by), 'send_after', d.send_after, 'sent_at', d.sent_at)
             order by d.sent_at nulls first, r.short_title, a.full_name)
             from hiring_decisions d join job_applications a on a.id = d.application_id join hiring_roles r on r.id = a.role_id
            where d.sent_at is null or d.sent_at > now() - interval '30 days'), '[]'::jsonb),
    'waiting', (select count(*) from hiring_decisions where sent_at is null),
    'emails', (select count(*) from hiring_decisions where sent_at is null and email_code is not null),
    'scheduled_at', (select min(send_after) from hiring_decisions where sent_at is null and send_after is not null));
end $$;

