-- the Sales role for a candidate: in person for an in-person role (Field staff, Sales in person), else remote
create or replace function app.hiring_sales_role_for(a job_applications) returns hiring_roles
language sql stable security definer set search_path = public, app as $$
  select s.* from hiring_roles r, hiring_roles s
   where r.id = a.role_id
     and s.slug = case when r.slug in ('field-staff', 'sales-in-person') or coalesce(a.work_mode, '') = 'in_person' then 'sales-in-person' else 'sales-remote' end
$$;

-- the email a decision sends (null: none)
create or replace function app.hiring_decision_email(d hiring_decisions) returns text
language sql immutable as $$
  select case when not d.send_email then null else case d.outcome
    when 'hire' then 'applicant_hired' when 'sales' then 'applicant_referred' when 'decline' then 'applicant_declined'
    when 'no_show' then 'applicant_no_show' end end
$$;

