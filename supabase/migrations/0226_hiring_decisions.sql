-- 0226: decisions after the interview calls, and the decision emails sent together (docs/changes/2026-11-03-hiring-decisions.md).
-- The owner, Release 23 (before Monday November 2, when every applicant hears back): the rubric's decision (Hire, Maybe,
-- No, No show) gets one more choice, "Good fit for Sales instead". A decision sends nothing by itself: Hiring > Emails to send lists every decided
-- candidate with the email that will go, each can be changed or undone, and one button sends them all (now, or at a time
-- chosen such as Monday 9:00 am Toronto). One email per candidate, never twice.
--
-- 1. hiring_decisions: one row per application, kept in step with the rubric's decision (interview_scores.decision:
--    hire, no = decline, no_show, sales; maybe or none removes a decision not sent yet). outcome: hire (email applicant_hired, new: the next steps), sales (the
--    candidate is referred to Sales with applicant_referred and its one-click prefilled link: sales-in-person for an
--    in-person role, Field staff and Sales in person, sales-remote for a remote one), sales_shortlist (they already applied
--    for that Sales role: no email, their Sales application gets a note for the shortlist), decline (applicant_declined)
--    and no_show (applicant_no_show, new). send_email off records the outcome without an email. personal_note goes into
--    the hire and no-show emails.
-- 2. Sending (app.hiring_decision_apply): the application's status follows (sales: referred to the Sales role; decline:
--    Not hired after a call, Declined before one; no_show: No show; hire: unchanged until Hire with the staff account,
--    0173), the email is queued with a dedupe key per application (emit_event: never twice), sent_at is set. A row sent
--    can no longer be changed or undone.
-- 3. Doors (Admins, as all of Hiring): admin_read hiring_decisions; admin_do hiring_decide (change one from the list; the
--    rubric's decision follows), hiring_decision_undo (back to Maybe),
--    hiring_decisions_send ({at}: schedule; none: send what is due now). The hiring job (every 15 minutes) sends the
--    scheduled ones when their time comes.
-- No applied migration is edited.

create function pg_temp.patch_fn(p_sig regprocedure, p_old text, p_new text) returns void
language plpgsql as $$
declare
  d text := pg_get_functiondef(p_sig);
begin
  if position(p_old in d) = 0 then
    raise exception '0226: the text to change was not found in %: %', p_sig, left(p_old, 120);
  end if;
  execute replace(d, p_old, p_new);
end $$;
create function pg_temp.copy_grants(p_new regprocedure, p_old regprocedure) returns void
language plpgsql as $$
declare g text;
begin
  execute format('revoke all on function %s from public, anon, authenticated', p_new);
  foreach g in array array['anon', 'authenticated', 'service_role'] loop
    if has_function_privilege(g, p_old, 'execute') then execute format('grant execute on function %s to %I', p_new, g); end if;
  end loop;
end $$;

