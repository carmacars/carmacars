-- the decision of an application, recorded (no permission check: the callers check); null outcome removes one not sent
create or replace function app.hiring_decision_set(p_app uuid, p_outcome text, p_send_email boolean, p_note text, p_by uuid) returns hiring_decisions
language plpgsql security definer set search_path = public, app as $$
declare
  a job_applications;
  d hiring_decisions;
  s hiring_roles;
  v_outcome text := p_outcome;
  v_sales_app uuid;
begin
  select * into a from job_applications where id = p_app;
  select * into d from hiring_decisions where application_id = p_app for update;
  if d.sent_at is not null then
    if v_outcome is distinct from d.outcome and not (v_outcome = 'sales' and d.outcome = 'sales_shortlist') then
      raise exception 'The decision email was sent already: it cannot be changed' using errcode = '23514';
    end if;
    return d;
  end if;
  if v_outcome is null then
    delete from hiring_decisions where application_id = p_app;
    return null;
  end if;
  if v_outcome not in ('hire', 'sales', 'decline', 'no_show') then raise exception 'Choose Hire, Sales instead, No or No show' using errcode = '22023'; end if;
  if a.status in ('hired', 'withdrawn') then raise exception 'This candidate is %', a.status using errcode = '23514'; end if;
  if v_outcome = 'sales' then
    s := app.hiring_sales_role_for(a);
    if s.id is null then raise exception 'No Sales role to refer to' using errcode = '23514'; end if;
    if s.id = a.role_id then raise exception 'This is already a Sales application: choose Hire or No' using errcode = '23514'; end if;
    select x.id into v_sales_app from job_applications x
     where x.role_id = s.id and x.id <> a.id and x.purged_at is null and lower(x.email) = lower(a.email) order by x.created_at desc limit 1;
    if v_sales_app is not null then v_outcome := 'sales_shortlist'; end if;
  end if;
  insert into hiring_decisions (application_id, outcome, send_email, sales_role_id, personal_note, decided_by, decided_at)
  values (a.id, v_outcome, case when v_outcome = 'sales_shortlist' then false else coalesce(p_send_email, true) end, s.id, nullif(btrim(coalesce(p_note, '')), ''), p_by, now())
  on conflict (application_id) do update set outcome = excluded.outcome,
         send_email = case when p_send_email is null and hiring_decisions.outcome = excluded.outcome then hiring_decisions.send_email else excluded.send_email end,
         sales_role_id = excluded.sales_role_id,
         personal_note = case when p_note is null then hiring_decisions.personal_note else excluded.personal_note end,
         decided_by = excluded.decided_by, decided_at = now()
  returning * into d;
  update hiring_decisions set email_code = app.hiring_decision_email(d) where application_id = a.id returning * into d;
  return d;
end $$;

-- the rubric's decision is the hiring decision (Maybe or none: no decision)
create or replace function app.hiring_decision_from_rubric() returns trigger
language plpgsql security definer set search_path = public, app as $$
begin
  if current_setting('app.hiring_decide', true) = 'on' then return null; end if;
  if tg_op = 'UPDATE' and new.decision is not distinct from old.decision then return null; end if;
  perform app.hiring_decision_set(new.application_id, case new.decision when 'hire' then 'hire' when 'no' then 'decline' when 'no_show' then 'no_show' when 'sales' then 'sales' end,
                                  null, null, new.interviewer);
  return null;
end $$;
