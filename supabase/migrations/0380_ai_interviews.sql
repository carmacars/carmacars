-- a new link (or the same one again): open for the days of the setting from now, the answers already given kept
create or replace function app.ai_interview_send(a job_applications) returns bigint
language plpgsql security definer set search_path = public, app as $$
declare
  iv ai_interviews;
  v_days integer := (app.settings()).hiring_ai_interview_days;
begin
  insert into ai_interviews (application_id, role_id, questions, expires_at)
  values (a.id, a.role_id, app.ai_interview_questions(a.role_id), now() + make_interval(days => v_days))
  on conflict (application_id) do update set
    expires_at = now() + make_interval(days => v_days), links_sent = ai_interviews.links_sent + 1,
    state = case when ai_interviews.state = 'expired' then case when ai_interviews.started_at is null then 'sent' else 'started' end else ai_interviews.state end,
    updated_at = now()
  returning * into iv;
  update job_applications set waiting_for_day = false, no_slots_since = null, updated_at = now() where id = a.id and (waiting_for_day or no_slots_since is not null);
  return app.hiring_emit_pre0211('applicant_ai_interview', a, app.ai_interview_vars(a, iv), 'applicant_ai_interview:' || a.id || ':' || iv.links_sent);
end $$;

