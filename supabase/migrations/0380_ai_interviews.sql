-- ================================================================ 6. the interview page (the applicant's link; the server calls these)
create or replace function app.ai_interview_open(iv ai_interviews) returns boolean
language sql stable as $$ select iv.state in ('sent', 'started') and iv.expires_at > now() and iv.purged_at is null $$;

-- the next thing to ask: the follow-up waiting, else the first question not answered yet (null: all answered)
create or replace function app.ai_interview_next(iv ai_interviews) returns jsonb
language sql stable security definer set search_path = public, app as $$
  select case
    when iv.pending_followup is not null then jsonb_build_object('seq', n.n + 1, 'kind', 'followup', 'key', iv.pending_followup ->> 'key', 'text', iv.pending_followup ->> 'text')
    else (select jsonb_build_object('seq', n.n + 1, 'kind', 'question', 'key', q ->> 'key', 'text', q ->> 'text')
            from jsonb_array_elements(iv.questions) with ordinality x(q, i)
           where not exists (select 1 from ai_interview_answers w where w.interview_id = iv.id and w.kind = 'question' and w.question_key = q ->> 'key')
           order by i limit 1) end
    from (select count(*)::int n from ai_interview_answers w where w.interview_id = iv.id) n
$$;

create or replace function app.ai_interview_view(a job_applications, iv ai_interviews) returns jsonb
language sql stable security definer set search_path = public, app as $$
  select jsonb_build_object('ok', true, 'id', iv.id,
    'state', case when iv.state in ('sent', 'started') and iv.expires_at <= now() then 'expired' else iv.state end,
    'first_name', app.hiring_first_name(a.full_name), 'role_title', r.title, 'expires_at', iv.expires_at,
    'consent_needed', iv.consent_at is null, 'consent_text', app.ai_interview_consent_text(),
    'total', jsonb_array_length(iv.questions),
    'answered', (select count(*) from ai_interview_answers w where w.interview_id = iv.id and w.kind = 'question'),
    'next', case when app.ai_interview_open(iv) then app.ai_interview_next(iv) end)
    from hiring_roles r where r.id = a.role_id
$$;

create or replace function public.server_ai_interview(p_token text) returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare
  a job_applications;
  iv ai_interviews;
begin
  select * into a from job_applications where token = p_token and purged_at is null;
  if a.id is null then return jsonb_build_object('ok', false, 'error', 'not_found'); end if;
  select * into iv from ai_interviews where application_id = a.id;
  if iv.id is null then return jsonb_build_object('ok', false, 'error', 'none'); end if;
  if a.status in ('withdrawn', 'hired', 'declined', 'rejected', 'referred') and iv.state in ('sent', 'started') then
    return jsonb_build_object('ok', false, 'error', 'closed');
  end if;
  return app.ai_interview_view(a, iv);
end $$;

-- the consent, then the interview starts
create or replace function public.server_ai_interview_start(p_token text, p jsonb default '{}'::jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  a job_applications;
  iv ai_interviews;
begin
  select * into a from job_applications where token = p_token and purged_at is null;
  select * into iv from ai_interviews where application_id = a.id for update;
  if iv.id is null then return jsonb_build_object('ok', false, 'error', 'not_found'); end if;
  if not app.ai_interview_open(iv) then return jsonb_build_object('ok', false, 'error', 'closed'); end if;
  if coalesce((p ->> 'consent')::boolean, false) is not true then return jsonb_build_object('ok', false, 'error', 'consent'); end if;
  update ai_interviews set consent_at = coalesce(consent_at, now()), consent_text = coalesce(consent_text, app.ai_interview_consent_text()),
         started_at = coalesce(started_at, now()), state = 'started', updated_at = now()
   where id = iv.id returning * into iv;
  return app.ai_interview_view(a, iv);
end $$;

-- one answer: p {seq, mode voice|typed, text (typed), audio_key, audio_type, audio_bytes, audio_seconds}. The seq must be the
-- one asked (a second press of the same answer is answered as the first). The last answer submits the interview: the
-- application is Interviewed and waits for an Admin.
create or replace function public.server_ai_interview_answer(p_token text, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  a job_applications;
  iv ai_interviews;
  v_next jsonb;
  v_mode text := p ->> 'mode';
  v_text text := nullif(btrim(left(coalesce(p ->> 'text', ''), 4000)), '');
  w ai_interview_answers;
begin
  select * into a from job_applications where token = p_token and purged_at is null for update;
  select * into iv from ai_interviews where application_id = a.id for update;
  if iv.id is null then return jsonb_build_object('ok', false, 'error', 'not_found'); end if;
  select * into w from ai_interview_answers where interview_id = iv.id and seq = (p ->> 'seq')::int;
  if w.id is not null then return app.ai_interview_view(a, iv) || jsonb_build_object('answer_id', w.id, 'repeat', true); end if;
  if not app.ai_interview_open(iv) then return jsonb_build_object('ok', false, 'error', 'closed'); end if;
  if iv.consent_at is null then return jsonb_build_object('ok', false, 'error', 'consent'); end if;
  v_next := app.ai_interview_next(iv);
  if v_next is null or (v_next ->> 'seq')::int is distinct from (p ->> 'seq')::int then return jsonb_build_object('ok', false, 'error', 'order', 'next', v_next); end if;
  if v_mode not in ('voice', 'typed') then return jsonb_build_object('ok', false, 'error', 'invalid'); end if;
  if v_mode = 'typed' and v_text is null then return jsonb_build_object('ok', false, 'error', 'empty'); end if;
  if v_mode = 'voice' and (nullif(p ->> 'audio_key', '') is null or (p ->> 'audio_key') !~ ('^hiring/interviews/' || iv.id || '/[0-9]+-[a-z0-9]+\.(webm|ogg|m4a|mp3|wav)$')) then
    return jsonb_build_object('ok', false, 'error', 'invalid');
  end if;
  insert into ai_interview_answers (interview_id, seq, question_key, kind, prompt, mode, audio_key, audio_type, audio_bytes, audio_seconds, transcript, transcript_state)
  values (iv.id, (v_next ->> 'seq')::int, v_next ->> 'key', v_next ->> 'kind', v_next ->> 'text', v_mode,
          case when v_mode = 'voice' then p ->> 'audio_key' end, case when v_mode = 'voice' then left(p ->> 'audio_type', 60) end,
          case when v_mode = 'voice' then least(greatest(coalesce((p ->> 'audio_bytes')::int, 0), 0), 20000000) end,
          case when v_mode = 'voice' then least(greatest(coalesce((p ->> 'audio_seconds')::numeric, 0), 0), 9999) end,
          case when v_mode = 'typed' then v_text end, case when v_mode = 'voice' then 'pending' else 'done' end)
  returning * into w;
  update ai_interviews set pending_followup = case when v_next ->> 'kind' = 'followup' then null else pending_followup end, updated_at = now()
   where id = iv.id returning * into iv;
  perform app.ai_interview_maybe_submit(iv.id);
  select * into iv from ai_interviews where id = iv.id;
  select * into a from job_applications where id = a.id;
  return app.ai_interview_view(a, iv) || jsonb_build_object('answer_id', w.id, 'kind', w.kind, 'question', w.prompt, 'followups_left',
    greatest((app.settings()).hiring_ai_followups - iv.followups_used, 0), 'transcribe_model', (app.settings()).hiring_ai_transcribe_model);
end $$;

-- all answered (and no follow-up waiting): submitted, the application Interviewed, the scoring due
create or replace function app.ai_interview_maybe_submit(p_id uuid) returns boolean
language plpgsql security definer set search_path = public, app as $$
declare iv ai_interviews;
begin
  select * into iv from ai_interviews where id = p_id for update;
  if iv.state <> 'started' or app.ai_interview_next(iv) is not null then return false; end if;
  update ai_interviews set state = 'submitted', submitted_at = now(), next_attempt_at = now(), updated_at = now() where id = iv.id;
  update job_applications set status = 'interviewed', interviewed_at = coalesce(interviewed_at, now()), updated_at = now()
   where id = iv.application_id and status = 'invited';
  return true;
end $$;

-- a provider call of the interviews, counted in the day's AI allowance
create or replace function app.ai_interview_spent(p_purpose text, p jsonb) returns void
language sql security definer set search_path = public, app as $$
  insert into provider_calls (provider, purpose, ok, error, duration_ms, cost_microusd, units, unit)
  values (left(coalesce(nullif(p ->> 'model', ''), 'workers-ai'), 120), p_purpose, coalesce((p ->> 'ok')::boolean, false), left(p ->> 'error', 500),
          greatest(coalesce((p ->> 'duration_ms')::integer, 0), 0), 0, greatest(coalesce((p ->> 'neurons')::numeric, 0), 0), 'neurons')
