-- 0380: the AI interview for remote assistant applicants, everything recorded (Release 27, docs/changes/2026-11-07-ai-interviews.md).
-- The owner: "wants to explore AI interviewing VAs with everything recorded". SCHEMA_MARKER 0381 (with 0381's guide).
--
-- 1. Who: an applicant for a remote assistant role (hiring_roles.remote and staff_kind 'va': customer service, fleet,
--    finance, remote sales) who passes screening, or whom an Admin invites anyway, gets one email with a personal link to
--    an interview they take on their own, from their phone or computer, instead of the link to book a live call
--    (program_settings.hiring_ai_interviews, on by default). The in-person roles keep their phone calls. The link works
--    7 days (hiring_ai_interview_days). No texts, no reminders: the one email.
-- 2. The interview: nine questions built from the role (app.ai_interview_questions) that cover the rubric: internet and
--    backup, English, social media, the role's skills, experience, understanding of the role and of CarmaCars (with the
--    role's own scenario), the hours and the pay, other jobs, school and education, career or job, moving to Canada. Each
--    question is shown and read aloud; the applicant answers by voice (recorded) or types. At most two follow-ups in all
--    (hiring_ai_followups), asked where an answer is vague. A consent line comes before anything is recorded.
-- 3. Recorded: the audio of each answer (private storage, documents bucket), its transcript (Workers AI Whisper), the
--    questions as asked, the consent and its text; then the AI's scores per rubric topic with a quote from the answers as
--    evidence, the spoken English, red flags, a summary and a recommendation (a live call, hire, decline, or good fit for
--    Sales instead). The AI never decides: the application waits as Interviewed for an Admin, who decides with the
--    rubric as after a call (0226), or invites the candidate to a live call.
-- 4. The AI budget (0133): transcription and follow-ups are live work (someone is waiting), the scoring is background
--    work; the hard stop applies (no paid usage). An answer that cannot be transcribed now is kept and transcribed by the
--    interviews job later; the scoring waits for its share.
-- 5. Privacy: the interview is removed with the application's personal data (12 months after the decision, 0173): the
--    transcripts, the scores' quotes and the audio files. The privacy policy names the recording and the AI summary.
-- 6. Admin: Hiring lists the interview's state and recommendation; the candidate page plays each answer beside its
--    transcript. admin_do 'hiring_ai_live_call', 'hiring_ai_new_link', 'hiring_ai_settings'.
-- No applied migration is edited: app.hiring_emit (0211), app.hiring_application_read (0226), app.hiring_read (0226),
-- app.job_hiring (0229), app.server_jobs_due (0263), public.server_hiring_apply (0173) and app.door (0283) are wrapped.
set local check_function_bodies = off;

create function pg_temp.copy_grants(p_new regprocedure, p_old regprocedure) returns void
language plpgsql as $$
declare g text;
begin
  execute format('revoke all on function %s from public, anon, authenticated', p_new);
  foreach g in array array['anon', 'authenticated', 'service_role'] loop
    if has_function_privilege(g, p_old, 'execute') then execute format('grant execute on function %s to %I', p_new, g); end if;
  end loop;
end $$;
create function pg_temp.patch_fn(p_sig regprocedure, p_old text, p_new text) returns void
language plpgsql as $$
declare
  d text := pg_get_functiondef(p_sig);
begin
  if position(p_old in d) = 0 then
    raise exception '0380: the text to change was not found in %: %', p_sig, left(p_old, 120);
  end if;
  execute replace(d, p_old, p_new);
end $$;

