-- the AI's scores: p {interview_id, ok, result, model, neurons, duration_ms, error, reason, called}. Each quote is checked
-- against the answers (one that is not in them is dropped), the recommendation kept to the four choices, Sales instead
-- never for a Sales role. The interview score is the topics' scores by their weights.
create or replace function public.server_ai_interview_scored(p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  iv ai_interviews;
  r hiring_roles;
  v jsonb := coalesce(p -> 'result', '{}'::jsonb);
  v_said text;
  t jsonb;
  v_topics jsonb := '[]'::jsonb;
  v_score numeric;
  v_ev text;
  v_rec text;
  v_pts numeric := 0;
  v_eng jsonb;
begin
  select * into iv from ai_interviews where id = (p ->> 'interview_id')::uuid for update;
  if iv.id is null or iv.state <> 'submitted' then return jsonb_build_object('ok', false); end if;
  if coalesce((p ->> 'called')::boolean, true) then perform app.ai_interview_spent('interview_score', p); end if;
  if not coalesce((p ->> 'ok')::boolean, false) then
    update ai_interviews set score_attempts = score_attempts + case when p ->> 'reason' = 'quota' then 0 else 1 end,
           next_attempt_at = now() + case when p ->> 'reason' = 'quota' then interval '1 hour' else interval '30 minutes' * (score_attempts + 1) end,
           last_error = left(p ->> 'error', 300), updated_at = now() where id = iv.id;
    return jsonb_build_object('ok', true, 'scored', false);
  end if;
  select * into r from hiring_roles where id = iv.role_id;
  select lower(regexp_replace(string_agg(coalesce(w.transcript, ''), ' '), '[^a-zA-Z0-9]+', ' ', 'g')) into v_said from ai_interview_answers w where w.interview_id = iv.id;
  for t in select x from jsonb_array_elements(app.ai_interview_topics()) x loop
    select (e ->> 'score')::numeric, nullif(btrim(left(e ->> 'evidence', 400)), '') into v_score, v_ev
      from jsonb_array_elements(case when jsonb_typeof(v -> 'topics') = 'array' then v -> 'topics' else '[]'::jsonb end) e
     where e ->> 'key' = t ->> 'key' and (e ->> 'score') ~ '^[1-5](\.0)?$' limit 1;
    -- a quote must be words the candidate said
    if v_ev is not null and (length(regexp_replace(v_ev, '[^a-zA-Z0-9]+', '', 'g')) < 3 or position(btrim(lower(regexp_replace(v_ev, '[^a-zA-Z0-9]+', ' ', 'g'))) in coalesce(v_said, '')) = 0) then v_ev := null; end if;
    v_topics := v_topics || jsonb_build_array(jsonb_build_object('key', t ->> 'key', 'label', t ->> 'label', 'weight', (t ->> 'weight')::int,
      'score', v_score, 'evidence', v_ev));
    v_pts := v_pts + coalesce(v_score, 1) / 5.0 * (t ->> 'weight')::numeric;
    v_score := null; v_ev := null;
  end loop;
  v_rec := v ->> 'recommendation';
  if v_rec not in ('live_call', 'hire', 'decline', 'sales') or v_rec is null then v_rec := 'live_call'; end if;
  if v_rec = 'sales' and r.va_function = 'sales' then v_rec := 'decline'; end if;
  v_eng := jsonb_build_object('level', case when v #>> '{english,level}' in ('fluent', 'good', 'basic') then v #>> '{english,level}' end,
    'score', case when (v #>> '{english,score}') ~ '^[1-5](\.0)?$' then (v #>> '{english,score}')::numeric end,
    'notes', left(v #>> '{english,notes}', 600));
  update ai_interviews set state = 'scored', scored_at = now(), score_model = left(p ->> 'model', 120), last_error = null, updated_at = now(),
         recommendation = v_rec, interview_score = least(greatest(round(v_pts), 0), 100)::int,
         result = jsonb_build_object('topics', v_topics, 'english', v_eng,
           'red_flags', coalesce((select jsonb_agg(left(f, 300)) from (select jsonb_array_elements_text(case when jsonb_typeof(v -> 'red_flags') = 'array' then v -> 'red_flags' else '[]'::jsonb end) f limit 8) x where btrim(f) <> ''), '[]'::jsonb),
           'summary', left(v ->> 'summary', 1200), 'reason', left(v ->> 'reason', 600))
   where id = iv.id;
  return jsonb_build_object('ok', true, 'scored', true, 'recommendation', v_rec);
end $$;

