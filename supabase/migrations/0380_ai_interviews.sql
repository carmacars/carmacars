-- ================================================================ 2. tables
create table if not exists ai_interviews (
  id               uuid primary key default gen_random_uuid(),
  application_id   uuid not null unique references job_applications (id) on delete cascade,
  role_id          uuid not null references hiring_roles (id),
  questions        jsonb not null,                           -- [{key, topics[], text}], as built when the link was sent
  state            text not null default 'sent' check (state in ('sent', 'started', 'submitted', 'scored', 'expired')),
  sent_at          timestamptz not null default now(),
  expires_at       timestamptz not null,
  links_sent       integer not null default 1,
  consent_at       timestamptz,
  consent_text     text,
  started_at       timestamptz,
  submitted_at     timestamptz,
  followups_used   integer not null default 0,
  pending_followup jsonb,                                    -- {key, text}: asked next
  result           jsonb,                                    -- topics[{key, score, evidence}], english{level, score, notes}, red_flags[], recommendation, summary
  interview_score  integer check (interview_score between 0 and 100),
  recommendation   text check (recommendation is null or recommendation in ('live_call', 'hire', 'decline', 'sales')),
  score_model      text,
  score_attempts   integer not null default 0,
  next_attempt_at  timestamptz,
  last_error       text,
  scored_at        timestamptz,
  live_call_at     timestamptz,                              -- an Admin invited the candidate to a live call after it
  purged_at        timestamptz,
  updated_at       timestamptz not null default now()
);
comment on table ai_interviews is 'Hiring (0380): the AI interview of one application: the questions, the consent, the state, and the AI''s scores with evidence and its recommendation. Admins decide; the AI never does.';
create index if not exists ai_interviews_due_idx on ai_interviews (next_attempt_at) where state = 'submitted';

create table if not exists ai_interview_answers (
  id                  uuid primary key default gen_random_uuid(),
  interview_id        uuid not null references ai_interviews (id) on delete cascade,
  seq                 integer not null check (seq between 1 and 40),
  question_key        text not null,
  kind                text not null check (kind in ('question', 'followup')),
  prompt              text not null,
  mode                text not null check (mode in ('voice', 'typed')),
  audio_key           text,
  audio_type          text,
  audio_bytes         integer,
  audio_seconds       numeric(6, 1),
  transcript          text,
  transcript_state    text not null default 'done' check (transcript_state in ('pending', 'done', 'failed')),
  transcript_model    text,
  transcribe_attempts integer not null default 0,
  audio_purged_at     timestamptz,
  created_at          timestamptz not null default now(),
  unique (interview_id, seq)
);
comment on table ai_interview_answers is 'Hiring (0380): each answer of an AI interview in the order asked: the question as asked, voice (the audio in the private documents bucket) or typed, and the transcript.';
create index if not exists ai_interview_answers_pending_idx on ai_interview_answers (created_at) where transcript_state = 'pending';

