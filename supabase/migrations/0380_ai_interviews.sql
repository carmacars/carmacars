-- a transcript (from the answer page, or later from the interviews job): p {answer_id, ok, text, model, neurons, duration_ms, error, called}
create or replace function public.server_ai_interview_transcript(p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare w ai_interview_answers;
begin
  select * into w from ai_interview_answers where id = (p ->> 'answer_id')::uuid for update;
  if w.id is null or w.transcript_state <> 'pending' then return jsonb_build_object('ok', false); end if;
  if coalesce((p ->> 'called')::boolean, true) then perform app.ai_interview_spent('interview_transcribe', p); end if;
  if coalesce((p ->> 'ok')::boolean, false) then
    update ai_interview_answers set transcript = left(btrim(coalesce(p ->> 'text', '')), 8000), transcript_state = 'done',
           transcript_model = left(p ->> 'model', 120), transcribe_attempts = transcribe_attempts + 1 where id = w.id;
  else
    -- a quota refusal is not an attempt (it waits for the allowance); five failures leave it without a transcript
    update ai_interview_answers set transcribe_attempts = transcribe_attempts + case when p ->> 'reason' = 'quota' then 0 else 1 end,
           transcript_state = case when transcribe_attempts + 1 >= 5 and coalesce(p ->> 'reason', '') <> 'quota' then 'failed' else 'pending' end
     where id = w.id;
  end if;
  return jsonb_build_object('ok', true);
end $$;

-- the follow-up after an answer: p {answer_id, text (empty: none), model, neurons, ok, duration_ms, called}. At most the
-- setting's number in one interview, and only after the latest answer to a question.
create or replace function public.server_ai_interview_followup(p_token text, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  a job_applications;
  iv ai_interviews;
  w ai_interview_answers;
  v_text text := nullif(btrim(left(coalesce(p ->> 'text', ''), 300)), '');
begin
  select * into a from job_applications where token = p_token and purged_at is null;
  select * into iv from ai_interviews where application_id = a.id for update;
  if iv.id is null then return jsonb_build_object('ok', false, 'error', 'not_found'); end if;
  if coalesce((p ->> 'called')::boolean, false) then perform app.ai_interview_spent('interview_followup', p); end if;
  select * into w from ai_interview_answers where id = (p ->> 'answer_id')::uuid and interview_id = iv.id;
  if v_text is not null and w.kind = 'question' and iv.pending_followup is null and iv.purged_at is null
     and (app.ai_interview_open(iv) or (iv.state = 'submitted' and iv.expires_at > now()))
     and iv.followups_used < (app.settings()).hiring_ai_followups
     and w.seq = (select max(seq) from ai_interview_answers where interview_id = iv.id)
     and v_text !~* '\m(test|tests|exam|assessment)\M' then
    update ai_interviews set pending_followup = jsonb_build_object('key', w.question_key, 'text', v_text), followups_used = followups_used + 1,
           state = case when state = 'submitted' then 'started' else state end, submitted_at = null, next_attempt_at = null, updated_at = now()
     where id = iv.id returning * into iv;
    -- the last question's follow-up: the interview is not over yet
    update job_applications set status = 'invited', updated_at = now() where id = a.id and status = 'interviewed'
       and not exists (select 1 from interview_scores s where s.application_id = a.id);
    select * into a from job_applications where id = a.id;
  end if;
  return app.ai_interview_view(a, iv);
end $$;

