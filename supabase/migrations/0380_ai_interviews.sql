  select count(*) + 1 into n from app_events where code = 'applicant_invited' and entity_id = a.id;
  perform app.hiring_emit('applicant_invited', a, app.hiring_invite_vars(a), 'applicant_invited:' || a.id || ':' || n);
  insert into audit_log (actor_user_id, action, entity_table, entity_id, after) values (p_by, 'hiring_ai_live_call', 'job_applications', a.id::text, jsonb_build_object('status', a.status));
  return app.hiring_app_row(a);
end $$;

-- A new interview link (7 days from now): an expired link, or one the candidate lost. The answers given are kept.
create or replace function app.hiring_ai_new_link(p_by uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  a job_applications := app.hiring_lock(p_by, (p ->> 'id')::uuid);
  iv ai_interviews;
begin
  select * into iv from ai_interviews where application_id = a.id;
  if iv.id is null then
    if not exists (select 1 from hiring_roles r where r.id = a.role_id and r.remote and r.staff_kind = 'va') then raise exception 'The AI interview is for the remote assistant roles' using errcode = '23514'; end if;
  elsif iv.state in ('submitted', 'scored') then raise exception 'The interview is done already' using errcode = '23514';
  elsif iv.live_call_at is not null then raise exception 'A live call was offered instead' using errcode = '23514';
  end if;
  if a.status not in ('invited', 'below_bar', 'declined', 'referred', 'no_show', 'new') then raise exception 'A new link is for a candidate not interviewed yet (this one is %)', replace(a.status, '_', ' ') using errcode = '23514'; end if;
  update job_applications set status = 'invited', invited_at = coalesce(invited_at, now()), decided_at = null, decided_by = null, updated_at = now() where id = a.id returning * into a;
  perform app.ai_interview_send(a);
  insert into audit_log (actor_user_id, action, entity_table, entity_id, after) values (p_by, 'hiring_ai_new_link', 'job_applications', a.id::text, '{}'::jsonb);
  return app.hiring_app_row(a);
end $$;

-- the setting, from Hiring: {enabled}
create or replace function app.hiring_ai_settings(p_by uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
begin
  perform app.assert_admin(p_by);
  update program_settings set hiring_ai_interviews = coalesce((p ->> 'enabled')::boolean, hiring_ai_interviews),
         hiring_ai_interview_days = coalesce(nullif(p ->> 'days', '')::int, hiring_ai_interview_days)
   where id = (app.settings()).id;
  return jsonb_build_object('enabled', (app.settings()).hiring_ai_interviews, 'days', (app.settings()).hiring_ai_interview_days);
end $$;

alter function app.door(uuid, text, text, text, jsonb) rename to door_pre0380;
create function app.door(p_user uuid, p_aal text, p_call text, p_name text, p jsonb default '{}'::jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
begin
  if p_call = 'admin_do' and p_name in ('hiring_ai_live_call', 'hiring_ai_new_link', 'hiring_ai_settings') then
    perform app.door_begin(p_user, p_aal);
    return case p_name
      when 'hiring_ai_live_call' then app.hiring_ai_live_call(p_user, coalesce(p, '{}'::jsonb))
      when 'hiring_ai_new_link' then app.hiring_ai_new_link(p_user, coalesce(p, '{}'::jsonb))
      else app.hiring_ai_settings(p_user, coalesce(p, '{}'::jsonb)) end;
  end if;
  return app.door_pre0380(p_user, p_aal, p_call, p_name, p);
end $$;
