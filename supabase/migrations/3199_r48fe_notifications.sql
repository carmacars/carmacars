-- the reminder also goes by email, in CarmaCars' branding, to the person's own inbox
create function app.data_check_remind_email(p_user uuid, p_issues jsonb) returns void
language plpgsql security definer set search_path = public, app as $$
declare
  v_text text := left((select string_agg(x ->> 'message', ' ') from jsonb_array_elements(p_issues) x), 900);
  v_first text := coalesce((select nullif(split_part(btrim(u.full_name), ' ', 1), '') from users u where u.id = p_user), 'there');
  v_base text := rtrim((app.settings()).notify_base_url, '/');
  r renters;
  o owners;
begin
  if exists (select 1 from jsonb_array_elements(p_issues) x where x ->> 'audience' = 'staff') then
    perform app.emit_event('staff_data_check', 'user', p_user, jsonb_build_object('recipient_user_id', p_user, 'first_name', v_first, 'issues', v_text,
      'portal_url', v_base || '/staff'), 'staff_data_check:' || p_user || ':' || to_char(now(), 'YYYYMMDDHH24MI'));
  end if;
  select * into o from owners where user_id = p_user order by created_at limit 1;
  if o.id is not null and exists (select 1 from jsonb_array_elements(p_issues) x where x ->> 'audience' = 'owner') then
    perform app.emit_event('owner_data_check', 'owner', o.id, jsonb_build_object('owner_id', o.id, 'recipient_user_id', p_user, 'first_name', v_first, 'issues', v_text,
      'portal_url', v_base || '/owner'), 'owner_data_check:' || o.id || ':' || to_char(now(), 'YYYYMMDDHH24MI'));
  end if;
  select * into r from renters where user_id = p_user and not coalesce(is_owner_account, false) order by created_at limit 1;
  if r.id is not null and exists (select 1 from jsonb_array_elements(p_issues) x where x ->> 'audience' = 'renter') then
    perform app.emit_event('renter_data_check', 'renter', r.id, jsonb_build_object('renter_id', r.id, 'recipient_user_id', p_user, 'first_name', v_first, 'issues', v_text,
      'portal_url', v_base || '/account'), 'renter_data_check:' || r.id || ':' || to_char(now(), 'YYYYMMDDHH24MI'));
  end if;
end $$;

alter function app.data_check_remind(uuid, jsonb) rename to data_check_remind_pre3199;
create function app.data_check_remind(p_by uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare v jsonb := app.data_check_remind_pre3199(p_by, p);
begin
  perform app.data_check_remind_email(nullif(p ->> 'user', '')::uuid, app.data_checks_for(nullif(p ->> 'user', '')::uuid));
  return v || jsonb_build_object('emailed', true);
end $$;

alter function app.terms_decline(uuid, jsonb) rename to terms_decline_pre3199;
create function app.terms_decline(p_user uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare v jsonb := app.terms_decline_pre3199(p_user, p);
begin
  begin
    perform app.staff_alert('terms_declined', 'user', p_user, coalesce(p ->> 'version_id', 'x'),
      left(format('Declined: %s', coalesce((select t.title || ' ' || t.version from terms_versions t where t.id = nullif(p ->> 'version_id', '')::uuid), 'an updated document')), 140),
      left(format('%s declined it; their portal stays closed until they accept.', coalesce((select coalesce(nullif(btrim(u.full_name), ''), u.email) from users u where u.id = p_user), 'Someone')), 240),
      jsonb_build_object('path_admin', '/admin/settings/terms'));
  exception when others then raise warning 'terms declined alert: %', sqlerrm;
  end;
  return v;
end $$;

-- the fee waiting for its evidence: an alert to the role beside the To do
create function app.fee_evidence_alert() returns trigger
language plpgsql security definer set search_path = public, app as $$
begin
  if new.task_type = 'fee_evidence_needed' then
    begin
      perform app.staff_alert('fee_evidence_needed', 'tasks', new.id, new.id::text, left(new.title, 140), left(coalesce(new.detail, ''), 240),
        jsonb_build_object('path_admin', '/admin/todo', 'path_staff', '/staff/tasks'));
    exception when others then raise warning 'fee evidence alert: %', sqlerrm;
    end;
  end if;
  return null;
end $$;
drop trigger if exists fee_evidence_alert on tasks;
create trigger fee_evidence_alert after insert on tasks for each row when (new.task_type = 'fee_evidence_needed') execute function app.fee_evidence_alert();

revoke all on function app.data_check_remind_email(uuid, jsonb), app.data_check_remind_pre3199(uuid, jsonb), app.terms_decline_pre3199(uuid, jsonb), app.fee_evidence_alert() from public, anon, authenticated;
grant execute on function app.data_check_remind_email(uuid, jsonb), app.data_check_remind_pre3199(uuid, jsonb), app.terms_decline_pre3199(uuid, jsonb), app.fee_evidence_alert() to service_role;
