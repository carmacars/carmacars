-- The listing queue (0022). A job claimed by a worker that did not finish within
-- listing_job_lock_minutes goes back to the queue, or fails once it has used its attempts.
-- Jobs waiting out a back-off are left alone (app.claim_listing_jobs takes them when due); the
-- answer counts what is due now, for the worker (an Edge Function, because it calls the decode,
-- copy and photo providers).
create or replace function app.sweep_listing_jobs(p_now timestamptz default now()) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  ps program_settings := app.settings(app.local_date(p_now));
  j listing_jobs;
  v_requeued integer := 0;
  v_failed integer := 0;
  v_due integer;
begin
  for j in select * from listing_jobs x
            where x.status = 'running' and x.locked_at < p_now - make_interval(mins => ps.listing_job_lock_minutes)
            order by x.locked_at, x.id
              for update skip locked
  loop
    if j.attempts < j.max_attempts then
      update listing_jobs set status = 'queued', next_attempt_at = p_now, locked_at = null, locked_by = null,
             error = 'The worker did not finish within the lock time'
       where id = j.id;
      update photo_jobs set status = 'queued', next_attempt_at = p_now where id = j.photo_job_id and status = 'processing';
      update vehicle_photos set status = 'uploaded',
             background_status = case when background_status = 'processing' then 'pending' else background_status end
       where id = j.vehicle_photo_id and status = 'processing';
      v_requeued := v_requeued + 1;
    else
      perform app.fail_listing_job(j.id, 'The worker did not finish within the lock time', false, null, 0, p_now);
      v_failed := v_failed + 1;
    end if;
  end loop;
  select count(*) into v_due from listing_jobs where status = 'queued' and next_attempt_at <= p_now;
  return jsonb_build_object('requeued', v_requeued, 'failed', v_failed, 'due', v_due);
end $$;

-- Every 10 minutes.
create or replace function app.job_listing_sweep(p_now timestamptz default now()) returns text
language plpgsql security definer set search_path = public, app as $$
declare
  v_run uuid;
  v jsonb;
begin
  v_run := app.job_claim('listing-sweep', app.job_slot(p_now, 10));
  if v_run is null then return 'already_run'; end if;
  begin
    v := app.sweep_listing_jobs(p_now);
    perform app.job_succeed(v_run, v);
    return 'succeeded';
  exception when others then
    perform app.job_fail(v_run, sqlerrm);
    return 'failed';
  end;
end $$;

-- Publish later: an Admin or a customer service or fleet assistant sets the time (null clears it).
-- At that time the job publishes through app.publish_listing in that person's name, so every
-- check of an immediate publish applies.
create or replace function app.schedule_listing_publish(p_by uuid, p_vehicle uuid, p_at timestamptz) returns jsonb
language plpgsql security definer set search_path = public, app as $$
begin
  if not (app.user_is_admin(p_by) or app.user_va_has(p_by, 'cs', 'fleet')) then
    raise exception 'Only an Admin or a customer service or fleet assistant schedules a listing' using errcode = '42501';
  end if;
  if not exists (select 1 from vehicles where id = p_vehicle) then raise exception 'Vehicle not found' using errcode = 'P0002'; end if;
  if p_at is not null and p_at <= now() then
    raise exception 'Choose a time in the future, or publish now' using errcode = '22023';
  end if;
  perform app.ensure_listing(p_vehicle);
  update vehicle_listings set publish_at = p_at, publish_scheduled_by = case when p_at is not null then p_by end, publish_error = null
   where vehicle_id = p_vehicle;
  return jsonb_build_object('vehicle_id', p_vehicle, 'publish_at', p_at);
end $$;

-- Publish every listing whose publish_at has come. A listing that cannot be published keeps its
-- reason in publish_error, its time is cleared (so it is not tried every five minutes) and Fleet
-- gets the listing_failed task.
create or replace function app.publish_scheduled_listings(p_now timestamptz default now()) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  l vehicle_listings;
  v_ok integer := 0;
  v_failed integer := 0;
  v_msg text;
begin
  update vehicle_listings set publish_at = null, publish_scheduled_by = null
   where status = 'published' and publish_at is not null and publish_at <= p_now;
  for l in select * from vehicle_listings
            where publish_at is not null and publish_at <= p_now and status <> 'published'
            order by publish_at, id
  loop
    begin
      perform app.publish_listing(l.vehicle_id, l.publish_scheduled_by);
      update vehicle_listings set publish_at = null, publish_scheduled_by = null, publish_error = null where id = l.id;
      v_ok := v_ok + 1;
    exception when others then
      v_msg := sqlerrm;
      update vehicle_listings set publish_at = null, publish_error = v_msg where id = l.id;
      perform app.raise_task(p_type => 'listing_failed', p_title => format('Scheduled listing not published: %s', app.vehicle_name(l.vehicle_id)),
          p_detail => v_msg, p_vehicle => l.vehicle_id,
          p_dedupe => 'listing_failed:' || l.vehicle_id || ':scheduled:' || to_char(l.publish_at at time zone 'UTC', 'YYYYMMDDHH24MI'));
      v_failed := v_failed + 1;
    end;
  end loop;
  return jsonb_build_object('published', v_ok, 'failed', v_failed);
end $$;

-- Every 5 minutes.
create or replace function app.job_publish_listings(p_now timestamptz default now()) returns text
language plpgsql security definer set search_path = public, app as $$
declare
  v_run uuid;
  v jsonb;
