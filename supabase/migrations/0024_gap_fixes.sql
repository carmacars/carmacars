create or replace function app.notification_payload(p_code text, p_event app_events, p_to jsonb) returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare
  x jsonb := app.ntf_payload_base(p_code, p_event, p_to);
  li booking_line_items;
  b bookings;
  v_type text;
  v_label text;
begin
  if p_code = 'renter_extra_charge' and p_event.entity = 'booking_line_item' then
    select * into li from booking_line_items where id = p_event.entity_id;
    select * into b from bookings where id = li.booking_id;
    v_type := coalesce((select f.label from fee_types f where f.code = li.charge_type), initcap(replace(li.charge_type, '_', ' ')));
    v_label := coalesce(nullif(btrim(li.description), ''), v_type);
    x := x || jsonb_build_object(
      'charge_type', v_type,
      'charge_lines', jsonb_build_array(jsonb_build_object('label', v_label, 'amount', app.fmt_money(li.amount_cents)))
                      || case when li.hst_cents <> 0
                              then jsonb_build_array(jsonb_build_object('label', 'HST (' || app.fmt_pct(b.hst_bps) || ')', 'amount', app.fmt_money(li.hst_cents)))
                              else '[]'::jsonb end,
      'charge_total', app.fmt_money(li.amount_cents + li.hst_cents),
      'charge_reference', coalesce((select s.statement_number from booking_statements s where s.id = li.statement_id),
                                   b.booking_number || '-' || upper(left(li.id::text, 8))),
      'charge_summary', v_label || ' charged after your rental',
      'charge_event_date', app.fmt_date(li.created_at),
      'charged_to', 'your card on file',
      'payment_date', app.fmt_date(li.created_at));
  end if;
  return x;
end $$;

