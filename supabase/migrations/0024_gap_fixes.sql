-- ================================================================ 2. scheduled jobs
-- The slot a frequent job runs in, as a Toronto wall-clock key: one run per slot.
create or replace function app.job_slot(p_now timestamptz, p_minutes integer) returns text
language sql immutable as $$
  select to_char(to_timestamp(floor(extract(epoch from p_now) / (p_minutes * 60)) * (p_minutes * 60)) at time zone 'America/Toronto',
                 'YYYY-MM-DD"T"HH24:MI')
$$;

-- Daily from housekeeping_hour: remove rate limit counters nobody will read again (0019).
create or replace function app.job_rate_limit_purge(p_now timestamptz default now()) returns text
language plpgsql security definer set search_path = public, app as $$
declare
  v_day date := app.local_date(p_now);
  v_set program_settings := app.settings(app.local_date(p_now));
  v_run uuid;
  n integer;
begin
  if app.local_hour(p_now) < v_set.housekeeping_hour then return 'not_due'; end if;
  v_run := app.job_claim('rate-limit-purge', v_day::text);
  if v_run is null then return 'already_run'; end if;
  begin
    n := app.rate_limit_purge(make_interval(hours => v_set.rate_limit_keep_hours));
    perform app.job_succeed(v_run, jsonb_build_object('removed', n));
    return 'succeeded';
  exception when others then
    perform app.job_fail(v_run, sqlerrm);
    return 'failed';
  end;
end $$;

