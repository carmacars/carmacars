-- 0024: the gaps left by 0019 to 0023.
--
--   1. Scheduled jobs that existed as functions only, now run by pg_cron in the 0015 pattern:
--      rate limit counters purged, unpaid extensions lapsed, the listing queue swept, old form
--      drafts purged, and listings published at their publish_at time.
--   2. A post-rental charge line added by hand (by Finance, after the Check-in statement) emails
--      the renter once with renter_extra_charge; the notification payload can build it.
--   3. One flow for changing a confirmed booking: a calendar change that needs the renter's
--      agreement becomes a booking_change_requests row (source staff_calendar) and goes through
--      0019's approve, agree and apply functions; a calendar extension is priced by 0019.
--   4. The owner portal lists an owner's vehicles in a fixed order (the flaky test of 0022).
--
-- Runs last. No earlier migration is edited. See docs/changes/0024_gap_fixes.md.

