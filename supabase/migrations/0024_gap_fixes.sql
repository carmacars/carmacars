    return 'succeeded';
  exception when others then
    perform app.job_fail(v_run, sqlerrm);
    return 'failed';
  end;
end $$;

-- ================================================================ 3. hand-added post-rental charges
-- A charge line added by hand after the Check-in statement (Finance or an Admin inserting into
-- booking_line_items; the policy finance_insert of 0012) is told to the renter once. Lines made
-- by the functions are left alone: 0020's app.assess_check_in sets assessment_key (damage
-- through 0021's app.bill_damage too), 0021's app.charge_toll_ticket sets toll_ticket_id and
-- assessment_key and emits its own renter_extra_charge. A line added before the Check-in
-- statement goes on that statement (renter_final_statement), so it is not emailed on its own.
-- The supporting record is required (catalogue): a line without one is emailed when it is attached.
create or replace function app.manual_charge_after() returns trigger
language plpgsql security definer set search_path = public, app as $$
declare
  b bookings;
begin
  if new.assessment_key is not null or new.toll_ticket_id is not null or new.voided_at is not null
     or not new.charged_to_renter or new.amount_cents <= 0 or new.supporting_document_id is null
     or new.stage not in ('check_in', 'after_return') then
    return null;
  end if;
  if tg_op = 'UPDATE' and old.supporting_document_id is not null then return null; end if;
  select * into b from bookings where id = new.booking_id;
  if b.status not in ('returned', 'closed') then return null; end if;
  if not exists (select 1 from booking_statements s where s.booking_id = b.id and s.kind = 'check_in') then return null; end if;
  perform app.emit_event('renter_extra_charge', 'booking_line_item', new.id,
    jsonb_build_object('booking_id', b.id, 'booking_number', b.booking_number, 'renter_id', b.renter_id,
                       'charge_kind', 'manual', 'line_item_id', new.id, 'charge_type', new.charge_type,
                       'amount_cents', new.amount_cents, 'hst_cents', new.hst_cents, 'total_cents', new.amount_cents + new.hst_cents,
                       'document_ids', jsonb_build_array(new.supporting_document_id), 'charged_from', 'card_on_file'),
    'renter_extra_charge:' || new.id || ':manual');
  return null;
end $$;
drop trigger if exists booking_line_items_manual_charge_notify on booking_line_items;
create trigger booking_line_items_manual_charge_notify after insert or update of supporting_document_id on booking_line_items
  for each row execute function app.manual_charge_after();

