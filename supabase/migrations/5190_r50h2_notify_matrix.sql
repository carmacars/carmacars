-- the adjuster on the booking, else the insurer's billing contact (as app.send_insurer_invoice_email)
create function app.insurer_invoice_contact(p_invoice uuid) returns jsonb
language plpgsql stable security definer set search_path = public, app, pg_temp as $$
declare
  ii insurer_invoices;
  b bookings;
  v_email text;
  v_name text;
begin
  select * into ii from insurer_invoices where id = p_invoice;
  if ii.id is null then return null; end if;
  select * into b from bookings where id = ii.booking_id;
  v_email := nullif(btrim(coalesce(b.insurer_adjuster_email, '')), '');
  v_name := case when v_email is not null then nullif(btrim(coalesce(b.insurer_adjuster_name, '')), '') end;
  if v_email is null then
    select nullif(btrim(x.billing_email), ''), coalesce(nullif(btrim(x.billing_contact_name), ''), x.name) into v_email, v_name from insurers x where x.id = ii.insurer_id;
  end if;
  if v_email is null or v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then return null; end if;
  return jsonb_build_object('to_email', v_email, 'to_name', v_name);
end $$;

