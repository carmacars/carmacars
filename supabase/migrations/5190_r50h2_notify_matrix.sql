-- 5190 (R50 hotfix 2). The notification audit (the owner, Nov 27: "many notifications are missing"). The matrix of every
-- event, recipient and channel is scripts/notification-map.json (checked by scripts/check-notification-map.mjs) and the
-- change record docs/changes/2026-11-27-r50-hotfix2-notify.md; this migration adds the cells that were missing and fixes
-- the ones that went to the wrong person or at the wrong time. SCHEMA_MARKER is not changed.
--
-- From production (connector: list_comms of CC-10600, CC-10662/10673, CC-10663, CC-10664; site_health, Nov 27):
--   - Every email goes through Resend's free plan (provider "resend" on all of them; Amazon SES is on in Program settings but
--     has not sent: app.ses_email_left is 0 until the sender reports its keys). The daily limit of 100 was used up 60 times
--     in 24 hours: the request received, offer ready and "request waiting" emails waited until midnight (05:00 UTC) for
--     up to 12 hours. That is most of "missing". The fix is the SES keys on the server (in the report), not code.
--   - While emails wait for the limit, 0212 texts the booking-critical ones. Its list missed the messages a renter must act
--     on (a question about the request, the licence, a decline, a withdrawn offer, a cancellation by us, a proposed change,
--     an approved extension, the coverage proof, the return details). Added. Its texts went at once, also between 1 and
--     5 am: now only a message whose pickup or return is within 6 hours (or an urgent type, or a code) goes at night.
--   - A payment an insurer made on its invoice (app.record_insurer_payment) is a payment row of the booking, so the renter
--     got a "Receipt: $X paid" for money they never paid, and the insurer got nothing. Fixed: no renter receipt, no
--     "payment received" alert for it; the adjuster (or the insurer's billing contact) gets a receipt as Blind Spot Car
--     Rental (insurer_payment_received, never naming the platform) and Admin and Finance get the alert "Insurer invoice
--     paid".
-- Missing cells added (staff alerts: the bell, the phone and the person's email settings, as every alert rule):
--   - work_assigned: a To do or a lead someone else assigns to you (not the To do's the site routes by itself: those are
--     in the queue and the morning brief, the noise 5102 removed).
--   - bug_report_closed: the person who reported a bug hears when it is fixed or will not be fixed.
-- Every function patched refuses when the text it changes is not found; no applied migration is edited.
