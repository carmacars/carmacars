create function app.record_insurer_payment(p_invoice uuid, p_amount_cents bigint, p_by uuid default null, p_method text default 'bank_transfer',
                                           p_paid_at timestamptz default now(), p_reference text default null) returns text
language plpgsql security definer set search_path = public, app, pg_temp as $$
declare
  v_status text;
  ii insurer_invoices;
  v_to jsonb;
begin
  perform set_config('app.insurer_payment', 'on', true);
  v_status := app.record_insurer_payment_pre5190(p_invoice, p_amount_cents, p_by, p_method, p_paid_at, p_reference);
  perform set_config('app.insurer_payment', '', true);
  select * into ii from insurer_invoices where id = p_invoice;
  begin
    v_to := app.insurer_invoice_contact(ii.id);
    if v_to is not null and not app.booking_is_test(ii.booking_id) then
      perform app.emit_event('insurer_payment_received', 'insurer_invoice', ii.id,
        v_to || jsonb_build_object('insurer_id', ii.insurer_id, 'amount_cents', p_amount_cents, 'paid_cents', ii.paid_cents,
                                   'balance_cents', ii.total_cents - ii.paid_cents, 'paid_at', p_paid_at),
        'insurer_payment_received:' || ii.id || ':' || ii.paid_cents);
    end if;
    if not app.booking_is_test(ii.booking_id) then
      perform app.staff_alert('insurer_invoice_paid', 'insurer_invoice', ii.id, 'paid:' || ii.paid_cents,
        left(format('Insurer invoice %s %s: %s', ii.invoice_number, case when v_status = 'paid' then 'paid in full' else 'part paid' end, app.fmt_money(p_amount_cents)), 140),
        left(concat_ws('. ', (select x.name from insurers x where x.id = ii.insurer_id),
                       case when v_status <> 'paid' then 'Balance ' || app.fmt_money(ii.total_cents - ii.paid_cents) end), 240),
        jsonb_build_object('booking_id', ii.booking_id, 'path_admin', '/admin/insurer-invoices', 'path_staff', '/staff/money'));
    end if;
  exception when others then
    raise warning 'insurer payment notice not made for %: %', p_invoice, sqlerrm;
  end;
  return v_status;
end $$;
