-- Release 41 (2620): owners hear about a trip when it is complete, not when a booking comes in
-- (docs/changes/2026-11-12-r41-owner-trip-email.md). The owner, November 12: "Don't email owners when a booking comes in: a lot
-- of bookings get cancelled. Inform them when a booking is complete and the car comes back." And: a weekly summary for owners.
--
-- A. Off: owner_new_booking (a booking is confirmed), owner_booking_confirmed (an Owner Booking is confirmed) and
--    owner_booking_changed (a confirmed, upcoming booking is changed or moved to another car) are switched off in
--    notification_catalogue.is_enabled. The events are still recorded and are processed at once with the note "code disabled", so
--    nothing is emailed, texted, pushed or shown as a notice. The owner portal's own booking list and calendar are unchanged.
-- B. owner_trip_completed (email and in-app notice): sent once when a booking on the owner's car is returned (status returned,
--    or closed when it skips returned; check-out is the end of a booking). Only when the booking counts toward the owner's revenue
--    (app.booking_counts_for_owner, 2480) and the owner may see it (app.booking_owner_view is not unavailable, 0156); never for
--    Owner Bookings or Turo trips. Car, dates, days, kilometres driven when both odometers are recorded, the owner's share
--    (booking_splits.owner_payout_cents) only when the booking's revenue is shown to the owner (view full, not a flat monthly pay
--    car); otherwise the email says the amount shows on the next statement. Link: /owner/bookings/<number>.
-- C. owner_weekly_summary (email and in-app notice): app.job_owner_weekly, every 15 minutes (pg_cron), acts on Mondays from 9:00
--    Toronto time and handles each owner once a week (owner_weekly_summaries). Only when the owner had any activity. Per car: the
--    trips returned last week (Monday to Sunday) with dates and the owner's share, the confirmed bookings of the next 14 days (dates
--    only), the owner's share of the month so far from the owner's month to date (app.owner_month_to_date, 0151, provisional).
--    Program setting owner_weekly_summary_enabled (on by default).
-- No applied migration is edited: app.notification_payload is wrapped (ntf_payload_pre2620). SCHEMA_MARKER 2621 (2621 carries the guide chapters).
set local check_function_bodies = off;

create function pg_temp.copy_grants(p_new regprocedure, p_old regprocedure) returns void
language plpgsql as $$
declare g text;
begin
  execute format('revoke all on function %s from public, anon, authenticated', p_new);
  foreach g in array array['anon', 'authenticated', 'service_role'] loop
    if has_function_privilege(g, p_old, 'execute') then execute format('grant execute on function %s to %I', p_new, g); end if;
  end loop;
end $$;

