-- a booking that is part of the owner's revenue and shown to the owner, other than an Owner Booking or a Turo trip
create function app.owner_mail_booking(b bookings) returns boolean
language sql stable security definer set search_path = public, app as $$
  select b.owner_id is not null and b.booking_type::text <> 'owner' and coalesce(b.source, '') <> 'turo'
     and app.booking_counts_for_owner(b) and app.booking_owner_view(b) <> 'unavailable'
$$;

-- "Fri, Oct 23, 2026 to Mon, Oct 26, 2026" (one day: that day)
create function app.owner_trip_dates(b bookings) returns text
language sql stable security definer set search_path = public, app as $$
  select case when app.local_date(b.pickup_at) = app.local_date(b.return_at) then app.fmt_date(b.pickup_at)
              else app.fmt_date(b.pickup_at) || ' to ' || app.fmt_date(b.return_at) end
$$;

-- the owner's share of a trip, in cents, only when the owner may see it (0156 view full; a flat monthly pay car has none per trip)
create function app.owner_trip_share_cents(b bookings) returns bigint
language sql stable security definer set search_path = public, app as $$
  select case when app.booking_owner_view(b) = 'full' and not app.booking_flat(b.id) then s.owner_payout_cents end
    from booking_splits s where s.booking_id = b.id and s.status <> 'reversed'
$$;

create function app.ntf_owner_trip_completed() returns trigger
language plpgsql security definer set search_path = public, app as $$
begin
  if new.status::text in ('returned', 'closed') and old.status::text not in ('returned', 'closed') and app.owner_mail_booking(new) then
    perform app.ntf_emit('owner_trip_completed', 'booking', new.id, 'done', jsonb_build_object('booking_id', new.id, 'owner_id', new.owner_id));
  end if;
  return null;
end $$;
create trigger bookings_owner_trip_completed after update of status on bookings for each row execute function app.ntf_owner_trip_completed();

alter function app.notification_payload(text, app_events, jsonb) rename to ntf_payload_pre2620;
create function app.notification_payload(p_code text, p_event app_events, p_to jsonb) returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare
  x jsonb := app.ntf_payload_pre2620(p_code, p_event, p_to);
  b bookings;
  v_cents bigint;
  v_km integer;
begin
  if p_code <> 'owner_trip_completed' then return x; end if;
  select * into b from bookings where id = app.owner_event_booking(p_event.entity, p_event.entity_id, p_event.payload);
  if b.id is null then return x; end if;
  v_cents := app.owner_trip_share_cents(b);
  v_km := case when b.odometer_in_km is not null and b.odometer_out_km is not null and b.odometer_in_km >= b.odometer_out_km
               then b.odometer_in_km - b.odometer_out_km end;
  return x || jsonb_build_object(
    'booking_number', b.booking_number, 'vehicle_name', app.vehicle_name(b.vehicle_id), 'vehicle_id', b.vehicle_id::text,
    'pickup_date', app.fmt_date(b.pickup_at), 'return_date', app.fmt_date(b.return_at), 'billable_days', b.billable_days::text,
    'has_km', v_km is not null, 'km_driven', coalesce(app.fmt_km(v_km), ''),
    'show_amounts', v_cents is not null, 'owner_share', coalesce(app.fmt_money(v_cents), ''));
end $$;
select pg_temp.copy_grants('app.notification_payload(text, app_events, jsonb)'::regprocedure, 'app.ntf_payload_pre2620(text, app_events, jsonb)'::regprocedure);

-- ================================================================ C. the Monday email
create table owner_weekly_summaries (
  owner_id   uuid not null references owners (id) on delete cascade,
  week_of    date not null,                -- the Monday
  event_id   bigint,                       -- null: the owner had no activity
  created_at timestamptz not null default now(),
  primary key (owner_id, week_of)
);
comment on table owner_weekly_summaries is 'One row per owner and week once the Monday email was considered (2620): event_id is the email''s event, null when the owner had nothing to report.';
alter table owner_weekly_summaries enable row level security;
revoke all on owner_weekly_summaries from public, anon, authenticated;
grant select, insert, update, delete on owner_weekly_summaries to service_role;

-- the payload of one owner's Monday email, or null when there is nothing to report
create function app.owner_weekly_payload(p_owner uuid, p_now timestamptz default now()) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  v_today date := app.local_date(p_now);
  v_monday date := v_today - (extract(isodow from v_today)::integer - 1);
  v_from timestamptz := app.local_midnight(v_monday - 7);
  v_to timestamptz := app.local_midnight(v_monday);
  v_user uuid;
  v_mtd jsonb;
  v_mv jsonb;
  v_cars jsonb := '[]'::jsonb;
  v_trips jsonb;
  v_up jsonb;
  v_cents bigint;
  v_has_mtd boolean;
  c record;
begin
  select o.user_id into v_user from owners o where o.id = p_owner;
  if v_user is not null then
    begin
      v_mtd := app.owner_month_to_date(v_user, v_today);
    exception when others then
      v_mtd := null;
    end;
  end if;
  for c in select v.id, v.created_at from vehicles v where v.owner_id = p_owner order by v.created_at, v.id loop
    v_trips := coalesce((select jsonb_agg(jsonb_build_object('dates', app.owner_trip_dates(b),
                                  'share', coalesce(app.fmt_money(app.owner_trip_share_cents(b)), 'On your statement'))
                                  order by coalesce(b.checked_in_at, b.return_at), b.id)
                           from bookings b
                          where b.vehicle_id = c.id and b.status::text in ('returned', 'closed')
                            and coalesce(b.checked_in_at, b.return_at) >= v_from and coalesce(b.checked_in_at, b.return_at) < v_to
                            and app.owner_mail_booking(b)), '[]'::jsonb);
    v_up := coalesce((select jsonb_agg(jsonb_build_object('dates', app.owner_trip_dates(b)) order by b.pickup_at, b.id)
                        from bookings b
                       where b.vehicle_id = c.id and b.status::text = 'confirmed'
                         and b.pickup_at >= p_now and b.pickup_at < p_now + interval '14 days'
                         and app.owner_mail_booking(b)), '[]'::jsonb);
    v_mv := null;
    if v_mtd is not null and coalesce(v_mtd ->> 'final', 'false') <> 'true' and jsonb_typeof(v_mtd -> 'vehicles') = 'array' then
      select x into v_mv from jsonb_array_elements(v_mtd -> 'vehicles') x where x ->> 'vehicle_id' = c.id::text limit 1;
    end if;
    v_cents := case when v_mv is not null then coalesce((v_mv ->> 'owner_revenue_cents')::bigint, 0) - coalesce((v_mv ->> 'revenue_share_cents')::bigint, 0) end;
    v_has_mtd := v_mv is not null and coalesce((v_mv ->> 'owner_revenue_cents')::bigint, 0) <> 0;
    if jsonb_array_length(v_trips) = 0 and jsonb_array_length(v_up) = 0 and not v_has_mtd then continue; end if;
    v_cars := v_cars || jsonb_build_array(jsonb_build_object(
      'car_name', app.vehicle_name(c.id),
      'has_trips', jsonb_array_length(v_trips) > 0, 'trips', v_trips,
      'has_upcoming', jsonb_array_length(v_up) > 0, 'upcoming', v_up,
      'has_mtd', v_has_mtd, 'month_label', to_char(v_today, 'FMMonth'), 'month_share', coalesce(app.fmt_money(v_cents), '')));
  end loop;
  if jsonb_array_length(v_cars) = 0 then return null; end if;
  return jsonb_build_object('owner_id', p_owner, 'cars', v_cars,
    'week_label', to_char(v_monday - 7, 'Dy, Mon FMDD') || ' to ' || to_char(v_monday - 1, 'Dy, Mon FMDD, YYYY'));
end $$;

-- every 15 minutes: on Mondays from 9:00 Toronto time, each owner is considered once for the week
create function app.job_owner_weekly(p_now timestamptz default now()) returns integer
language plpgsql security definer set search_path = public, app as $$
declare
  v_local timestamp := p_now at time zone 'America/Toronto';
  v_monday date := (p_now at time zone 'America/Toronto')::date - (extract(isodow from p_now at time zone 'America/Toronto')::integer - 1);
  o record;
  pl jsonb;
  v_event bigint;
  n integer := 0;
begin
  if not coalesce((app.settings()).owner_weekly_summary_enabled, true) then return 0; end if;
  if extract(isodow from v_local) <> 1 or extract(hour from v_local) < 9 then return 0; end if;
  for o in select ow.id from owners ow left join users u on u.id = ow.user_id
            where exists (select 1 from vehicles v where v.owner_id = ow.id)
              and coalesce(nullif(ow.email, ''), u.email) is not null and coalesce(u.status::text, 'active') = 'active'
              and not exists (select 1 from owner_weekly_summaries w where w.owner_id = ow.id and w.week_of = v_monday)
            order by ow.id
  loop
    begin
      pl := app.owner_weekly_payload(o.id, p_now);
      v_event := case when pl is null then null else app.ntf_emit('owner_weekly_summary', 'owner', o.id, v_monday::text, pl) end;
      insert into owner_weekly_summaries (owner_id, week_of, event_id) values (o.id, v_monday, v_event) on conflict do nothing;
      if v_event is not null then n := n + 1; end if;
    exception when others then
      raise warning 'owner weekly summary %: %', o.id, sqlerrm;
    end;
  end loop;
  return n;
end $$;

do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'app' and p.proname = any (array['owner_mail_booking', 'owner_trip_dates', 'owner_trip_share_cents', 'ntf_owner_trip_completed',
                    'owner_weekly_payload', 'job_owner_weekly'])
  loop
    execute format('revoke all on function %s from public, anon, authenticated', f.sig);
    execute format('grant execute on function %s to service_role', f.sig);
  end loop;
end $$;

do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.schedule('carmacars-owner-weekly', '*/15 * * * *', $q$select app.job_owner_weekly()$q$);
  end if;
end $$;
