-- ================================================================ the values of the two notices
alter function app.notification_payload(text, app_events, jsonb) rename to ntf_payload_pre3152;
create function app.notification_payload(p_code text, p_event app_events, p_to jsonb) returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare x jsonb := app.ntf_payload_pre3152(p_code, p_event, p_to); v uuid;
begin
  if p_code in ('owner_car_photos_ready', 'staff_car_photos_ready') then
    v := coalesce(nullif(p_event.payload ->> 'vehicle_id', '')::uuid, p_event.entity_id);
    x := coalesce(x, '{}'::jsonb) || jsonb_build_object(
      'vehicle_id', v::text, 'vehicle_name', app.vehicle_name(v),
      'render_count', coalesce(p_event.payload ->> 'render_count', '9'),
      'owner_name', coalesce((select o.legal_name from owners o join vehicles c on c.owner_id = o.id where c.id = v), ''),
      '_url', (app.settings()).notify_base_url || case when p_code = 'owner_car_photos_ready' then '/owner/vehicles/' else '/staff/vehicles/' end || v);
  end if;
  return x;
end $$;
select pg_temp.copy_grants('app.notification_payload(text, app_events, jsonb)'::regprocedure, 'app.ntf_payload_pre3152(text, app_events, jsonb)'::regprocedure);

-- ================================================================ raised once per car and standard
create table if not exists photo_render_notified (
  vehicle_id uuid not null references vehicles (id) on delete cascade,
  spec       text not null,
  told_at    timestamptz not null default now(),
  primary key (vehicle_id, spec)
);
comment on table photo_render_notified is 'Release 48 AN (3152): the cars whose finished render set was told to the owner and Fleet (once per photo standard).';
alter table photo_render_notified enable row level security;
create policy admin_all on photo_render_notified for select to authenticated using (app.is_admin());
create trigger audit_photo_render_notified after insert or update or delete on photo_render_notified for each row execute function app.audit_row();
revoke all on table photo_render_notified from public, anon, authenticated;
grant select, insert, update, delete on table photo_render_notified to service_role;

create function app.photo_render_notices() returns integer
language plpgsql security definer set search_path = public, app as $$
declare r record; n integer := 0; v_spec text := app.photo_r48_spec();
begin
  for r in
    select v.id, v.owner_id,
           (select count(distinct ph.shot_type) from vehicle_photos ph where ph.vehicle_id = v.id and ph.r48 and ph.replaced_at is null
              and ph.status = 'approved' and ph.is_public and nullif(ph.processed_path, '') is not null) as live
      from vehicles v join vehicle_listings l on l.vehicle_id = v.id and l.status = 'published'
     where not coalesce(v.is_sample, false) and v.retired_at is null
       and not exists (select 1 from photo_render_notified t where t.vehicle_id = v.id and t.spec = v_spec)
       and app.photo_r48_car_done(v.id)
       and exists (select 1 from vehicle_photos ph where ph.vehicle_id = v.id and ph.r48 and ph.shot_type = 'left' and ph.replaced_at is null
                     and ph.status = 'approved' and ph.is_public and nullif(ph.processed_path, '') is not null)
     limit 50
  loop
    insert into photo_render_notified (vehicle_id, spec) values (r.id, v_spec) on conflict do nothing;
    perform app.emit_event('owner_car_photos_ready', 'vehicle', r.id, jsonb_build_object('vehicle_id', r.id, 'owner_id', r.owner_id, 'render_count', r.live::text),
      'owner_car_photos_ready:' || r.id || ':' || v_spec);
    perform app.emit_event('staff_car_photos_ready', 'vehicle', r.id, jsonb_build_object('vehicle_id', r.id, 'render_count', r.live::text),
      'staff_car_photos_ready:' || r.id || ':' || v_spec);
    n := n + 1;
  end loop;
  return n;
end $$;
revoke all on function app.photo_render_notices() from public, anon, authenticated;
grant execute on function app.photo_render_notices() to service_role;

alter function app.job_photo_r48() rename to job_photo_r48_pre3152;
create function app.job_photo_r48() returns text
language plpgsql security definer set search_path = public, app as $$
declare r text := app.job_photo_r48_pre3152(); n integer := app.photo_render_notices();
begin
  return r || case when n > 0 then format('; %s car(s) told their studio photos are live', n) else '' end;
end $$;
select pg_temp.copy_grants('app.job_photo_r48()'::regprocedure, 'app.job_photo_r48_pre3152()'::regprocedure);

