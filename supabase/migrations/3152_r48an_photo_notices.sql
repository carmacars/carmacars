-- Raised once per car and photo standard, when every view of the car's set is made and the side profile is on the site
-- (app.photo_render_notices, run by app.job_photo_r48 every 5 minutes). Cars whose set was already done before this
-- migration are marked as told (no flood of emails for photos that went live earlier).
-- SCHEMA_MARKER 3152. docs/changes/2026-11-20-r48-motion-covers-filters.md.
