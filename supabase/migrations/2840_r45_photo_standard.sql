-- ================================================================ 6. a real photo of an angle replaces its generated view
create function app.vehicle_photo_r45_real() returns trigger
language plpgsql security definer set search_path = public, app as $$
begin
  if not new.ai_generated and new.replaced_at is null and new.status <> 'rejected' and new.shot_type = any (app.photo_r45_angles()) then
    update vehicle_photos x set replaced_at = now(), is_public = false
     where x.vehicle_id = new.vehicle_id and x.shot_type = new.shot_type and x.ai_generated and x.replaced_at is null and x.id <> new.id;
  end if;
  return null;
end $$;
drop trigger if exists vehicle_photos_r45_real on vehicle_photos;
create trigger vehicle_photos_r45_real after insert or update of shot_type on vehicle_photos for each row execute function app.vehicle_photo_r45_real();

