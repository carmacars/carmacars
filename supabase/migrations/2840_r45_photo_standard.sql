-- the worker's context: the car named for Gemini on every photo step (a new upload's too)
alter function app.listing_job_context(uuid) rename to listing_job_context_pre2840;
create function app.listing_job_context(p_job uuid) returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare x jsonb := app.listing_job_context_pre2840(p_job);
begin
  if x is null or jsonb_typeof(x) <> 'object' or x ->> 'kind' not in ('process_photo', 'photo_r45') then return x; end if;
  if jsonb_typeof(x #> '{input,r45,car}') = 'object' then return x; end if;
  return jsonb_set(x, '{input}', coalesce(x -> 'input', '{}'::jsonb) || jsonb_build_object('r45', coalesce(x #> '{input,r45}', '{}'::jsonb)
    || jsonb_build_object('car', app.photo_r45_car((x ->> 'vehicle_id')::uuid))));
end $$;
