-- 2840_r45_photo_standard.sql
-- Release 45. The owner (Nov 14), after Release 44: the plates still wrong, the backgrounds not removed, many cars with only
-- one or two photos, an inside photo first, and the photos made with Cloudflare's cut-out still on the site "and they look
-- like shit": "use the photos directly and use Gemini to edit them directly". Then: every plate blurred, nothing drawn on it.
--
-- Why Release 44 changed nothing visible (the root causes):
--   a. "Redo with Gemini" made a photo again FROM ITS KEPT CLOUDFLARE CUT-OUT (photo_scene_queue sends the kept mask as an
--      edit): the car was still the segmenter's cut-out pasted in the drawn room, Gemini only relit that composite, so every
--      photo kept the Cloudflare look. Only a poor mask reached Gemini's background swap.
--   b. The job (job_photo_spec, every 20 minutes) took 4 photos a run, only outside photos, only those with a kept mask, each
--      once a standard; inside photos, photos without a mask and every interior were never made again.
--   c. Gemini's daily limit was 100 (at most 500 by the column's check), 10 kept back: about 90 photos a day for a fleet of
--      about 100 cars with several photos each, so weeks, and the limit stopped the rest.
--   d. A car with one or two photos never got its missing angles: the generated views (2200) were made only when a person
--      pressed Make, waited for a person to approve them, came after the real photos and were never the first photo.
--   e. A car with no outside photo on the site showed an inside photo first: nothing stopped it.
--
-- Release 45 (the web side: features/listing/r45.ts and worker.ts makeR45), one photo standard, r45.1:
--   1. app.photo_spec() 'r45.1'. Every listing photo is made by Gemini from the ORIGINAL upload (never a Cloudflare cut-out,
--      composite or transformation: the worker is given the local steps only). vehicle_photos.r45 records how each photo
--      stands (queued, done, flagged; tries, the check's reasons, the models, when).
--   2. A missing standard angle (r45.ts STANDARD_ANGLES: front three-quarter, front, side profile, rear three-quarter, rear,
--      dashboard, front seats, rear seats, trunk) is generated by Gemini from the car's own photos in the same room: a
--      vehicle_photos row with ai_generated true (Admin and fleet see the mark; the site does not need it), approved and on
--      the site once it passes the check, replaced by itself when a real photo of that angle arrives.
--   3. Job photo_r45 (one photo, two Gemini calls: the edit and the check): the database files the answer, tries again twice
--      on a refusal, then keeps the photo off the site and flags it; Gemini's daily limit or a quota waits without a try.
--   4. app.job_photo_r45 every 5 minutes until every car is at r45.1: newest listed cars first, within Gemini's daily limit
--      (Program settings listing_showroom_ai_daily, 2000 by default now) less a reserve for new uploads
--      (listing_photo_r45_reserve, 50). A photo at r45.1 is never made again unless a person asks.
--   5. Plates: blurred, never drawn (plate_auto, the editor, the carry-over: style blur).
-- The order and the first photo are 2841; the Admin view and the buttons 2842; the guides 2843.
-- SCHEMA_MARKER 2843. No applied migration is edited: functions are wrapped (_pre2840) or patched in place.
set local check_function_bodies = off;

create function pg_temp.copy_grants(p_new regprocedure, p_old regprocedure) returns void
language plpgsql as $$
declare g text;
begin
  execute format('revoke all on function %s from public, anon, authenticated', p_new);
  foreach g in array array['anon', 'authenticated', 'service_role'] loop
    if has_function_privilege(g, p_old, 'execute') then execute format('grant execute on function %s to %I', p_new, g); end if;
  end loop;
end $$;
create function pg_temp.patch_fn(p_sig regprocedure, p_old text, p_new text) returns void
language plpgsql as $$
declare d text := pg_get_functiondef(p_sig);
begin
  if position(p_old in d) = 0 then raise exception '2840: the text to change was not found in %: %', p_sig, left(p_old, 160); end if;
  execute replace(d, p_old, p_new);
end $$;

