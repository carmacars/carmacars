-- the car as the prompts name it
create function app.photo_r45_car(p_vehicle uuid) returns jsonb
language sql stable security definer set search_path = public, app as $$
  select jsonb_strip_nulls(jsonb_build_object('year', v.year, 'make', v.make, 'model', v.model, 'trim', v.trim, 'colour', v.colour)) from vehicles v where v.id = p_vehicle
$$;

-- a photo the standard applies to: a current photo shown on the site (not the odometer), of a real car, with an original
create function app.photo_r45_applies(ph vehicle_photos) returns boolean
language sql stable security definer set search_path = public, app as $$
  select ph.replaced_at is null and ph.status <> 'rejected' and nullif(ph.original_path, '') is not null
     and coalesce((select st.is_public from listing_shot_types st where st.code = ph.shot_type), false)
     and not coalesce((select v.is_sample from vehicles v where v.id = ph.vehicle_id), true)
$$;

-- not yet made to this standard (and not being made, nor flagged at it): a photo made by Cloudflare, an older standard, never made
create function app.photo_r45_due(ph vehicle_photos) returns boolean
language sql stable security definer set search_path = public, app as $$
  select app.photo_r45_applies(ph)
     and not (coalesce(ph.r45 ->> 'spec', '') = app.photo_spec() and coalesce(ph.r45 ->> 'state', '') in ('done', 'flagged', 'queued'))
$$;

-- the car's listing for the job (the newest)
create function app.photo_r45_intake(p_vehicle uuid) returns uuid
language sql stable security definer set search_path = public, app as $$
  select i.id from listing_intakes i where i.vehicle_id = p_vehicle order by i.created_at desc limit 1
$$;

-- ================================================================ 3. queueing
-- one real photo made again by Gemini from its original (p_force: also one at the standard already)
create function app.photo_r45_queue(p_by uuid, p_photo uuid, p_force boolean default false) returns boolean
language plpgsql security definer set search_path = public, app as $$
declare ph vehicle_photos; v_intake uuid; v_tries integer;
begin
  select * into ph from vehicle_photos where id = p_photo for update;
  if ph.id is null or not app.photo_r45_applies(ph) then return false; end if;
  if not p_force and not app.photo_r45_due(ph) then return false; end if;
  if exists (select 1 from listing_jobs j where j.vehicle_photo_id = ph.id and j.kind in ('photo_r45', 'process_photo') and j.status in ('queued', 'running')) then return false; end if;
  v_intake := coalesce(ph.intake_id, app.photo_r45_intake(ph.vehicle_id));
  if v_intake is null then return false; end if;
  v_tries := case when not p_force and coalesce(ph.r45 ->> 'spec', '') = app.photo_spec() then coalesce((ph.r45 ->> 'tries')::integer, 0) else 0 end;
  perform app.enqueue_listing_job(v_intake, 'photo_r45', ph.id, jsonb_build_object('r45', jsonb_build_object(
    'mode', case when ph.ai_generated then 'generate' else 'edit' end, 'car', app.photo_r45_car(ph.vehicle_id),
    'sources', case when ph.ai_generated then coalesce(ph.r45 -> 'sources', jsonb_build_array(ph.original_path)) end), 'by', p_by));
  update vehicle_photos set intake_id = coalesce(intake_id, v_intake),
         r45 = coalesce(r45, '{}'::jsonb) || jsonb_build_object('state', 'queued', 'spec', app.photo_spec(), 'tries', v_tries, 'at', now())
   where id = ph.id;
  return true;
end $$;

-- the photos a missing view is made from: up to three of the car's real photos, the same side first (r45.ts angleSources)
create function app.photo_r45_sources(p_vehicle uuid, p_shot text) returns text[]
language sql stable security definer set search_path = public, app as $$
  select coalesce(array_agg(x.original_path order by x.k), '{}') from (
    select ph.original_path, row_number() over (order by ((app.photo_rank(ph.shot_type) between 0 and 8) = (app.photo_rank(p_shot) between 0 and 8)) desc,
             coalesce(array_position(app.photo_r45_angles(), ph.shot_type), 50), ph.created_at, ph.id) as k
      from vehicle_photos ph
     where ph.vehicle_id = p_vehicle and not ph.ai_generated and app.photo_r45_applies(ph) and coalesce(ph.r45 ->> 'state', '') <> 'flagged'
       and app.photo_rank(ph.shot_type) < 30) x
   where x.k <= 3
$$;

-- the standard angles a car has no usable photo of (a flagged one is off the site, so it does not count)
create function app.photo_r45_missing(p_vehicle uuid) returns setof text
language sql stable security definer set search_path = public, app as $$
  select a from unnest(app.photo_r45_angles()) with ordinality u(a, k)
   where not exists (select 1 from vehicle_photos ph where ph.vehicle_id = p_vehicle and ph.shot_type = u.a and ph.replaced_at is null
                       and ph.status <> 'rejected' and coalesce(ph.r45 ->> 'state', '') <> 'flagged')
   order by k
$$;

-- one missing view generated: a new photo marked ai_generated, off the site until it is made and passes the check
create function app.photo_r45_generate(p_by uuid, p_vehicle uuid, p_shot text) returns uuid
language plpgsql security definer set search_path = public, app as $$
declare v_src text[] := app.photo_r45_sources(p_vehicle, p_shot); v_intake uuid := app.photo_r45_intake(p_vehicle); v_id uuid;
begin
  if cardinality(v_src) = 0 or v_intake is null or not (p_shot = any (app.photo_r45_angles())) then return null; end if;
  if coalesce((select v.is_sample from vehicles v where v.id = p_vehicle), true) then return null; end if;
  insert into vehicle_photos (vehicle_id, intake_id, angle, shot_type, original_path, status, is_public, background_status, ai_generated, sort_order,
                              scene, r45, uploaded_by)
  values (p_vehicle, v_intake, p_shot, p_shot, v_src[1], 'processing', false, 'processing', true, 100 + coalesce(array_position(app.photo_r45_angles(), p_shot), 50),
          case when app.photo_rank(p_shot) between 0 and 8 then 'showroom' end,
          jsonb_build_object('state', 'queued', 'spec', app.photo_spec(), 'tries', 0, 'at', now(), 'sources', to_jsonb(v_src)), p_by)
  returning id into v_id;
  perform app.enqueue_listing_job(v_intake, 'photo_r45', v_id, jsonb_build_object('r45', jsonb_build_object(
    'mode', 'generate', 'car', app.photo_r45_car(p_vehicle), 'sources', to_jsonb(v_src)), 'by', p_by));
  return v_id;
end $$;

-- a car to the standard: its photos that are due, then its missing angles; at most p_limit Gemini photos queued
create function app.photo_r45_plan(p_by uuid, p_vehicle uuid, p_limit integer, p_force boolean default false) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare r record; n integer := 0; g integer := 0; v_shot text;
begin
  if coalesce(p_limit, 0) <= 0 then return jsonb_build_object('queued', 0, 'generating', 0); end if;
  -- the primary photo first, then the order of the site
  for r in select ph.id from vehicle_photos ph
            where ph.vehicle_id = p_vehicle and not ph.ai_generated and app.photo_r45_applies(ph) and (p_force or app.photo_r45_due(ph))
            order by app.photo_rank(ph.shot_type), ph.sort_order, ph.created_at, ph.id loop
    exit when n + g >= p_limit;
    if app.photo_r45_queue(p_by, r.id, p_force) then n := n + 1; end if;
  end loop;
  -- generated views made before this standard (or asked again) are made again too
  for r in select ph.id from vehicle_photos ph
            where ph.vehicle_id = p_vehicle and ph.ai_generated and app.photo_r45_applies(ph) and (p_force or app.photo_r45_due(ph)) loop
    exit when n + g >= p_limit;
    if app.photo_r45_queue(p_by, r.id, p_force) then g := g + 1; end if;
  end loop;
  for v_shot in select app.photo_r45_missing(p_vehicle) loop
    exit when n + g >= p_limit;
    if app.photo_r45_generate(p_by, p_vehicle, v_shot) is not null then g := g + 1; end if;
  end loop;
  return jsonb_build_object('queued', n, 'generating', g);
end $$;

-- the fleet's photos waiting for Gemini right now
create function app.photo_r45_outstanding() returns integer
language sql stable security definer set search_path = public, app as $$
  select count(*)::integer from listing_jobs j where j.kind = 'photo_r45' and j.status in ('queued', 'running')
$$;

-- the cars in the order the job takes them: newest listed first
create function app.photo_r45_cars() returns table (vehicle_id uuid, listed_at timestamptz)
language sql stable security definer set search_path = public, app as $$
  select v.id, coalesce((select max(i.created_at) from listing_intakes i where i.vehicle_id = v.id), v.created_at)
    from vehicles v
   where not v.is_sample and exists (select 1 from listing_intakes i where i.vehicle_id = v.id)
     and exists (select 1 from vehicle_photos ph where ph.vehicle_id = v.id and not ph.ai_generated and ph.replaced_at is null and ph.status <> 'rejected')
   order by 2 desc, v.id
$$;

-- whether a car is at the standard: every photo done (or flagged: off the site) and no standard angle missing
create function app.photo_r45_car_done(p_vehicle uuid) returns boolean
language sql stable security definer set search_path = public, app as $$
  select not exists (select 1 from vehicle_photos ph where ph.vehicle_id = p_vehicle and app.photo_r45_applies(ph)
                       and not (coalesce(ph.r45 ->> 'spec', '') = app.photo_spec() and ph.r45 ->> 'state' in ('done', 'flagged')))
     and (not exists (select 1 from app.photo_r45_missing(p_vehicle)) or cardinality(app.photo_r45_sources(p_vehicle, 'front_left')) = 0)
$$;

-- ================================================================ 4. the job (every 5 minutes)
create function app.job_photo_r45() returns text
language plpgsql security definer set search_path = public, app as $$
declare ps program_settings := app.settings(); v_room integer; r record; x jsonb; n integer := 0; g integer := 0; v_cars integer := 0;
begin
  if not coalesce(ps.listing_photo_r45_auto, true) or not coalesce(ps.listing_showroom_ai, false) then return 'off'; end if;
  v_room := least(greatest(coalesce(ps.listing_photo_r45_batch, 12) - app.photo_r45_outstanding(), 0),
                  greatest(app.photo_gemini_left(coalesce(ps.listing_photo_r45_reserve, 50)) - app.photo_r45_outstanding(), 0));
  if v_room = 0 then return 'full or waiting for Gemini'; end if;
  for r in select c.vehicle_id from app.photo_r45_cars() c loop
    exit when n + g >= v_room;
    if app.photo_r45_car_done(r.vehicle_id) then continue; end if;
    x := app.photo_r45_plan(null, r.vehicle_id, v_room - n - g, false);
    n := n + (x ->> 'queued')::integer; g := g + (x ->> 'generating')::integer;
    if (x ->> 'queued')::integer + (x ->> 'generating')::integer > 0 then v_cars := v_cars + 1; end if;
  end loop;
  return format('%s photo(s) and %s generated view(s) queued on %s car(s)', n, g, v_cars);
end $$;

do $$
begin
  if to_regclass('cron.job') is not null then
    if exists (select 1 from cron.job where jobname = 'carmacars-photo-spec') then perform cron.unschedule('carmacars-photo-spec'); end if;
    perform cron.schedule('carmacars-photo-r45', '*/5 * * * *', 'select app.job_photo_r45()');
  end if;
end $$;

-- ================================================================ 5. the worker's answers
alter function app.worker_listing_result(uuid, jsonb) rename to worker_listing_result_pre2840;
create function app.worker_listing_result(p_job uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare j listing_jobs; r jsonb; v_ok boolean := coalesce((p ->> 'ok')::boolean, false); v_out jsonb := coalesce(p -> 'output', '{}'::jsonb);
        v_r jsonb := p #> '{output,r45}'; ph vehicle_photos; v_pass boolean; v_wait text := coalesce(p #>> '{output,gemini_wait}', p #>> '{output,r45,wait}');
        v_tries integer; v_plates jsonb; v_rec jsonb; v_status text;
begin
  select * into j from listing_jobs where id = p_job;
  r := app.worker_listing_result_pre2840(p_job, p);
  -- a fleet step that failed without an answer (the worker stopped): once its retries are used, made again later by the job
  -- (each such failure counts as a try, so a photo that always fails is flagged after three)
  if j.kind = 'photo_r45' and coalesce(jsonb_typeof(v_r), '') <> 'object' and (select status from listing_jobs where id = p_job) = 'failed' then
    update vehicle_photos set r45 = coalesce(r45, '{}'::jsonb) || jsonb_build_object('tries', coalesce((r45 ->> 'tries')::integer, 0) + 1, 'at', now(),
             'why', left(coalesce(p ->> 'error', 'the step failed'), 300),
             'state', case when coalesce((r45 ->> 'tries')::integer, 0) + 1 >= 3 then 'flagged' else 'redo' end)
     where id = j.vehicle_photo_id;
    update vehicle_photos set is_public = false where id = j.vehicle_photo_id and r45 ->> 'state' = 'flagged';
    return r;
  end if;
  if j.kind not in ('photo_r45', 'process_photo') or coalesce(jsonb_typeof(v_r), '') <> 'object' then return r; end if;
  select * into ph from vehicle_photos where id = j.vehicle_photo_id for update;
  if ph.id is null then return r; end if;
  v_pass := v_ok and coalesce((v_r ->> 'pass')::boolean, false) and nullif(v_out ->> 'processed_path', '') is not null;
  v_plates := case when jsonb_typeof(v_r -> 'plates') = 'array' then v_r -> 'plates' else '[]'::jsonb end;
  v_rec := jsonb_strip_nulls(jsonb_build_object('spec', app.photo_spec(), 'model', left(v_r ->> 'model', 80), 'check_model', left(v_r ->> 'check_model', 80),
             'view', left(v_r ->> 'view', 20), 'reasons', v_r -> 'reasons', 'why', left(v_r ->> 'why', 300), 'sources', ph.r45 -> 'sources', 'at', now()));

  if v_pass and j.kind = 'photo_r45' then
    if ph.replaced_at is not null then return r; end if;
    -- the version before is kept (a generated view has none)
    if ph.processed_path is not null then
      insert into vehicle_photo_versions (photo_id, version, processed_path, variants, preset_version, uncovered_path, plate_status, plate_boxes, plate_style, cutout, reason, created_by)
      values (ph.id, ph.edit_version, ph.processed_path, ph.variants, ph.preset_version, ph.uncovered_path, ph.plate_status, ph.plate_boxes, ph.plate_style, ph.cutout, 'r45', nullif(j.input ->> 'by', '')::uuid)
      on conflict (photo_id, version) do nothing;
    end if;
    v_status := case when ph.ai_generated or ph.status = 'approved' then 'approved' else ph.status end;
    update vehicle_photos set edit_version = edit_version + 1, processed_path = v_out ->> 'processed_path',
           variants = coalesce(v_out -> 'variants', '[]'::jsonb), width = nullif(v_out ->> 'width', '')::integer, height = nullif(v_out ->> 'height', '')::integer,
           preset_version = left(coalesce(v_out ->> 'preset_version', 'gemini_r45'), 40), provider = 'gemini', background_status = 'done',
           showroom = v_out -> 'showroom', quality_flags = '[]'::jsonb, cutout = null, uncovered_path = null, plate_carry = null, plate_suggestion = null,
           plate_status = case when jsonb_array_length(v_plates) > 0 then 'covered' else 'not_visible' end,
           plate_style = case when jsonb_array_length(v_plates) > 0 then 'blur' end, plate_boxes = v_plates, plate_checked_by = null, plate_checked_at = now(),
           plate_auto = jsonb_build_object('who', 'auto', 'decision', case when jsonb_array_length(v_plates) > 0 then 'blurred' else 'not_visible' end,
                                           'model', left(v_r ->> 'check_model', 80), 'path', v_out ->> 'processed_path', 'at', now()),
           status = v_status, is_public = (v_status = 'approved'), approved_at = case when v_status = 'approved' then coalesce(approved_at, now()) end,
           r45 = v_rec || jsonb_build_object('state', 'done', 'tries', coalesce((ph.r45 ->> 'tries')::integer, 0) + 1, 'generated', ph.ai_generated)
     where id = ph.id;
    return r;
  end if;

  if v_pass and j.kind = 'process_photo' then
    -- a new upload made by Gemini (the listing's own step filed the file): the plates blurred, no plate check left to do
    update vehicle_photos set plate_status = case when jsonb_array_length(v_plates) > 0 then 'covered' else 'not_visible' end,
           plate_style = case when jsonb_array_length(v_plates) > 0 then 'blur' end, plate_boxes = v_plates, plate_checked_at = now(), plate_checked_by = null,
           plate_auto = jsonb_build_object('who', 'auto', 'decision', case when jsonb_array_length(v_plates) > 0 then 'blurred' else 'not_visible' end,
                                           'model', left(v_r ->> 'check_model', 80), 'path', v_out ->> 'processed_path', 'at', now()),
           r45 = v_rec || jsonb_build_object('state', 'done', 'tries', 1, 'generated', false)
     where id = ph.id and processed_path is not distinct from (v_out ->> 'processed_path');
    delete from listing_jobs where vehicle_photo_id = ph.id and kind = 'plate_auto' and status = 'queued';
    return r;
  end if;

  -- not made: Gemini's daily limit or a quota waits for Gemini (no try counted)
  if v_wait in ('limit', 'quota') then
    if j.kind = 'photo_r45' then
      perform app.enqueue_listing_job(j.intake_id, 'photo_r45', ph.id, j.input);
      update listing_jobs set next_attempt_at = case when v_wait = 'limit' then app.local_midnight(app.local_date(now()) + 1) + interval '15 minutes' else now() + interval '10 minutes' end
       where vehicle_photo_id = ph.id and kind = 'photo_r45' and status = 'queued';
    elsif coalesce(j.input ->> 'engine', '') <> 'gemini' then
      -- (2780 already requeues the "Redo with Gemini" steps)
      update listing_jobs set status = 'queued', attempts = 0, error = left('Waiting for Gemini (' || v_wait || '): ' || coalesce(p ->> 'error', ''), 500),
             next_attempt_at = case when v_wait = 'limit' then app.local_midnight(app.local_date(now()) + 1) + interval '15 minutes' else now() + interval '10 minutes' end,
             locked_at = null, locked_by = null, finished_at = null
       where id = p_job and status = 'failed'
         and not exists (select 1 from listing_jobs o where o.id <> p_job and o.vehicle_photo_id = ph.id and o.kind = 'process_photo' and o.status in ('queued', 'running'));
    end if;
    update vehicle_photos set r45 = coalesce(r45, '{}'::jsonb) || v_rec || jsonb_build_object('state', 'queued', 'waiting', v_wait) where id = ph.id;
    return r;
  end if;
  if v_wait = 'no_key' then
    update vehicle_photos set r45 = coalesce(r45, '{}'::jsonb) || v_rec || jsonb_build_object('state', 'waiting', 'waiting', 'no_key') where id = ph.id;
    return r;
  end if;

  -- refused by the check (or not made): again, twice; then off the site and flagged, never published
  v_tries := coalesce((ph.r45 ->> 'tries')::integer, 0) + 1;
  if j.kind = 'photo_r45' and v_tries < 3 then
    update vehicle_photos set r45 = coalesce(r45, '{}'::jsonb) || v_rec || jsonb_build_object('state', 'queued', 'tries', v_tries) where id = ph.id;
    perform app.enqueue_listing_job(j.intake_id, 'photo_r45', ph.id, j.input);
    update listing_jobs set next_attempt_at = now() + interval '2 minutes' where vehicle_photo_id = ph.id and kind = 'photo_r45' and status = 'queued';
    return r;
  end if;
  if j.kind = 'process_photo' and (select status from listing_jobs where id = p_job) <> 'failed' then
    -- the listing's own step tries again by itself
    update vehicle_photos set r45 = coalesce(r45, '{}'::jsonb) || v_rec || jsonb_build_object('state', 'queued', 'tries', v_tries) where id = ph.id;
    return r;
  end if;
  update vehicle_photos set is_public = false,
         status = case when ai_generated then 'processed' else status end,
         quality_flags = case when quality_flags ? 'r45_flagged' then quality_flags else quality_flags || '["r45_flagged"]'::jsonb end,
         r45 = coalesce(r45, '{}'::jsonb) || v_rec || jsonb_build_object('state', 'flagged', 'tries', v_tries)
   where id = ph.id;
  return r;
end $$;
