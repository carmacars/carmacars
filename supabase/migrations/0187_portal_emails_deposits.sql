-- ================================================================ 5. the conversation on the screen
-- p: booking. The messages written on the booking (staff and renter, both ways; the adjuster's too), each email of the
-- booking from the outbox (what, to whom, from which sender, its state), the quick replies, today's email use, and
-- what may be chosen: the adjuster and the Blind Spot Car Rental sender on an insurer-billed booking. Fleet sees the
-- renter's first name only, as on its booking screen (0031), never the renter's address.
create or replace function app.booking_conversation(p_by uuid, p jsonb) returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare
  b bookings;
  r renters;
  v_problem text;
  v_fleet boolean;
  v_usage jsonb := app.email_usage(now());
begin
  select * into b from bookings where id::text = p ->> 'booking' or booking_number = p ->> 'booking';
  v_problem := app.booking_email_problem(p_by, b);
  if v_problem is not null then raise exception '%', v_problem using errcode = case when b.id is null then 'P0002' else '42501' end; end if;
  v_fleet := not app.user_is_admin(p_by) and app.va_active_fn(p_by) = 'fleet';
  select * into r from renters where id = b.renter_id;
  return jsonb_build_object(
    'booking', b.booking_number, 'booking_id', b.id, 'status', b.status, 'bill_to', b.bill_to,
    'insurer_billed', app.booking_insurer_billed(b),
    'insurer_name', (select i.name from insurers i where i.id = b.insurer_id), 'claim_number', b.insurer_claim_number,
    'renter', case when r.id is not null then jsonb_build_object(
        'name', case when v_fleet then split_part(btrim(coalesce(r.legal_name, '')), ' ', 1) else r.legal_name end,
        'email', case when v_fleet then null else coalesce(nullif(r.email, ''), (select u.email from users u where u.id = r.user_id)) end) end,
    'adjuster', case when app.booking_insurer_billed(b) then jsonb_build_object(
        'name', b.insurer_adjuster_name, 'email', nullif(btrim(coalesce(b.insurer_adjuster_email, '')), '')) end,
    'messages', coalesce((select jsonb_agg(jsonb_build_object(
        'id', m.id, 'direction', m.direction, 'channel', m.channel, 'subject', m.subject, 'body', m.body, 'at', m.occurred_at,
        'by', case when m.direction = 'inbound' then coalesce(split_part(btrim(r.legal_name), ' ', 1), 'Renter') else coalesce((select u.full_name from users u where u.id = m.sent_by), 'CarmaCars') end,
        'from', m.from_address,
        'to', case when v_fleet and m.to_address is not distinct from r.email then null else m.to_address end,
        'adjuster', m.direction = 'outbound' and m.channel = 'email' and m.to_address is not null and m.to_address = lower(btrim(coalesce(b.insurer_adjuster_email, ''))))
        order by m.occurred_at desc)
      from (select * from messages x
             where x.booking_id = b.id and x.channel in ('portal', 'email', 'sms', 'whatsapp')
               and x.related_table is distinct from 'tasks' and x.related_table is distinct from 'notification_outbox'
               and coalesce(x.template_code, '') <> 'T7'
             order by x.occurred_at desc limit 100) m), '[]'::jsonb),
    'emails', coalesce((select jsonb_agg(jsonb_build_object(
        'id', o.id, 'code', o.code, 'subject', app.render_text(c.subject, o.payload),
        'to', case when v_fleet and o.audience = 'renter' then null else o.to_address end, 'audience', o.audience,
        'from', c.from_address, 'status', o.status, 'reason', o.status_reason, 'at', o.created_at, 'sent_at', o.sent_at)
        order by o.created_at desc)
      from (select * from notification_outbox x where x.booking_id = b.id and x.audience not like 'staff\_%' order by x.created_at desc limit 100) o
      join notification_catalogue c on c.code = o.code), '[]'::jsonb),
    'quick_replies', coalesce((select jsonb_agg(jsonb_build_object('id', q.id, 'title', q.title, 'body', q.body) order by q.sort_order, q.title)
      from quick_replies q where q.is_active and q.audience in ('renter', 'any')), '[]'::jsonb),
    'usage', jsonb_build_object('total', (v_usage ->> 'total')::integer, 'cap', (v_usage ->> 'cap')::integer));
end $$;

-- ================================================================ 6. deposits due back
-- The deposits with something still to give back and the day it is due: release_due_on (7 business days after the
-- check-in, 0011), or, with no check-in recorded on a returned booking, deposit_release_reminder_days business days
-- after the return.
create or replace function app.deposit_release_reminders(p_now timestamptz default now())
returns table (deposit_id uuid, booking_id uuid, booking_number text, vehicle_id uuid, renter_id uuid, balance_cents bigint, due_on date, from_return boolean)
language sql stable security definer set search_path = public, app as $$
  select d.id, b.id, b.booking_number, b.vehicle_id, b.renter_id,
         d.amount_cents - d.applied_cents - d.released_cents - d.held_back_cents,
         coalesce(d.release_due_on, app.add_business_days(app.local_date(coalesce(b.checked_in_at, b.return_at)),
                                                         (app.settings(app.local_date(p_now))).deposit_release_reminder_days)),
         d.release_due_on is null
    from deposits d join bookings b on b.id = d.booking_id
   where d.status in ('held', 'captured')
     and d.amount_cents - d.applied_cents - d.released_cents - d.held_back_cents > 0
     and (d.release_due_on is not null or b.status::text in ('returned', 'closed'))
$$;

-- deposits-due, daily from 06:00 (0020, same signature): one release task per deposit (Finance; an Admin works every queue),
-- raised the warning window before its day, now also for a deposit with no release date; on the day and after, an in-app
-- notice to Finance and the Admins (once per deposit and due day). The hold-backs as 0020.
create or replace function app.job_deposits_due(p_now timestamptz default now()) returns text
language plpgsql security definer set search_path = public, app as $$
declare
  v_day date := app.local_date(p_now);
  v_set program_settings := app.settings(app.local_date(p_now));
  v_run uuid;
  r record;
  u record;
  v_due integer := 0; v_overdue integer := 0; v_hold integer := 0; v_notices integer := 0;
begin
  if app.local_hour(p_now) < 6 then return 'not_due'; end if;
  v_run := app.job_claim('deposits-due', v_day::text);
  if v_run is null then return 'already_run'; end if;
  begin
    for r in select * from app.deposit_release_reminders(p_now) x
              where x.due_on <= app.add_business_days(v_day, v_set.deposit_due_warning_business_days)
    loop
      perform app.raise_task(p_type => 'release_deposit',
          p_title => format('Release the deposit for %s: %s, due %s', r.booking_number, app.money_text(r.balance_cents), app.fmt_day(r.due_on)),
          p_detail => case when r.due_on < v_day then 'OVERDUE. Settle the deposit on the booking''s Money tab: apply what is owed, hold back what an open item needs, release the rest.'
                           else 'Settle the deposit on the booking''s Money tab: apply what is owed, hold back what an open item needs, release the rest.' end
                      || case when r.from_return then ' No check-in was recorded: the date is counted from the return.' else '' end,
          p_booking => r.booking_id, p_vehicle => r.vehicle_id, p_renter => r.renter_id, p_related_table => 'deposits', p_related_id => r.deposit_id,
          p_due_at => app.local_midnight(r.due_on + 1),
          p_priority => case when r.due_on <= v_day then 'urgent' else 'high' end, p_dedupe => 'release_deposit:' || r.deposit_id);
      v_due := v_due + 1;
      if r.due_on < v_day then v_overdue := v_overdue + 1; end if;
      if r.due_on <= v_day then
        for u in select distinct x.id, x.admin from (
                   select us.id, true as admin from users us join user_roles ur on ur.user_id = us.id and ur.role = 'admin' where us.status = 'active'
                   union all
                   select us.id, false from users us join user_roles ur on ur.user_id = us.id and ur.role = 'va'
                     join staff_profiles sp on sp.user_id = us.id and sp.staff_type = 'va' and sp.is_active
                    where us.status = 'active' and 'finance'::va_function = any (array[sp.va_function] || coalesce(sp.cover_functions, '{}'))) x
                  where not exists (select 1 from user_roles ar where ar.user_id = x.id and ar.role = 'admin') or x.admin
        loop
          insert into notifications (user_id, code, title, body, url, entity, entity_id, dedupe_key)
          values (u.id, 'staff_deposit_release_due',
                  format('Release the deposit for %s', r.booking_number),
                  format('%s due back %s%s. Settle it on the booking''s Money tab.', app.money_text(r.balance_cents),
                         case when r.due_on < v_day then 'since ' else 'by ' end, app.fmt_day(r.due_on)),
                  v_set.notify_base_url || case when u.admin then '/admin/bookings/' else '/va/bookings/' end || r.booking_number || '?tab=money',
                  'deposits', r.deposit_id, 'staff_deposit_release_due:' || r.deposit_id || ':' || r.due_on || '|' || u.id)
          on conflict (dedupe_key) do nothing;
          if found then v_notices := v_notices + 1; end if;
        end loop;
      end if;
    end loop;
    for r in select d.id, d.booking_id, d.held_back_cents, d.held_back_until, d.held_back_reason, b.booking_number, b.vehicle_id, b.renter_id
               from deposits d join bookings b on b.id = d.booking_id
              where d.held_back_cents > 0 and d.held_back_until is not null
                and d.held_back_until <= v_day + v_set.holdback_warning_days
    loop
      perform app.raise_task(p_type => 'settle_holdback',
          p_title => format('Booking %s: %s held back until %s', r.booking_number, app.money_text(r.held_back_cents), r.held_back_until),
          p_detail => format('Held back for: %s. Apply it or release it by that day.', r.held_back_reason),
          p_booking => r.booking_id, p_vehicle => r.vehicle_id, p_renter => r.renter_id, p_related_table => 'deposits', p_related_id => r.id,
          p_due_at => app.local_midnight(r.held_back_until + 1),
          p_priority => case when r.held_back_until <= v_day then 'urgent' else 'high' end, p_dedupe => 'settle_holdback:' || r.id);
      v_hold := v_hold + 1;
    end loop;
    perform app.job_succeed(v_run, jsonb_build_object('day', v_day, 'deposits_due', v_due, 'overdue', v_overdue, 'holdbacks_due', v_hold, 'notices', v_notices));
    return 'succeeded';
  exception when others then
    perform app.job_fail(v_run, sqlerrm);
    return 'failed';
  end;
end $$;

-- The release task closes by itself once nothing is left to give back, however the deposit was settled (the guided
-- settlement, kept whole against charges, given back another way, carried forward to the next booking, or failed).
create or replace function app.deposit_release_done() returns trigger
language plpgsql security definer set search_path = public, app as $$
begin
  if new.status in ('settled', 'carried_forward', 'failed')
     or new.amount_cents - new.applied_cents - new.released_cents - new.held_back_cents <= 0 then
    perform app.resolve_tasks(array['release_deposit'], new.booking_id, null,
      case when new.status = 'carried_forward' then 'Deposit carried forward' when new.status = 'failed' then 'Deposit failed'
           else 'Deposit settled' end);
  end if;
  return null;
end $$;
drop trigger if exists deposits_release_done on deposits;
create trigger deposits_release_done after update on deposits
  for each row execute function app.deposit_release_done();

