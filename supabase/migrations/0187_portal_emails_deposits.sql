-- ================================================================ 7. the door
alter function app.door(uuid, text, text, text, jsonb) rename to door_pre0187;
create function app.door(p_user uuid, p_aal text, p_call text, p_name text, p jsonb default '{}'::jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  p_ jsonb := coalesce(p, '{}'::jsonb) - '_va';
begin
  if (p_call = 'ops_do' and p_name = 'booking_email') or (p_call = 'ops_read' and p_name = 'booking_conversation') then
    if coalesce(p, '{}'::jsonb) ? '_va' then perform set_config('app.va_active', coalesce(p ->> '_va', ''), true); end if;
    perform app.door_begin(p_user, p_aal);
    return case p_name when 'booking_email' then app.booking_email_send(p_user, p_) else app.booking_conversation(p_user, p_) end;
  end if;
  return app.door_pre0187(p_user, p_aal, p_call, p_name, p);
end $$;
select pg_temp.copy_grants('app.door(uuid, text, text, text, jsonb)'::regprocedure, 'app.door_pre0187(uuid, text, text, text, jsonb)'::regprocedure);

