-- ================================================================ 3. who may write, and from which sender
-- Staff who may email from a booking: an Admin, or an assistant in customer service, Sales, Fleet or Finance (Sales only
-- while the booking is a request or an offer, as the booking screen). Null when they may.
create or replace function app.booking_email_problem(p_by uuid, b bookings) returns text
language sql stable security definer set search_path = public, app as $$
  select case
    when b.id is null then 'Booking not found'
    when app.user_is_admin(p_by) then null
    when not app.user_va_has(p_by, 'cs', 'sales', 'fleet', 'finance') then 'Only an Admin or an assistant emails the renter'
    when app.va_active_fn(p_by) = 'sales' and b.status::text not in ('requested', 'offered') then 'Sales works on requests and offers only'
  end
$$;

-- An insurer pays all or part of the booking: the Blind Spot Car Rental sender and the adjuster are offered.
create or replace function app.booking_insurer_billed(b bookings) returns boolean
language sql stable as $$
  select coalesce(b.bill_to, 'renter') <> 'renter' and b.insurer_id is not null
$$;

-- ================================================================ 4. send
-- p: booking (id or number), to ('renter' or 'adjuster'), sender ('carmacars' or 'blindspot'), subject, body.
-- The message is kept on the booking (messages, with who sent it and from which address) and in its history; the email
-- is an event like any other, so it waits in the outbox under the daily limit at the customer priority.
--   to the renter, as CarmaCars: renter_staff_message (0033's email; the renter also sees it in their account)
--   to the renter, as Blind Spot Car Rental (insurer-billed only): insurance_staff_message (also in their account)
--   to the adjuster (insurer-billed, with the adjuster's email on the booking): insurance_staff_message, always Blind Spot
create or replace function app.booking_email_send(p_by uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  b bookings;
  r renters;
  v_problem text;
  v_to text := coalesce(nullif(btrim(p ->> 'to'), ''), 'renter');
  v_sender text := coalesce(nullif(btrim(p ->> 'sender'), ''), 'carmacars');
  v_subject text := btrim(coalesce(p ->> 'subject', ''));
  v_body text := btrim(coalesce(p ->> 'body', ''));
  v_from text;
  v_address text;
  v_name text;
  v_id uuid;
  v_code text;
begin
  select * into b from bookings where id::text = p ->> 'booking' or booking_number = p ->> 'booking';
  v_problem := app.booking_email_problem(p_by, b);
  if v_problem is not null then raise exception '%', v_problem using errcode = case when b.id is null then 'P0002' else '42501' end; end if;
  if v_to not in ('renter', 'adjuster') then raise exception 'Email the renter or the adjuster' using errcode = '22023'; end if;
  if v_sender not in ('carmacars', 'blindspot') then raise exception 'Send as CarmaCars or as Blind Spot Car Rental' using errcode = '22023'; end if;
  if v_subject = '' then raise exception 'Write the subject' using errcode = '22023'; end if;
  if length(v_subject) > 150 then raise exception 'Keep the subject under 150 characters' using errcode = '22023'; end if;
  v_problem := app.staff_message_problem(v_body);
  if v_problem is not null then raise exception '%', v_problem using errcode = '23514'; end if;
  -- the daily limit is shared by every email of the account: a runaway on one booking is stopped
  if (select count(*) from messages m where m.booking_id = b.id and m.direction = 'outbound' and m.sent_by is not null
        and m.channel in ('portal', 'email') and m.occurred_at >= app.local_midnight(app.today())) >= 20 then
    raise exception 'Twenty emails on this booking today already: call instead, or write tomorrow' using errcode = '23514';
  end if;

  if v_to = 'adjuster' then
    if not app.booking_insurer_billed(b) then raise exception 'This booking is not billed to an insurer' using errcode = '23514'; end if;
    v_address := lower(nullif(btrim(coalesce(b.insurer_adjuster_email, '')), ''));
    if v_address is null then raise exception 'Add the adjuster''s email to the booking first (Insurance claim)' using errcode = '23514'; end if;
    v_sender := 'blindspot';
    v_name := nullif(btrim(coalesce(b.insurer_adjuster_name, '')), '');
  else
    select * into r from renters where id = b.renter_id;
    if r.id is null then raise exception 'This booking has no renter to write to' using errcode = '23514'; end if;
    if v_sender = 'blindspot' and not app.booking_insurer_billed(b) then
      raise exception 'Blind Spot Car Rental writes only about a booking billed to an insurer' using errcode = '23514';
    end if;
    v_address := lower(nullif(btrim(coalesce(nullif(r.email, ''), (select u.email from users u where u.id = r.user_id), '')), ''));
    if v_address is null then raise exception 'The renter has no email address' using errcode = '23514'; end if;
    v_name := r.legal_name;
  end if;
  v_from := case v_sender when 'blindspot' then 'Blind Spot Car Rental <blindspotcarrental@carmacars.ca>' else 'CarmaCars <bookings@carmacars.ca>' end;
  v_code := case when v_sender = 'carmacars' then 'renter_staff_message' else 'insurance_staff_message' end;

  -- the renter's messages are in their account (portal); the adjuster's are kept as email, out of the renter's view
  insert into messages (direction, channel, subject, body, to_address, from_address, user_id, renter_id, booking_id, vehicle_id, sent_by, status)
  values ('outbound', case when v_to = 'adjuster' then 'email' else 'portal' end, v_subject, left(v_body, 4000), v_address, v_from,
          case when v_to = 'renter' then r.user_id end, b.renter_id, b.id, b.vehicle_id, p_by, 'delivered')
  returning id into v_id;

  insert into booking_events (booking_id, kind, from_status, to_status, note, details, actor_type, actor_user_id)
  values (b.id, 'staff_email', b.status::text, b.status::text,
          format('Email to the %s, from %s: %s', case when v_to = 'adjuster' then 'adjuster' else 'renter' end,
                 case when v_sender = 'blindspot' then 'Blind Spot Car Rental' else 'CarmaCars' end, v_subject),
          jsonb_build_object('message_id', v_id, 'to', v_to, 'sender', v_sender, 'address', v_address, 'code', v_code),
          'staff', p_by);

  perform app.ntf_emit(v_code, 'message', v_id, 'sent',
    jsonb_build_object('booking_id', b.id, 'renter_id', b.renter_id, 'to', v_to, 'email', v_address, 'name', v_name,
                       'user_id', case when v_to = 'renter' then r.user_id end));
  if v_to = 'renter' then
    perform app.resolve_tasks(array['renter_message'], b.id, p_by, 'Replied by email', false);
  end if;
  return jsonb_build_object('id', v_id, 'code', v_code, 'to', v_to, 'sender', v_sender, 'address', v_address);
end $$;

