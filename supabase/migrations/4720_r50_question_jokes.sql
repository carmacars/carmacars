-- 4720 (release 50; docs/releases/r50.md, docs/changes/2026-11-24-r50-question-jokes.md): the Academy's funny wrong answers
-- are written for their own question. 4200 gave every question one joke from a shared bank, so most jokes had nothing to do
-- with their question. Now:
--  - only about one question in three carries a joke: those where a light, obviously wrong answer to that very question fits.
--    Serious questions (safety, legal, money, ID, damage, insurance) carry none;
--  - each joke is a line of web/src/features/academy/jokes-by-question.json, keyed by "<section slug>:<sort>" and tied to the
--    question's prompt (md5): generated below into app.academy_question_joke_line() by supabase/seed/4200_gen_academy.mjs;
--  - the trigger of 4200 no longer adds a bank joke. On every save it takes out any bank joke and the question's last joke, then
--    adds the question's own line, if it has one, at a pseudo-random place and moves the right answer's index with it. A new
--    question, or one whose prompt changed, gets no joke until a line is written for it. academy_questions.joke names it.
--  - the quiz hands out the shown position of the joke (academy_quiz_start: questions[].joke) for its playful line, and the
--    Admin editor reads academy_questions.joke (academy_content).
-- The right answers are unchanged: the right answer keeps pointing at the same option text. SCHEMA_MARKER stays 5011 (the highest).

alter table academy_questions add column if not exists joke text;
comment on column academy_questions.joke is '4720: the funny wrong option this question carries (its own line of jokes-by-question.json), or null: always wrong, set by the trigger app.academy_questions_joke().';

