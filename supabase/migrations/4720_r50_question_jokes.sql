create or replace function app.academy_questions_joke() returns trigger
language plpgsql security definer set search_path = public, app, pg_temp as $$
declare
  v_strip text[] := app.academy_joke_bank();
  v_slug text;
  v_joke text;
  v_len integer;
  v_pos integer;
  v_plain jsonb;
  v_ans integer;
begin
  if jsonb_typeof(new.options) <> 'array' then return new; end if;
  -- take out what was a joke: a 4200 bank joke, the question's last joke
  if tg_op = 'UPDATE' and old.joke is not null then v_strip := v_strip || old.joke; end if;
  if new.joke is not null then v_strip := v_strip || new.joke; end if;
  if (new.options ->> new.answer) = any (v_strip) then raise exception 'The right answer cannot be a joke' using errcode = '22023'; end if;
  select coalesce(jsonb_agg(e.v order by e.i), '[]'::jsonb), (count(*) filter (where e.i - 1 < new.answer))::integer
    into v_plain, v_ans
    from jsonb_array_elements(new.options) with ordinality e(v, i)
   where not (jsonb_typeof(e.v) = 'string' and (e.v #>> '{}') = any (v_strip));
  new.options := v_plain;
  new.answer := v_ans;
  new.joke := null;
  -- the question's own line, only while its prompt is the one the line was written for
  select s.slug into v_slug from academy_sections s where s.id = new.section_id;
  v_joke := app.academy_question_joke_line(v_slug || ':' || new.sort, new.prompt);
  v_len := jsonb_array_length(new.options);
  if v_joke is null or v_len < 1 or v_len >= 7
     or exists (select 1 from jsonb_array_elements_text(new.options) o where o = v_joke) then return new; end if;
  v_pos := (abs(hashtextextended(new.prompt, 7)) % (v_len + 1))::integer;
  new.options := (select jsonb_agg(t.x order by t.k) from (
      select k, new.options -> k as x from generate_series(0, v_pos - 1) k
      union all select v_pos, to_jsonb(v_joke)
      union all select k + 1, new.options -> k from generate_series(v_pos, v_len - 1) k) t);
  if v_pos <= new.answer then new.answer := new.answer + 1; end if;
  new.joke := v_joke;
  return new;
end $$;
comment on function app.academy_questions_joke() is '4720: a question carries its own joke (jokes-by-question.json) or none; bank jokes are taken out; the right answer keeps pointing at the same option.';

drop trigger if exists academy_questions_a_joke on academy_questions;
create trigger academy_questions_a_joke before insert or update of options, answer, prompt, sort, section_id, joke on academy_questions
  for each row execute function app.academy_questions_joke();

