-- ================================================================ 2. the one-tap new link
-- an expired link the applicant may open again: still invited, never sent in, under the links allowed
create function app.ai_interview_can_renew(a job_applications, iv ai_interviews, p_now timestamptz default now()) returns boolean
language sql stable security definer set search_path = public, app, pg_temp as $$
  select iv.id is not null and a.id is not null and a.status = 'invited' and a.purged_at is null and a.hired_user_id is null and iv.purged_at is null
     and iv.state in ('sent', 'started', 'expired') and iv.expires_at <= p_now
     and iv.links_sent < (app.settings()).hiring_ai_self_renewals and coalesce((app.settings()).hiring_ai_interviews, false)
$$;

alter function public.server_ai_interview(text) rename to server_ai_interview_pre5161;
create function public.server_ai_interview(p_token text) returns jsonb
language plpgsql stable security definer set search_path = public, app, pg_temp as $$
declare
  v jsonb := public.server_ai_interview_pre5161(p_token);
  a job_applications;
  iv ai_interviews;
begin
  if coalesce(v ->> 'state', '') <> 'expired' then return v; end if;
  select * into a from job_applications where token = p_token and purged_at is null;
  select * into iv from ai_interviews where application_id = a.id;
  return v || jsonb_build_object('can_renew', app.ai_interview_can_renew(a, iv));
end $$;
select pg_temp.copy_grants('public.server_ai_interview(text)'::regprocedure, 'public.server_ai_interview_pre5161(text)'::regprocedure);

create function public.server_ai_interview_renew(p_token text) returns jsonb
language plpgsql security definer set search_path = public, app, pg_temp as $$
declare
  a job_applications;
  iv ai_interviews;
begin
  select * into a from job_applications where token = btrim(coalesce(p_token, '')) and purged_at is null;
  if a.id is null then return jsonb_build_object('ok', false, 'error', 'not_found'); end if;
  select * into iv from ai_interviews where application_id = a.id for update;
  if not coalesce(app.ai_interview_can_renew(a, iv), false) then return jsonb_build_object('ok', false, 'error', 'not_renewable'); end if;
  update ai_interviews set expires_at = now() + make_interval(days => (app.settings()).hiring_ai_interview_days), links_sent = links_sent + 1,
         state = case when started_at is null then 'sent' else 'started' end, updated_at = now()
   where id = iv.id;
  insert into audit_log (actor_user_id, action, entity_table, entity_id, after)
  values (null, 'ai_interview_renewed_by_applicant', 'ai_interviews', iv.id::text, jsonb_build_object('links_sent', iv.links_sent + 1));
  return jsonb_build_object('ok', true);
end $$;

-- ================================================================ 3. a waiting reminder that no longer applies
alter function app.outbox_stale_reason(notification_outbox, timestamptz) rename to outbox_stale_reason_pre5161;
create function app.outbox_stale_reason(o notification_outbox, p_now timestamptz default now()) returns text
language plpgsql stable security definer set search_path = public, app, pg_temp as $$
declare v_iv ai_interviews;
begin
  if o.status in ('queued', 'delayed') and o.code = 'applicant_ai_interview_reminder' then
    select i.* into v_iv from ai_interviews i join job_applications a on a.id = i.application_id
     where lower(a.email) = lower(o.to_address) order by i.sent_at desc nulls last limit 1;
    if v_iv.id is not null and (v_iv.expires_at <= least(p_now, now()) or v_iv.state not in ('sent', 'started')) then return 'stale: the interview is in or its link expired'; end if;
  end if;
  return app.outbox_stale_reason_pre5161(o, p_now);
end $$;
select pg_temp.copy_grants('app.outbox_stale_reason(notification_outbox, timestamptz)'::regprocedure, 'app.outbox_stale_reason_pre5161(notification_outbox, timestamptz)'::regprocedure);

-- ================================================================ grants: the server only
do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where (n.nspname = 'app' and p.proname = any (array['ai_interview_reminder_due', 'ai_interview_reminder_vars', 'hiring_ai_nudge', 'job_hiring_pre5161',
                     'ai_interview_can_renew', 'outbox_stale_reason_pre5161']))
               or (n.nspname = 'public' and p.proname = any (array['server_ai_interview_pre5161', 'server_ai_interview_renew'])) loop
    execute format('revoke all on function %s from public, anon, authenticated', f.sig);
    execute format('grant execute on function %s to service_role', f.sig);
  end loop;
end $$;
