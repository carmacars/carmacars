-- ================================================================ 1. reminders
-- when the next reminder of an interview is due (null: none left); the link's start is its expiry less its days
create function app.ai_interview_reminder_due(iv ai_interviews, s program_settings) returns timestamptz
language plpgsql stable set search_path = public, app, pg_temp as $$
declare
  v_n integer := case when iv.reminders_link is distinct from iv.links_sent then 0 else iv.reminders_sent end;
  v_start timestamptz := iv.expires_at - make_interval(days => s.hiring_ai_interview_days);
  v_hours integer[] := coalesce(s.hiring_ai_reminder_hours, '{}');
  v_at timestamptz;
begin
  if v_n < cardinality(v_hours) then
    v_at := v_start + make_interval(hours => (select h from unnest(v_hours) with ordinality u(h, i) order by h limit 1 offset v_n));
    -- a reminder never later than the last one (the link nearly gone)
    if s.hiring_ai_reminder_last_hours > 0 then v_at := least(v_at, iv.expires_at - make_interval(hours => s.hiring_ai_reminder_last_hours)); end if;
    return v_at;
  end if;
  if v_n = cardinality(v_hours) and s.hiring_ai_reminder_last_hours > 0 then
    return iv.expires_at - make_interval(hours => s.hiring_ai_reminder_last_hours);
  end if;
  return null;
end $$;

create function app.ai_interview_reminder_vars(a job_applications, iv ai_interviews) returns jsonb
language sql stable security definer set search_path = public, app, pg_temp as $$
  select app.ai_interview_vars(a, iv) || jsonb_build_object('answered_line',
    case when x.n > 0 then format('You have answered %s of %s questions: it picks up where you left off.', x.n, jsonb_array_length(iv.questions)) else '' end)
    from (select count(*)::int n from ai_interview_answers w where w.interview_id = iv.id and w.kind = 'question') x
$$;

create function app.hiring_ai_nudge(p_now timestamptz default now()) returns jsonb
language plpgsql security definer set search_path = public, app, pg_temp as $$
declare
  s program_settings := app.settings(app.local_date(p_now));
  r record;
  a job_applications;
  iv ai_interviews;
  v_k integer;
  v_texts integer := 0;
  v_emails integer := 0;
  v_held integer := 0;
  v_text phone_outbox;
begin
  if not coalesce(s.hiring_ai_interviews, false) then return jsonb_build_object('emails', 0, 'texts', 0, 'held', 0); end if;
  for r in select i.id from ai_interviews i join job_applications j on j.id = i.application_id
            where i.state in ('sent', 'started') and i.purged_at is null and i.expires_at > p_now
              and j.status = 'invited' and j.purged_at is null and j.hired_user_id is null
              and nullif(btrim(coalesce(j.email, '')), '') is not null and not app.email_is_test(j.email)
              and (i.reminded_at is null or i.reminded_at < p_now - interval '12 hours')
              and app.ai_interview_reminder_due(i, s) <= p_now
            order by i.expires_at limit 200 loop
    select * into iv from ai_interviews where id = r.id for update skip locked;
    continue when iv.id is null;
    select * into a from job_applications where id = iv.application_id;
    -- another email to this applicant still waiting (the day's cap): wait for it rather than stack a second one
    if exists (select 1 from notification_outbox o where lower(o.to_address) = lower(a.email) and o.status in ('queued', 'delayed') and o.code like 'applicant\_%') then
      v_held := v_held + 1; continue;
    end if;
    v_k := case when iv.reminders_link is distinct from iv.links_sent then 0 else iv.reminders_sent end + 1;
    update ai_interviews set reminders_sent = v_k, reminders_link = links_sent, reminded_at = p_now, updated_at = now() where id = iv.id;
    perform app.hiring_emit('applicant_ai_interview_reminder', a, app.ai_interview_reminder_vars(a, iv), 'applicant_ai_interview_reminder:' || iv.id || ':' || iv.links_sent || ':' || v_k);
    v_emails := v_emails + 1;
    -- a text with it, to a Canadian or US number only (the phone line texts North America)
    if s.phone_enabled and s.hiring_sms_reminders and regexp_replace(coalesce(a.phone, ''), '\D', '', 'g') ~ '^1?[2-9][0-9]{9}$' then
      begin
        v_text := app.phone_outbox_put(a.phone, format('CarmaCars: your interview for %s is still open until %s. About 10 minutes, one tap to start: %s',
          (select coalesce(short_title, title) from hiring_roles where id = a.role_id), to_char(iv.expires_at at time zone 'America/Toronto', 'FMMon FMDD'),
          app.hiring_url('/careers/interview/' || a.token)), 'staff', null, null, 'hiring', null, 'hiring_ai_reminder:' || iv.id || ':' || iv.links_sent || ':' || v_k);
        if v_text.id is not null and v_text.status <> 'skipped' then v_texts := v_texts + 1; end if;
      exception when others then null;  -- a number the line cannot text: the email went
      end;
    end if;
  end loop;
  return jsonb_build_object('emails', v_emails, 'texts', v_texts, 'held', v_held);
end $$;

