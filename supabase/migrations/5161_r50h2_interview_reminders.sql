-- 5161_r50h2_interview_reminders.sql
-- Release 50 hotfix 2 (the owner: "many applicants apply but never do the interview"). The drop-off, from the data of
-- Nov 27 (list_applicants, the newest 200 applications): 29 invited and never interviewed, 116 referred to Sales who never
-- said yes, 2 no-shows; the interview email went once, with no reminder and no text (0380: "No texts, no reminders: the
-- one email"); hiring email is a low class held behind the day's email cap (3410), which was hit 60 times in the last 24
-- hours (site_health email_cap), and a held invitation is skipped as stale once its link expires (0601). So the one email
-- often arrived late or never, and an expired link was a dead end ("reply to our email").
--   1. Reminders (app.hiring_ai_nudge, every hiring job run): an invited applicant who has not sent the interview in gets
--      the one-tap link again 1 and 3 days after the link went (Program settings hiring_ai_reminder_hours) and the day
--      before it expires (hiring_ai_reminder_last_hours), never two within 12 hours, never while another email to them is
--      still waiting, and a text with it to a Canadian or US number while texts are on (hiring_sms_reminders).
--   2. The one-tap "do it now" path when the link has expired: the page opens a new link and starts at once
--      (public.server_ai_interview_renew, token-gated, the server only), up to hiring_ai_self_renewals links in all. No
--      email is needed for it.
--   3. A waiting reminder is skipped as stale once the interview is in or its link has expired (as 0601 does for the
--      invitation).
-- No applied migration is edited: app.job_hiring, public.server_ai_interview and app.outbox_stale_reason are wrapped.
set local check_function_bodies = off;

create function pg_temp.copy_grants(p_new regprocedure, p_old regprocedure) returns void
language plpgsql as $$
declare g text;
begin
  execute format('revoke all on function %s from public, anon, authenticated', p_new);
  foreach g in array array['anon', 'authenticated', 'service_role'] loop
    if has_function_privilege(g, p_old, 'execute') then execute format('grant execute on function %s to %I', p_new, g); end if;
  end loop;
end $$;

