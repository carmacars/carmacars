-- a crossing reaches Admins and on-duty Fleet at once: the staff alert (in-app and push, locked on), the email and a text
create function app.tracker_border_staff() returns trigger
language plpgsql security definer set search_path = public, app as $$
declare
  v_rule text := case new.kind when 'left_canada' then 'tracker_canada' else 'tracker_province' end;
  v_title text := case new.kind when 'left_canada' then 'Left Canada' else 'Left Ontario' end;
  v_car text;
  v_number text;
  u record;
begin
  if not (app.tracker_settings()).events_on or new.vehicle_id is null then return null; end if;
  begin
    v_car := app.tracker_car_label(new.vehicle_id);
    v_number := (select booking_number from bookings where id = new.booking_id);
    perform app.staff_alert(v_rule, 'vehicle', new.vehicle_id, new.id::text, left(format('%s: %s', v_title, v_car), 140),
      left(format('%s.%s Call the renter now.', coalesce(new.detail, ''), coalesce(' Booking ' || v_number || '.', '')), 240),
      jsonb_build_object('path_admin', '/admin/vehicles/tracking#events', 'path_staff', '/staff/fleet/map#events'));
    perform app.emit_event('staff_border_alert', 'vehicle', new.vehicle_id,
      jsonb_build_object('vehicle_id', new.vehicle_id, 'booking_id', new.booking_id, 'alert_id', new.id, 'alert_kind', new.kind, 'border_title', v_title, 'car_label', v_car,
        'border_when', app.fmt_at(new.at), 'booking_line', coalesce('Booking ' || v_number, 'No rental under way'),
        'border_clause', 'Rental agreement 10.1 Area; 12.3 Grounds',
        'border_map_url', coalesce(format('https://www.google.com/maps?q=%s,%s', new.lat, new.lng), 'https://carmacars.ca/staff/fleet/map'),
        'border_action', case new.kind when 'left_canada' then 'Call the renter now. Leaving Canada needs our written approval: if there is none and you cannot reach them, tell an Admin (ending the rental and recovery are section 12).'
                                       else 'Call the renter. The car stays in Ontario unless we agreed in writing: note what was agreed on the booking.' end),
      'staff_border_alert:' || new.id);
    for u in select distinct us.phone, us.id from app.staff_alert_users(v_rule, '{}'::jsonb) x(uid, aud) join users us on us.id = x.uid where app.dc_phone_ok(us.phone) loop
      perform app.phone_outbox_put(u.phone, left(format('CarmaCars: %s: %s%s. Call the renter now. https://carmacars.ca/staff/fleet/map', v_title, v_car, coalesce(', booking ' || v_number, '')), 300),
                                   'notify', new.booking_id, null, 'staff_border_alert', null, 'sms:staff_border:' || new.id || ':' || u.id, now());
    end loop;
  exception when others then
    raise warning 'border alert % not completed for staff: %', new.id, sqlerrm;
  end;
  return null;
end $$;
create trigger tracker_border_staff after insert on tracker_alerts for each row when (new.kind in ('left_ontario', 'left_canada')) execute function app.tracker_border_staff();

-- one alert per crossing out of Canada, with its urgent Fleet To do
create function app.tracker_border_scan(s tracker_settings, p_since timestamptz) returns integer
language plpgsql security definer set search_path = public, app as $$
declare
  r record;
  v_out boolean;
  v_alert uuid;
  v_booking uuid;
  n integer := 0;
begin
  for r in select ts.tracker_device_id, ts.reported_at, ts.latitude, ts.longitude, ts.speed_kmh, ts.outside_canada, d.vehicle_id
             from tracker_status ts join tracker_devices d on d.id = ts.tracker_device_id
            where d.status = 'installed' and d.vehicle_id is not null and ts.reported_at > '-infinity' and ts.latitude is not null and ts.received_at >= p_since
  loop
    v_out := not coalesce(app.tracker_in_canada(r.latitude, r.longitude), true);
    if v_out is not distinct from r.outside_canada then continue; end if;
    update tracker_status set outside_canada = v_out where tracker_device_id = r.tracker_device_id;
    if not v_out then continue; end if;
    v_alert := app.tracker_event_raise('left_canada', null, 'reading', r.tracker_device_id, r.vehicle_id, r.reported_at, r.latitude, r.longitude, r.speed_kmh,
      format('Left Canada: %s', app.tracker_car_label(r.vehicle_id)), format('Outside Canada at %s (rental agreement 10.1: written approval is needed)', app.fmt_at(r.reported_at)),
      'canada:' || r.vehicle_id || ':' || extract(epoch from r.reported_at)::bigint);
    if v_alert is null then continue; end if;
    n := n + 1;
    begin
      v_booking := (select a.booking_id from tracker_alerts a where a.id = v_alert);
      perform app.raise_task(p_type => 'left_canada', p_queue => 'fleet', p_priority => 'urgent',
        p_title => left(format('Left Canada: %s%s', app.tracker_car_label(r.vehicle_id), coalesce(' (booking ' || (select booking_number from bookings where id = v_booking) || ')', '')), 200),
        p_detail => left(format('The tracker shows the car outside Canada at %s. Leaving Canada needs written approval (rental agreement 10.1). Call the renter now; with no approval and no answer, tell an Admin (section 12). Its evidence record is on Cars > Fleet tracking > Tracker events.', app.fmt_at(r.reported_at)), 900),
        p_booking => v_booking, p_vehicle => r.vehicle_id, p_related_table => 'tracker_alerts', p_related_id => v_alert, p_dedupe => 'left_canada:' || v_alert);
    exception when others then
      raise warning 'left Canada To do not made for %: %', v_alert, sqlerrm;
    end;
  end loop;
  return n;
end $$;

create or replace function app.tracker_ingest(p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  s tracker_settings := app.tracker_settings();
  v_start timestamptz := clock_timestamp();
  v jsonb;
  v_events integer := 0;
begin
  if not s.events_on then return app.tracker_ingest_pre3320(p); end if;
  v_events := app.tracker_events_scan(p, s);
  v := app.tracker_ingest_pre3320(p);
  v_events := v_events + app.tracker_border_scan(s, v_start);
  v_events := v_events + app.tracker_pound_scan(s, v_start, clock_timestamp());
  perform app.tracker_evidence_fill(clock_timestamp());
  return v || jsonb_build_object('events', v_events);
end $$;

