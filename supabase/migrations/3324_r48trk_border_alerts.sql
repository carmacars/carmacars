-- in Canada, roughly: Ontario's outline (0400); outside it, north of the 49th parallel (49.4: clear of Lake of the Woods),
-- or east of Ontario and north of the 45th parallel (Quebec; farther east, north of Maine or in the Maritimes)
create function app.tracker_in_canada(p_lat numeric, p_lng numeric) returns boolean
language sql immutable as $$
  select case when p_lat is null or p_lng is null then null
              when coalesce(app.tracker_in_ontario(p_lat, p_lng), false) then true
              when p_lng < -141 then false
              when p_lat >= 49.4 then true
              when p_lng > -79.52 and p_lng <= -70.9 and p_lat >= 45.02 then true
              when p_lng > -70.9 and (p_lat >= 47.5 or p_lng > -67.0) and p_lat >= 43.4 then true
              else false end
$$;

