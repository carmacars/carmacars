-- 0229: interview calls by role (phone for the in-person roles, video for the remote ones), a one-click confirmation for
-- the remote calls instead of reminders, and the Quo texts on Settings > Usage (docs/changes/2026-11-03-hiring-call-confirm.md).
-- The owner, Release 23:
--
-- 1. The way a call is held follows the role, not the day: Field staff and Sales in person are always called by phone
--    (recorded with Quo), the remote roles always meet by video (a Jitsi link). The day's "How" stays as its default for
--    the slots shown. app.hiring_mode(role); the booking, its emails, the booking page and the Calls tab use it. Future
--    bookings that got the other way are put right now, with one corrected booking email each.
-- 2. Remote roles: no reminder emails and no texts (long distance; each Quo text costs about a cent). One email asks the
--    candidate to confirm (applicant_confirm, "Confirm my call", no sign-in), 24 hours before the call or at once when it
--    is booked less than 24 hours ahead. Not confirmed within 12 hours of that email, or by 1 hour before the call,
--    whichever is sooner: the call is cancelled, the time opens again, and one short email says so with the link to book
--    again (applicant_unconfirmed). The Calls tab shows Confirmed, Waiting or Cancelled (not confirmed).
-- 3. In-person roles keep their reminders as they are (email; a text only while texts are on).
-- 4. Settings > Usage: "Texts this month (Quo)", the texts sent through the Quo API this month at US$0.01 each, with the
--    usage alerts of 0080 and 0221 (300 a month included as the budget; change the allowance there).
-- No applied migration is edited.

create function pg_temp.copy_grants(p_new regprocedure, p_old regprocedure) returns void
language plpgsql as $$
declare g text;
begin
  execute format('revoke all on function %s from public, anon, authenticated', p_new);
  foreach g in array array['anon', 'authenticated', 'service_role'] loop
    if has_function_privilege(g, p_old, 'execute') then execute format('grant execute on function %s to %I', p_new, g); end if;
  end loop;
end $$;
create function pg_temp.patch_fn(p_sig regprocedure, p_old text, p_new text) returns void
language plpgsql as $$
declare
  d text := pg_get_functiondef(p_sig);
begin
  if position(p_old in d) = 0 then
    raise exception '0229: the text to change was not found in %: %', p_sig, left(p_old, 120);
  end if;
  execute replace(d, p_old, p_new);
end $$;

