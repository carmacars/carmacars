-- ================================================================ 1. the way a call is held follows the role
create or replace function app.hiring_mode(p_role uuid) returns text
language sql stable security definer set search_path = public, app as $$
  select case when coalesce((select r.remote from hiring_roles r where r.id = p_role), false) then 'video' else 'phone' end
$$;

