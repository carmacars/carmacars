alter function app.job_hiring(timestamptz) rename to job_hiring_pre0229;
create function app.job_hiring(p_now timestamptz default now()) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  a job_applications;
  v_start timestamptz;
  v_asked integer := 0;
  v_cancelled integer := 0;
  v jsonb;
begin
  -- remote roles get no reminder emails or texts: their reminder marks are set, so the reminders of 0173 pass them by
  update job_applications x set reminded_evening_at = coalesce(x.reminded_evening_at, p_now), reminded_hour_at = coalesce(x.reminded_hour_at, p_now)
    from hiring_roles r
   where r.id = x.role_id and r.remote and x.status = 'booked' and (x.reminded_evening_at is null or x.reminded_hour_at is null);
  -- the confirmation email, 24 hours before (at once for a call booked closer than that)
  for a in select x.* from job_applications x join interview_slots y on y.id = x.slot_id join hiring_roles r on r.id = x.role_id
            where r.remote and x.status = 'booked' and x.confirm_sent_at is null and y.starts_at > p_now + interval '1 hour'
              and y.starts_at - p_now <= interval '24 hours'
            for update of x skip locked loop
    update job_applications set confirm_sent_at = p_now, updated_at = p_now where id = a.id returning * into a;
    perform app.hiring_emit('applicant_confirm', a, app.hiring_booking_vars(a) || jsonb_build_object(
      'confirm_url', app.hiring_url('/careers/book/' || a.token || '/confirm?seq=' || a.booking_seq),
      'confirm_by', app.hiring_when(app.hiring_confirm_by(a))), 'applicant_confirm:' || a.id || ':' || a.booking_seq);
    v_asked := v_asked + 1;
  end loop;
  -- not confirmed in time: cancelled, the time opens again, one short email
  for a in select x.* from job_applications x join hiring_roles r on r.id = x.role_id
            where r.remote and x.status = 'booked' and x.confirm_sent_at is not null and x.confirmed_at is null and p_now >= app.hiring_confirm_by(x)
            for update of x skip locked loop
    update job_applications set status = 'invited', slot_id = null, meet_url = null, unconfirmed_at = p_now, updated_at = p_now where id = a.id returning * into a;
    perform app.hiring_emit('applicant_unconfirmed', a, jsonb_build_object('booking_url', app.hiring_url('/careers/book/' || a.token)), 'applicant_unconfirmed:' || a.id || ':' || a.booking_seq);
    v_cancelled := v_cancelled + 1;
  end loop;
  v := app.job_hiring_pre0229(p_now);
  return coalesce(v, '{}'::jsonb) || jsonb_build_object('confirm_asked', v_asked, 'unconfirmed_cancelled', v_cancelled);
end $$;
select pg_temp.copy_grants('app.job_hiring(timestamptz)'::regprocedure, 'app.job_hiring_pre0229(timestamptz)'::regprocedure);

