-- a new booking (or a moved one) asks again
create or replace function app.hiring_confirm_reset() returns trigger
language plpgsql security definer set search_path = public, app as $$
begin
  if new.booking_seq is distinct from old.booking_seq then
    new.confirm_sent_at := null; new.confirmed_at := null; new.unconfirmed_at := null;
  end if;
  return new;
end $$;
drop trigger if exists job_applications_confirm_reset on job_applications;
create trigger job_applications_confirm_reset before update of booking_seq on job_applications for each row execute function app.hiring_confirm_reset();

create or replace function app.hiring_confirm_state(a job_applications) returns text
language sql stable security definer set search_path = public, app as $$
  select case when not coalesce((select r.remote from hiring_roles r where r.id = a.role_id), false) then null
              when a.unconfirmed_at is not null and a.status <> 'booked' then 'cancelled'
              when a.status <> 'booked' then null
              when a.confirmed_at is not null then 'confirmed'
              when a.confirm_sent_at is not null then 'waiting'
              else 'not_asked' end
$$;

-- the time to confirm by: 12 hours after the email, or 1 hour before the call, whichever is sooner
create or replace function app.hiring_confirm_by(a job_applications) returns timestamptz
language sql stable security definer set search_path = public, app as $$
  select least(a.confirm_sent_at + interval '12 hours', (select s.starts_at from interview_slots s where s.id = a.slot_id) - interval '1 hour')
$$;

create or replace function app.hiring_confirm(p_token text, p_seq integer default null) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare a job_applications;
begin
  select * into a from job_applications where token = p_token and purged_at is null for update;
  if a.id is null then return jsonb_build_object('ok', false, 'error', 'not_found'); end if;
  if a.status <> 'booked' then return jsonb_build_object('ok', false, 'error', case when a.unconfirmed_at is not null then 'cancelled' else 'not_booked' end); end if;
  if p_seq is not null and p_seq <> a.booking_seq then return jsonb_build_object('ok', false, 'error', 'moved'); end if;
  if a.confirmed_at is null then update job_applications set confirmed_at = now(), updated_at = now() where id = a.id returning * into a; end if;
  return jsonb_build_object('ok', true, 'confirmed_at', a.confirmed_at, 'starts_at', (select starts_at from interview_slots where id = a.slot_id));
end $$;
create or replace function public.server_hiring_confirm(p_token text, p_seq integer default null) returns jsonb
language sql security definer set search_path = public, app as $$ select app.hiring_confirm(p_token, p_seq) $$;

