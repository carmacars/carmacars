-- 2861 (release 45, part B): "Restore this version" on a confirmed booking.
--
-- "Revert to this offer" works only while a booking is requested, offered or waiting for payment. Once confirmed, staff
-- change the dates and the fees with Edit and could not go back (a 7 day booking changed to 4, then 3, then back to 7
-- days was repriced higher than the original 7). Each change is kept (booking_staff_edits, 0132) with the booking before
-- and after; this keeps the fee lines with them and puts any of those versions back.
--   1. booking_staff_edits: seq (the order within one moment), lines_before and lines_after (each fee line by its key,
--      the way Edit changes them), restored_version. A change of the fees alone (Change booking fees) on a confirmed,
--      on-trip or returned booking is kept as a change too, so it is a version.
--   2. ops_read booking_versions {booking}: version 1 is the booking before its first change, then one version after
--      each change, the newest the current one; with who, when, why and the price.
--   3. ops_do booking_version_restore {booking, version, reason, tell_renter, preview}: puts the booking back to that
--      version's dates, car, rental charge and fee lines exactly, as one Edit (app.booking_staff_edit): the same checks
--      (who may change a booking, the car free for the dates, the fees) and the change logged with the reason. With
--      preview it does all of it and undoes it, answering the difference (dates, car, total, what the renter would owe
--      or get back). Payments are never touched: a difference is a balance or a credit like any change. A version kept
--      before this release has no fee lines: its dates, car and rental charge are put back and the fees stay as they are
--      (the preview says so).
-- No applied migration is edited: booking_staff_edit, booking_fees_change and the door are wrapped (_pre2861).
set local check_function_bodies = off;

create function pg_temp.copy_grants(p_new regprocedure, p_old regprocedure) returns void
language plpgsql as $$
declare g text;
begin
  execute format('revoke all on function %s from public, anon, authenticated', p_new);
  foreach g in array array['anon', 'authenticated', 'service_role'] loop
    if has_function_privilege(g, p_old, 'execute') then execute format('grant execute on function %s to %I', p_new, g); end if;
  end loop;
end $$;

-- ================================================================ 1. the fee lines with each change
alter table booking_staff_edits add column if not exists seq bigint generated by default as identity;
alter table booking_staff_edits add column if not exists lines_before jsonb;
alter table booking_staff_edits add column if not exists lines_after jsonb;
alter table booking_staff_edits add column if not exists restored_version integer;
comment on column booking_staff_edits.lines_before is 'r45 (2861): each fee line before the change, {line key: cents} as Edit changes them (app.booking_fee_lines). Null for a change kept before 2861.';
comment on column booking_staff_edits.lines_after is 'r45 (2861): each fee line after the change. Null for a change kept before 2861.';
comment on column booking_staff_edits.restored_version is 'r45 (2861): this change put the booking back to that version (Restore this version).';

-- the booking's fee lines as Edit sees them: the key of each line (addon:<code> for an add-on) and its amount; the rental
-- charge, the discounts and the deposit have their own fields
create function app.booking_fee_lines(p_booking uuid) returns jsonb
language sql stable security definer set search_path = public, app as $$
  select coalesce(jsonb_object_agg(k, c), '{}'::jsonb) from (
    select case when li.booking_addon_id is not null then 'addon:' || a.code else li.charge_type end k, sum(li.amount_cents)::bigint c
      from booking_line_items li left join booking_addons ba on ba.id = li.booking_addon_id left join addons a on a.id = ba.addon_id
     where li.booking_id = p_booking and li.stage = 'booking' and li.voided_at is null
     group by 1) x
   where k is not null and k ~ '^[a-z0-9_]+(:[A-Za-z0-9_-]+)?$' and k not in ('rental_charge', 'non_refundable_discount', 'promo_discount', 'staff_discount', 'deposit')
$$;
revoke all on function app.booking_fee_lines(uuid) from public, anon, authenticated;
grant execute on function app.booking_fee_lines(uuid) to service_role;

alter function app.booking_staff_edit(uuid, jsonb) rename to booking_staff_edit_pre2861;
create function app.booking_staff_edit(p_by uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  v_id uuid;
  v_lines0 jsonb;
  v_depth text := coalesce(current_setting('cc.staff_edit', true), '');
  r jsonb;
begin
  select id into v_id from bookings where id::text = p ->> 'booking' or booking_number = upper(btrim(coalesce(p ->> 'booking', '')));
  if v_id is not null then v_lines0 := app.booking_fee_lines(v_id); end if;
  perform set_config('cc.staff_edit', '1', true);
  r := app.booking_staff_edit_pre2861(p_by, p);
  perform set_config('cc.staff_edit', v_depth, true);
  if v_id is not null and coalesce((r ->> 'changed')::boolean, false) then
    update booking_staff_edits set lines_before = v_lines0, lines_after = app.booking_fee_lines(v_id)
     where id = (select e.id from booking_staff_edits e where e.booking_id = v_id and e.lines_after is null and e.edited_at = now() order by e.seq desc limit 1);
  end if;
  return r;
end $$;
select pg_temp.copy_grants('app.booking_staff_edit(uuid, jsonb)'::regprocedure, 'app.booking_staff_edit_pre2861(uuid, jsonb)'::regprocedure);

alter function app.booking_fees_change(uuid, jsonb) rename to booking_fees_change_pre2861;
create function app.booking_fees_change(p_by uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  b bookings;
  v_before jsonb;
  v_lines0 jsonb;
  r jsonb;
begin
  if coalesce(current_setting('cc.staff_edit', true), '') = '1' then return app.booking_fees_change_pre2861(p_by, p); end if;
  select * into b from bookings where id::text = p ->> 'booking' or booking_number = upper(btrim(coalesce(p ->> 'booking', '')));
  if b.id is null or b.status::text not in ('confirmed', 'on_rent', 'returned') then return app.booking_fees_change_pre2861(p_by, p); end if;
  v_before := app.booking_snapshot(b.id);
  v_lines0 := app.booking_fee_lines(b.id);
  r := app.booking_fees_change_pre2861(p_by, p);
  if jsonb_typeof(r -> 'changes') = 'array' and jsonb_array_length(r -> 'changes') > 0 then
    insert into booking_staff_edits (booking_id, edited_by, booking_status, reason, told_renter, changes, before, after, total_before_cents, total_after_cents, lines_before, lines_after)
    values (b.id, p_by, b.status::text, nullif(btrim(coalesce(p ->> 'reason', '')), ''), false,
            (select jsonb_agg(jsonb_build_object('field', 'fee:' || (c ->> 'key'), 'label', c ->> 'label', 'before', c -> 'before_cents', 'after', c -> 'after_cents')) from jsonb_array_elements(r -> 'changes') c),
            v_before, app.booking_snapshot(b.id), (v_before ->> 'total_cents')::bigint, (r ->> 'total_cents')::bigint, v_lines0, app.booking_fee_lines(b.id));
  end if;
  return r;
end $$;
select pg_temp.copy_grants('app.booking_fees_change(uuid, jsonb)'::regprocedure, 'app.booking_fees_change_pre2861(uuid, jsonb)'::regprocedure);

-- ================================================================ 2. the versions
create function app.booking_version_list(p_booking uuid) returns jsonb
language sql stable security definer set search_path = public, app as $$
  with e as (
    select e.*, row_number() over (order by e.edited_at, e.seq) n, count(*) over () total
      from booking_staff_edits e where e.booking_id = p_booking),
  v as (
    select 1 no, e.edited_at at, null::text by_name, null::text reason, 'start' kind, e.before snap, e.lines_before lines, null::integer restored, e.total
      from e where e.n = 1
    union all
    select e.n + 1, e.edited_at, (select u.full_name from users u where u.id = e.edited_by), e.reason,
           case when e.restored_version is not null then 'restore' else 'change' end, e.after, e.lines_after, e.restored_version, e.total
      from e)
  select coalesce(jsonb_agg(jsonb_build_object('no', v.no, 'at', v.at, 'by', v.by_name, 'reason', v.reason, 'kind', v.kind, 'restored', v.restored,
           'current', v.no = v.total + 1,
           'pickup_at', v.snap -> 'pickup_at', 'return_at', v.snap -> 'return_at', 'vehicle_id', v.snap -> 'vehicle_id', 'vehicle', v.snap -> 'vehicle',
           'billable_days', v.snap -> 'billable_days', 'rental_charge_cents', v.snap -> 'rental_charge_cents', 'total_cents', v.snap -> 'total_cents',
           'lines', v.lines) order by v.no), '[]'::jsonb)
    from v
$$;
revoke all on function app.booking_version_list(uuid) from public, anon, authenticated;
grant execute on function app.booking_version_list(uuid) to service_role;

create function app.booking_versions(p_by uuid, p jsonb) returns jsonb
language plpgsql stable security definer set search_path = public, app as $$
declare b bookings;
begin
  if not (app.user_is_admin(p_by) or app.user_is_staff(p_by)) then raise exception 'Not permitted' using errcode = '42501'; end if;
  select * into b from bookings where id::text = p ->> 'booking' or booking_number = upper(btrim(coalesce(p ->> 'booking', '')));
  if b.id is null then raise exception 'Booking not found' using errcode = 'P0002'; end if;
  return jsonb_build_object('booking_number', b.booking_number, 'status', b.status, 'refusal', app.booking_edit_refusal(p_by, b),
    'may_restore', app.booking_edit_refusal(p_by, b) is null, 'versions', app.booking_version_list(b.id));
end $$;
revoke all on function app.booking_versions(uuid, jsonb) from public, anon, authenticated;
grant execute on function app.booking_versions(uuid, jsonb) to service_role;

-- ================================================================ 3. restore one
create function app.booking_version_restore(p_by uuid, p jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
declare
  b bookings;
  v jsonb;
  v_no integer := nullif(p ->> 'version', '')::integer;
  v_preview boolean := coalesce((p ->> 'preview')::boolean, false);
  v_reason text := nullif(btrim(coalesce(p ->> 'reason', '')), '');
  v_refuse text;
  c jsonb := '{}'::jsonb;
  l jsonb := '{}'::jsonb;
  v_cur jsonb;
  v_dates boolean;
  k text;
  r jsonb;
  v_problem text;
  v_before jsonb;
  v_after jsonb;
  v_lines_after jsonb;
  v_open0 bigint;
  v_open1 bigint;
  v_unmatched jsonb := '[]'::jsonb;
begin
  select * into b from bookings where id::text = p ->> 'booking' or booking_number = upper(btrim(coalesce(p ->> 'booking', ''))) for update;
  v_refuse := app.booking_edit_refusal(p_by, b);
  if v_refuse is not null then raise exception '%', v_refuse using errcode = case when b.id is null then 'P0002' else '42501' end; end if;
  select t.e into v from jsonb_array_elements(app.booking_version_list(b.id)) as t(e) where (t.e ->> 'no')::integer = v_no;
  if v is null then raise exception 'That version is not in this booking''s history' using errcode = 'P0002'; end if;
  if not v_preview and (v_reason is null or length(v_reason) < 3) then raise exception 'Give the reason for restoring this version' using errcode = '22023'; end if;

  -- the dates, the car and the rental charge of the version (a new length is never repriced: the version's own charge is set)
  if (v ->> 'pickup_at')::timestamptz is distinct from b.pickup_at then c := c || jsonb_build_object('pickup_at', v -> 'pickup_at'); end if;
  if (v ->> 'return_at')::timestamptz is distinct from b.return_at then c := c || jsonb_build_object('return_at', v -> 'return_at'); end if;
  v_dates := c <> '{}'::jsonb;
  if nullif(v ->> 'vehicle_id', '')::uuid is distinct from b.vehicle_id and nullif(v ->> 'vehicle_id', '') is not null then
    c := c || jsonb_build_object('vehicle_id', v -> 'vehicle_id');
  end if;
  if v_dates or (v ->> 'rental_charge_cents')::bigint is distinct from b.rental_charge_cents then
    c := c || jsonb_build_object('rental_charge_cents', (v ->> 'rental_charge_cents')::bigint);
  end if;
  -- each fee line of the version (one missing from it now: 0); with new dates every line is set, so none is rescaled
  if jsonb_typeof(v -> 'lines') = 'object' then
    v_cur := app.booking_fee_lines(b.id);
    for k in select x from jsonb_object_keys(v -> 'lines') x union select x from jsonb_object_keys(v_cur) x loop
      if v_dates or coalesce((v -> 'lines' ->> k)::bigint, 0) is distinct from coalesce((v_cur ->> k)::bigint, 0) then
        l := l || jsonb_build_object(k, coalesce((v -> 'lines' ->> k)::bigint, 0));
      end if;
    end loop;
  end if;

  v_before := app.booking_snapshot(b.id) || jsonb_build_object('lines', app.booking_fee_lines(b.id));
  v_open0 := app.booking_part_open(b.id, 'rental') + app.booking_part_open(b.id, 'fees');
  if c = '{}'::jsonb and l = '{}'::jsonb then
    return jsonb_build_object('ok', true, 'changed', false, 'preview', v_preview, 'version', v_no, 'booking_number', b.booking_number,
      'message', 'The booking is already as in this version.');
  end if;
  p := jsonb_build_object('booking', b.id, 'changes', c, 'tell_renter', coalesce((p ->> 'tell_renter')::boolean, false),
         'reason', format('Restored version %s%s', v_no, coalesce(': ' || v_reason, '')))
       || case when l <> '{}'::jsonb then jsonb_build_object('lines', l) else '{}'::jsonb end;

  if v_preview then
    begin
      r := app.booking_staff_edit(p_by, p);
      v_after := app.booking_snapshot(b.id);
      v_lines_after := app.booking_fee_lines(b.id);
      v_open1 := app.booking_part_open(b.id, 'rental') + app.booking_part_open(b.id, 'fees');
      raise exception using errcode = 'XC861', message = 'preview only';
    exception
      when sqlstate 'XC861' then null;
      when others then v_problem := sqlerrm;
    end;
  else
    r := app.booking_staff_edit(p_by, p);
    v_after := app.booking_snapshot(b.id);
    v_lines_after := app.booking_fee_lines(b.id);
    v_open1 := app.booking_part_open(b.id, 'rental') + app.booking_part_open(b.id, 'fees');
    update booking_staff_edits set restored_version = v_no
     where id = (select e.id from booking_staff_edits e where e.booking_id = b.id and e.edited_at = now() order by e.seq desc limit 1);
  end if;
  if v_problem is null and jsonb_typeof(v -> 'lines') = 'object' then
    select coalesce(jsonb_agg(ks.k2 order by ks.k2), '[]'::jsonb) into v_unmatched
      from (select jsonb_object_keys(v -> 'lines') k2 union select jsonb_object_keys(v_lines_after)) ks
     where coalesce((v -> 'lines' ->> ks.k2)::bigint, 0) is distinct from coalesce((v_lines_after ->> ks.k2)::bigint, 0);
  end if;
  return jsonb_build_object('ok', v_problem is null, 'problem', v_problem, 'changed', v_problem is null, 'preview', v_preview, 'version', v_no,
    'booking_number', b.booking_number, 'fees_kept', jsonb_typeof(v -> 'lines') <> 'object',
    'before', v_before, 'after', case when v_after is not null then v_after || jsonb_build_object('lines', v_lines_after) end, 'target', v,
    'changes', r -> 'changes', 'total_before_cents', (v_before ->> 'total_cents')::bigint, 'total_after_cents', (v_after ->> 'total_cents')::bigint,
    'open_before_cents', v_open0, 'open_after_cents', v_open1, 'unmatched', v_unmatched);
end $$;
comment on function app.booking_version_restore(uuid, jsonb) is 'r45 (2861): Restore this version: the booking back to a version''s dates, car, rental charge and fee lines as one staff edit (its checks, its log), or with preview the difference only. Never a payment.';
revoke all on function app.booking_version_restore(uuid, jsonb) from public, anon, authenticated;
grant execute on function app.booking_version_restore(uuid, jsonb) to service_role;

