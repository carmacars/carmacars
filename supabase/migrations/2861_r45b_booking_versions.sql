create function app.door(p_user uuid, p_aal text, p_call text, p_name text, p jsonb default '{}'::jsonb) returns jsonb
language plpgsql security definer set search_path = public, app as $$
begin
  if (p_call = 'ops_read' and p_name = 'booking_versions') or (p_call = 'ops_do' and p_name = 'booking_version_restore') then
    if coalesce(p, '{}'::jsonb) ? '_va' then perform set_config('app.va_active', coalesce(p ->> '_va', ''), true); end if;
    perform app.door_begin(p_user, p_aal);
    if p_name = 'booking_versions' then return app.booking_versions(p_user, coalesce(p, '{}'::jsonb) - '_va'); end if;
    return app.booking_version_restore(p_user, coalesce(p, '{}'::jsonb) - '_va');
  end if;
  return app.door_pre2861(p_user, p_aal, p_call, p_name, p);
end $$;
