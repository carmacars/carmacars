#!/usr/bin/env node
// Migration 0093's two generated blocks:
//   FLEET: the 01 Motors partner, its 62 cars and 11 chauffeur vehicles, from web/src/features/partner/fleet-01-motors.ts
//          (the parsed price sheet; its unit test checks it against the sheet's text);
//   GUIDES: the guide chapters of this release, from docs/guides/content (as 0088 does: every chapter that changed since
//          the branch point is published; an Admin's earlier text stays in the history).
//   node supabase/seed/0093_gen.mjs           rewrites both blocks in 0093_01_motors_partner.sql
//   node supabase/seed/0093_gen.mjs --check   exits 1 if a block is out of date (needs git for the guides' base text)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderGuide } from '../../web/src/features/guides/markdown.ts';
import { CARS, CHAUFFEUR, DEFAULT_CUT_BPS, DEFAULT_MARKUP_BPS } from '../../web/src/features/partner/fleet-01-motors.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MIGRATION = join(ROOT, 'supabase', 'migrations', '0093_01_motors_partner.sql');
const BASE = '3c17a04';
const q = (v) => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

export function fleetBlock() {
  const data = {
    partner: { business_name: '01 Motors', commission_bps: DEFAULT_CUT_BPS, markup_bps: DEFAULT_MARKUP_BPS,
      notes: 'Partner rental fleet (October 22, 2026). No portal sign-in yet: staff manage the cars; add an email and invite them from this page later. Rates are the partner\'s guideline rates; final pricing may change after insurance review (driver risk, vehicle, use).' },
    cars: CARS.map((c) => ({ sheet: c.sheet, make: c.make, model: c.model, trim: c.trim, colour: c.colour, body: c.body, seats: c.seats, doors: c.doors,
      drive: c.drive, transmission: c.transmission, class: c.cls, year: c.year, included: c.included, base: c.rates.base, multi: c.rates.multi, long: c.rates.long })),
    chauffeur: CHAUFFEUR.map((c) => ({ sheet: c.sheet, name: c.name, slug: slug(c.name), kind: c.kind, passengers: c.passengers, rentals: c.rentals,
      two_hour: c.twoHour, three_plus: c.threePlus, sort: c.sort }))
  };
  const json = JSON.stringify(data).replace(/\},\{"sheet"/g, '},\n  {"sheet"');
  return `select app.partner_fleet_import_0093(${q(json)}::jsonb);`;
}

function guidesBlock() {
  const lines = [];
  for (const portal of ['renter', 'owner', 'admin', 'va', 'field', 'investor']) {
    const now = JSON.parse(readFileSync(join(ROOT, 'docs', 'guides', 'content', `${portal}.json`), 'utf8'));
    const base = JSON.parse(execFileSync('git', ['show', `${BASE}:docs/guides/content/${portal}.json`], { cwd: ROOT, encoding: 'utf8' }));
    let after = null;
    for (const s of now.sections) {
      const b = base.sections.find((x) => x.slug === s.slug);
      const prev = after; after = s.slug;
      if (b && b.body_md === s.body_md && b.title === s.title && (b.blurb ?? '') === (s.blurb ?? '')) continue;
      const { html, warnings } = renderGuide([{ ...s, id: 'x' }]);
      if (warnings.length) throw new Error(`${portal}/${s.slug}: ${warnings.join('; ')}`);
      lines.push(`select app.guide_release_0093(${q(portal)}, ${q(s.slug)}, ${q(s.kind)}, ${q(prev)}, ${q(b?.body_md ?? null)}, ${q(s.title)}, ${q(s.blurb)},\n  ${q(s.body_md)},\n  ${q(html.x)});`);
    }
  }
  return lines.join('\n');
}

function put(sql, name, body) {
  const start = `-- ${name} 0093 START (generated by supabase/seed/0093_gen.mjs from ${name === 'FLEET' ? 'web/src/features/partner/fleet-01-motors.ts' : 'docs/guides/content'}; do not edit by hand)`;
  const end = `-- ${name} 0093 END`;
  const a = sql.indexOf(start), b = sql.indexOf(end);
  if (a < 0 || b < 0) throw new Error(`${name} markers missing`);
  return sql.slice(0, a) + `${start}\n${body}\n${end}` + sql.slice(b + end.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sql = readFileSync(MIGRATION, 'utf8');
  const next = put(put(sql, 'FLEET', fleetBlock()), 'GUIDES', guidesBlock());
  if (process.argv.includes('--check')) {
    if (next !== sql) { console.error('0093 generated blocks are out of date: run node supabase/seed/0093_gen.mjs'); process.exit(1); }
    console.log('0093 blocks up to date');
  } else { writeFileSync(MIGRATION, next); console.log('0093: fleet and guides blocks written'); }
}
