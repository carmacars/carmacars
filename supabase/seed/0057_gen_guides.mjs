#!/usr/bin/env node
// The guide chapters of this release (migration 0057: My sales, the team's sales, the first reply target of 5 minutes, the
// staff agreement defaults by function), from docs/guides/content (written by docs/guides/src/export.py), with the HTML of
// web/src/features/guides/markdown.ts. Each chapter carries its text of the last release (the content of commit 2cd490d,
// live since October 17): a live chapter still showing that text (with the screenshots the upkeep replaced) gets the new
// one, published; a chapter an Admin edited keeps the Admin's text and gets the new one as a suggestion; a new chapter is
// added after the one before it.
//   node supabase/seed/0057_gen_guides.mjs           rewrites the block in 0057_sales_tracking.sql
//   node supabase/seed/0057_gen_guides.mjs --check   exits 1 if the block is out of date (needs git for the base text)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderGuide } from '../../web/src/features/guides/markdown.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MIGRATION = join(ROOT, 'supabase', 'migrations', '0057_sales_tracking.sql');
const START = '-- GUIDES 0057 START (generated by supabase/seed/0057_gen_guides.mjs from docs/guides/content; do not edit by hand)';
const END = '-- GUIDES 0057 END';
const BASE = '2cd490d';
const q = (v) => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");

const lines = [];
for (const portal of ['renter', 'owner', 'admin', 'va', 'field', 'investor']) {
  const now = JSON.parse(readFileSync(join(ROOT, 'docs', 'guides', 'content', `${portal}.json`), 'utf8'));
  const base = JSON.parse(execFileSync('git', ['show', `${BASE}:docs/guides/content/${portal}.json`], { cwd: ROOT, encoding: 'utf8' }));
  let after = null;
  for (const s of now.sections) {
    const b = base.sections.find((x) => x.slug === s.slug);
    const prev = after; after = s.slug;
    if (b && b.body_md === s.body_md && b.title === s.title && (b.blurb ?? '') === (s.blurb ?? '')) continue;
    const { html, warnings } = renderGuide([{ ...s, id: 'x' }]);
    if (warnings.length) throw new Error(`${portal}/${s.slug}: ${warnings.join('; ')}`);
    lines.push(`select app.guide_release_0057(${q(portal)}, ${q(s.slug)}, ${q(s.kind)}, ${q(prev)}, ${q(b?.body_md ?? null)}, ${q(s.title)}, ${q(s.blurb)},\n  ${q(s.body_md)},\n  ${q(html.x)});`);
  }
}
const block = `${START}\n${lines.join('\n')}\n${END}`;
const sql = readFileSync(MIGRATION, 'utf8');
const a = sql.indexOf(START), b = sql.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers missing');
const next = sql.slice(0, a) + block + sql.slice(b + END.length);
if (process.argv.includes('--check')) { if (next !== sql) { console.error('0057 guides block is out of date'); process.exit(1); } console.log('0057 guides block up to date'); }
else { writeFileSync(MIGRATION, next); console.log(`0057: ${lines.length} chapters updated or added`); }
