#!/usr/bin/env node
// The guide chapters of the investor deck release (migration NNNN_investor_deck.sql), from docs/guides/content, with
// the HTML of web/src/features/guides/markdown.ts: the new chapter "The investor deck" in the investor and Admin guides,
// published as 0059 does (app.guide_release_section).
//   node --experimental-strip-types supabase/seed/0083_gen_guides.mjs           rewrites the block in the migration
//   node --experimental-strip-types supabase/seed/0083_gen_guides.mjs --check   exits 1 if the block is out of date
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderGuide } from '../../web/src/features/guides/markdown.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MIGRATION = join(ROOT, 'supabase', 'migrations', readdirSync(join(ROOT, 'supabase', 'migrations')).find((f) => /_investor_deck\.sql$/.test(f)));
const START = '-- GUIDES 0083 START (generated by supabase/seed/0083_gen_guides.mjs from docs/guides/content; do not edit by hand)';
const END = '-- GUIDES 0083 END';
const CHAPTERS = [['investor', 'the-investor-deck'], ['admin', 'the-investor-deck']];
const q = (v) => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");

const lines = [];
for (const [portal, slug] of CHAPTERS) {
  const g = JSON.parse(readFileSync(join(ROOT, 'docs', 'guides', 'content', `${portal}.json`), 'utf8'));
  const i = g.sections.findIndex((s) => s.slug === slug);
  if (i < 0) throw new Error(`${portal}/${slug} missing`);
  const s = g.sections[i];
  const { html, warnings } = renderGuide([{ ...s, id: 'x' }]);
  if (warnings.length) throw new Error(`${portal}/${slug}: ${warnings.join('; ')}`);
  lines.push(`select app.guide_release_section(${q(portal)}, ${q(slug)}, ${q(s.kind)}, ${q(g.sections[i - 1]?.slug ?? null)}, null, ${q(s.title)}, ${q(s.blurb)},\n  ${q(s.body_md)},\n  ${q(html.x)});`);
}
const block = `${START}\n${lines.join('\n')}\n${END}`;
const sql = readFileSync(MIGRATION, 'utf8');
const a = sql.indexOf(START), b = sql.indexOf(END);
const next = a < 0 || b < 0 ? `${sql.trimEnd()}\n\n-- ================================================================ 5. the guides for this release\n${block}\n` : sql.slice(0, a) + block + sql.slice(b + END.length);
if (process.argv.includes('--check')) { if (next !== sql) { console.error('deck guides block is out of date'); process.exit(1); } console.log('deck guides block up to date'); }
else { writeFileSync(MIGRATION, next); console.log(`deck: ${lines.length} chapters published`); }
