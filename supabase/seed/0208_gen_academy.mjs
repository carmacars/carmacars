#!/usr/bin/env node
// The academy's first content (migration 0208; Release 21b, item 9): the paths, sections, lessons (scenes) and quizzes of
// supabase/seed/academy/*.mjs, written as SQL between the markers of 0208_academy_content.sql. After the migration the
// content lives in the database and an Admin edits it in Admin > Academy; this file is not read again.
//   node supabase/seed/0208_gen_academy.mjs           rewrites the block
//   node supabase/seed/0208_gen_academy.mjs --check   exits 1 if the block is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { POLICY_SECTIONS } from './academy/policies.mjs';
import { ROLE_SECTIONS, PATHS } from './academy/roles.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MIGRATION = join(ROOT, 'supabase', 'migrations', '0208_academy_content.sql');
const START = '-- ACADEMY 0208 START (generated by supabase/seed/0208_gen_academy.mjs from supabase/seed/academy; do not edit by hand)';
const END = '-- ACADEMY 0208 END';
const q = (v) => "'" + String(v).replace(/'/g, "''") + "'";
const j = (v) => q(JSON.stringify(v)) + '::jsonb';

const SECTIONS = [...POLICY_SECTIONS, ...ROLE_SECTIONS];
const bySlug = new Map(SECTIONS.map((s) => [s.slug, s]));
const problems = [];
for (const s of SECTIONS) {
  if (!s.lessons.length || s.quiz.length < 5) problems.push(`${s.slug}: lessons and at least 5 questions`);
  for (const l of s.lessons) for (const sc of l.scenes) if (!sc.caption || !sc.say || !sc.visual?.kind) problems.push(`${s.slug}/${l.title}: a scene without caption, words or picture`);
  for (const x of s.quiz) if (!(x.answer >= 0 && x.answer < x.options.length)) problems.push(`${s.slug}: answer out of range in "${x.prompt}"`);
  if (/[–—]/.test(JSON.stringify(s))) problems.push(`${s.slug}: a long dash`);
}
for (const p of PATHS) for (const s of p.sections) if (!bySlug.has(s)) problems.push(`${p.code}: no section ${s}`);
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const out = [];
PATHS.forEach((p, i) => out.push(`insert into academy_paths (code, title, blurb, sort) values (${q(p.code)}, ${q(p.title)}, ${q(p.blurb)}, ${i + 1});`));
for (const s of SECTIONS) {
  out.push(`insert into academy_sections (slug, title, blurb) values (${q(s.slug)}, ${q(s.title)}, ${q(s.blurb)});`);
  const sec = `(select id from academy_sections where slug = ${q(s.slug)})`;
  s.lessons.forEach((l, i) => out.push(`insert into academy_lessons (section_id, sort, title, scenes) values (${sec}, ${i + 1}, ${q(l.title)}, ${j(l.scenes)});`));
  s.quiz.forEach((x, i) => out.push(`insert into academy_questions (section_id, sort, prompt, options, answer, explain) values (${sec}, ${i + 1}, ${q(x.prompt)}, ${j(x.options)}, ${x.answer}, ${q(x.explain)});`));
}
for (const p of PATHS) p.sections.forEach((s, i) => out.push(`insert into academy_path_sections (path_code, section_id, sort) values (${q(p.code)}, (select id from academy_sections where slug = ${q(s)}), ${i + 1});`));

const block = `${START}\n${out.join('\n')}\n${END}`;
const sql = readFileSync(MIGRATION, 'utf8');
const a = sql.indexOf(START), b = sql.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers missing');
const next = sql.slice(0, a) + block + sql.slice(b + END.length);
const count = (code) => { const p = PATHS.find((x) => x.code === code); const ss = p.sections.map((s) => bySlug.get(s)); return `${code}: ${ss.length} sections, ${ss.reduce((n, s) => n + s.lessons.length, 0)} lessons, ${ss.reduce((n, s) => n + s.lessons.reduce((m, l) => m + l.scenes.length, 0), 0)} scenes, ${ss.reduce((n, s) => n + s.quiz.length, 0)} questions`; };
if (process.argv.includes('--check')) { if (next !== sql) { console.error('0208_academy_content.sql: block out of date'); process.exit(1); } console.log('0208_academy_content.sql: up to date'); }
else { writeFileSync(MIGRATION, next); console.log(`0208: ${SECTIONS.length} sections, ${SECTIONS.reduce((n, s) => n + s.lessons.length, 0)} lessons, ${SECTIONS.reduce((n, s) => n + s.quiz.length, 0)} questions`); for (const p of PATHS) console.log('  ' + count(p.code)); }
