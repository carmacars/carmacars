#!/usr/bin/env node
// The guide chapters of migration 0144 (the field ready check fixed on the spot, automatic field jobs, the identity review in one step, Payments by day, the owner's month to date),
// from docs/guides/content (written by docs/guides/src/export.py),
// with the HTML of web/src/features/guides/markdown.ts. Every chapter that differs from release4 (the merge base) is
// published as 0059 does (an Admin's earlier text stays in the history, with Revert).
//   node supabase/seed/0144_gen_guides.mjs           rewrites the block in the migration
//   node supabase/seed/0144_gen_guides.mjs --check   exits 1 if the block is out of date (needs git)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderGuide } from '../../web/src/features/guides/markdown.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DIR = join(ROOT, 'supabase', 'migrations');
const file = '0144_field_finance_owner_mtd.sql';
const MIGRATION = join(DIR, file);
const START = '-- GUIDES 0144 START (generated by supabase/seed/0144_gen_guides.mjs from docs/guides/content; do not edit by hand)';
const END = '-- GUIDES 0144 END';
// the content main leaves: the commit before the one that brought 0144 into this history (HEAD itself while it is not committed)
const git = (...a) => execFileSync('git', a, { cwd: ROOT, encoding: 'utf8' }).trim();
const ADDED = git('log', '--first-parent', '--format=%H', '-1', '--diff-filter=A', 'HEAD', '--', 'supabase/migrations/0144_field_finance_owner_mtd.sql');
const BASE = process.env.GUIDES_BASE || (ADDED ? git('rev-parse', `${ADDED}^1`) : git('rev-parse', 'HEAD'));
const q = (v) => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");

const lines = [];
for (const portal of ['renter', 'owner', 'admin', 'va', 'field', 'investor']) {
  const now = JSON.parse(readFileSync(join(ROOT, 'docs', 'guides', 'content', `${portal}.json`), 'utf8'));
  const base = JSON.parse(execFileSync('git', ['show', `${BASE}:docs/guides/content/${portal}.json`], { cwd: ROOT, encoding: 'utf8' }));
  let after = null;
  for (const s of now.sections) {
    const b = base.sections.find((x) => x.slug === s.slug);
    const prev = after; after = s.slug;
    if (b && b.body_md === s.body_md && b.title === s.title && (b.blurb ?? '') === (s.blurb ?? '')) continue;
    const { html, warnings } = renderGuide([{ ...s, id: 'x' }]);
    if (warnings.length) throw new Error(`${portal}/${s.slug}: ${warnings.join('; ')}`);
    lines.push(`select app.guide_release_section(${q(portal)}, ${q(s.slug)}, ${q(s.kind)}, ${q(prev)}, ${q(b?.body_md ?? null)}, ${q(s.title)}, ${q(s.blurb)},\n  ${q(s.body_md)},\n  ${q(html.x)});`);
  }
}
const block = `${START}\n${lines.join('\n')}\n${END}`;
const sql = readFileSync(MIGRATION, 'utf8');
const a = sql.indexOf(START), b = sql.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers missing');
const next = sql.slice(0, a) + block + sql.slice(b + END.length);
if (process.argv.includes('--check')) { if (next !== sql) { console.error(`${file}: guides block is out of date`); process.exit(1); } console.log(`${file}: guides block up to date`); }
else { writeFileSync(MIGRATION, next); console.log(`${file}: ${lines.length} chapters published`); }
