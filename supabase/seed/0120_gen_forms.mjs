// the fields of each publisher's download, as the filler reads them
const shape = (x) => {
  const o = { name: x.name, type: x.type };
  if (x.options?.length) o.options = x.options;
  if (x.page) o.page = x.page;
  if (x.rect) o.rect = x.rect.map((n) => Math.round(n * 10) / 10);
  const label = x.label || x.tooltip;
  if (label) o.label = String(label).replace(/\s+/g, ' ').trim().slice(0, 200);
  if (x.max_length) o.max_length = x.max_length;
  return o;
};
const rows = [];
for (const f of REPORT.forms) {
  const read = await readPdfFields(new Uint8Array(readFileSync(join(FIX, `${f.code}.pdf`))));
  const fields = read.fields.filter((x) => x.type !== 'button').map(shape);
  const byName = new Map(fields.map((x) => [x.name, x]));
  const map = {};
  for (const [name, m] of Object.entries(MAP[f.code])) {
    const x = byName.get(name);
    if (!x) throw new Error(`${f.code}: no field ${name}`);
    if (m.type === 'checkbox' && x.type !== 'checkbox' && !read.xfaOnly) throw new Error(`${f.code}: ${name} is not a checkbox`);
    if (m.type === 'dropdown' && x.type !== 'dropdown') throw new Error(`${f.code}: ${name} is not a drop-down`);
    if ((m.type ?? 'text') === 'text' && x.type !== 'text') throw new Error(`${f.code}: ${name} is not a text field`);
    map[name] = m;
  }
  const notes = `${PURPOSE[f.code]} ${LEFT[f.code]} ${INK} Mapping checked against the official PDF (${f.pdf_url}, SHA-256 ${f.original_sha256}); check it with a preview before use.`;
  rows.push({ code: f.code, from: f.template_sha256, sha256: f.original_sha256, pages: read.pages, kind: f.kind, fields, map, notes });
}

const sql = [START,
  '-- the copies stored today (the same fields; the laid-out copy of the Adobe dynamic form ON00453 is retired, see 6.)',
  ...rows.filter((r) => r.kind !== 'overlay').map((r) => `select app.official_form_remap(${q(r.code)}, ${q(r.from)},\n  ${q(js(r.fields))}::jsonb,\n  ${q(js(r.map))}::jsonb,\n  ${q(r.notes)});`),
  '-- the publisher\'s downloads, byte for byte',
  ...rows.map((r) => `select app.official_form_original(${q(r.code)}, ${q(r.from)}, ${q(r.sha256)}, ${q(`forms/templates/${r.code}/official-${r.sha256.slice(0, 16)}.pdf`)}, ${r.pages},\n  ${q(js(r.fields))}::jsonb,\n  ${q(js(r.map))}::jsonb,\n  ${q(r.notes)});`),
  END].join('\n');
const maps = JSON.stringify(Object.fromEntries(rows.map((r) => [r.code, { kind: 'acroform', map: r.map }])), null, 1) + '\n';
const src = readFileSync(MIGRATION, 'utf8');
const a = src.indexOf(START), b = src.indexOf(END);
if (a < 0 || b < 0) throw new Error('0120_form_fillers.sql has no markers');
const next = src.slice(0, a) + sql + src.slice(b + END.length);
if (process.argv.includes('--check')) {
  let bad = false;
  if (next !== src) { console.error('out of date: the forms block in 0120_form_fillers.sql'); bad = true; }
  let cur = ''; try { cur = readFileSync(MAPS, 'utf8'); } catch { /* missing */ }
  if (cur !== maps) { console.error('out of date: web/src/features/official-forms/maps.generated.json'); bad = true; }
  if (bad) process.exit(1);
  console.log('0120 forms block and maps are up to date');
} else {
  writeFileSync(MIGRATION, next);
  writeFileSync(MAPS, maps);
  console.log(rows.map((r) => `${r.code}: ${r.fields.length} fields, ${Object.keys(r.map).length} mapped`).join('\n'));
}
