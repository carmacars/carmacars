// the laid-out form: the three unnamed boxes of the signature row get their names; the signature is drawn in the
// cell under its label (the cell runs from x 20.8 to 200.8, the label takes its top 12 points); the anchor is not a field
function overlayFields(f) {
  const out = [];
  for (const x of f.fields) {
    if (x.name === 'Beginning of form') continue;
    if (x.name === 'Field on page 2') { out.push({ name: 'Section 1. Signature', type: 'signature', page: x.page, rect: [26, 534.6, 168, 16], label: 'Signature (electronic, digital or ink)' }); continue; }
    if (x.name === 'Field on page 2 (2)') { out.push({ ...x, name: 'Section 1. Signature. Name', label: 'Name' }); continue; }
    if (x.name === 'Field on page 2 (3)') { out.push({ ...x, name: 'Section 1. Signature. Date', label: 'Date (yyyy/mm/dd)' }); continue; }
    out.push(x);
  }
  return out;
}

const rows = REPORT.forms.map((f) => {
  const fields = (f.kind === 'overlay' ? overlayFields(f) : f.fields.filter((x) => x.type !== 'button')).map((x) => {
    const o = { name: x.name, type: x.type };
    if (x.options?.length) o.options = x.options;
    if (x.page) o.page = x.page;
    if (x.rect) o.rect = x.rect;
    const label = x.label || x.tooltip;
    if (label) o.label = String(label).replace(/\s+/g, ' ').trim().slice(0, 200);
    if (x.max_length) o.max_length = x.max_length;
    return o;
  });
  const byName = new Map(fields.map((x) => [x.name, x]));
  const map = {};
  for (const [name, m] of Object.entries(MAP[f.code])) {
    const x = byName.get(name);
    if (!x) throw new Error(`${f.code}: no field ${name}`);
    if (m.type === 'checkbox' && x.type !== 'checkbox') throw new Error(`${f.code}: ${name} is not a checkbox`);
    if (m.type === 'dropdown' && x.type !== 'dropdown') throw new Error(`${f.code}: ${name} is not a drop-down`);
    map[name] = f.kind === 'overlay' ? { ...m, box: { page: x.page, rect: x.rect } } : m;
  }
  const notes = `${PURPOSE[f.code]} ${LEFT[f.code]} Mapping checked against the official PDF (${f.pdf_url}, SHA-256 ${f.original_sha256}); check it with a preview before use.`;
  return { code: f.code, sha256: f.template_sha256, fields, map, notes };
});

const sql = [START,
  ...rows.map((r) => `select app.official_form_remap(${q(r.code)}, ${q(r.sha256)},\n  ${q(js(r.fields))}::jsonb,\n  ${q(js(r.map))}::jsonb,\n  ${q(r.notes)});`),
  END].join('\n');
const maps = JSON.stringify(Object.fromEntries(rows.map((r) => [r.code, { kind: REPORT.forms.find((f) => f.code === r.code).kind, map: r.map }])), null, 1) + '\n';
const src = readFileSync(MIGRATION, 'utf8');
const a = src.indexOf(START), b = src.indexOf(END);
if (a < 0 || b < 0) throw new Error('0120_form_fillers.sql has no markers');
const next = src.slice(0, a) + sql + src.slice(b + END.length);
if (process.argv.includes('--check')) {
  let bad = false;
  if (next !== src) { console.error('out of date: the forms block in 0120_form_fillers.sql'); bad = true; }
  let cur = ''; try { cur = readFileSync(MAPS, 'utf8'); } catch { /* missing */ }
  if (cur !== maps) { console.error('out of date: web/src/features/official-forms/maps.generated.json'); bad = true; }
  if (bad) process.exit(1);
  console.log('0120 forms block and maps are up to date');
} else {
  writeFileSync(MIGRATION, next);
  writeFileSync(MAPS, maps);
  console.log(rows.map((r) => `${r.code}: ${r.fields.length} fields, ${Object.keys(r.map).length} mapped`).join('\n'));
}
