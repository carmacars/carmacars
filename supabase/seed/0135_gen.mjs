#!/usr/bin/env node
// The generated blocks of migration 0135 (owner terms per car):
//   the catalogue row of owner_fee_change_notice (lower amounts and the management fee), from emails/catalogue.json as
//   0090's generator does; run after `node emails/build.mjs`;
//   the guide chapters that differ from main (the merge base), from docs/guides/content (written by
//   docs/guides/src/export.py) with the HTML of web/src/features/guides/markdown.ts, published as 0059 does (an Admin's
//   earlier text stays in the history, with Revert).
//   node supabase/seed/0135_gen.mjs           rewrites both blocks in the migration
//   node supabase/seed/0135_gen.mjs --check   exits 1 if a block is out of date (needs git)
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderGuide } from '../../web/src/features/guides/markdown.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const file = '0135_owner_terms_per_car.sql';
const MIGRATION = join(ROOT, 'supabase', 'migrations', file);
const q = (v) => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");
const arr = (a) => (a && a.length ? 'array[' + a.map(q).join(', ') + ']::text[]' : "'{}'::text[]");

// ---------------------------------------------------------------- the catalogue row
const CODES = ['owner_fee_change_notice'];
const C_START = '-- CATALOGUE 0135 START (generated by supabase/seed/0135_gen.mjs; do not edit by hand)';
const C_END = '-- CATALOGUE 0135 END';
const cat = JSON.parse(readFileSync(join(ROOT, 'emails', 'catalogue.json'), 'utf8'));
const site = /export const SITE = '([^']+)'/.exec(readFileSync(join(ROOT, 'emails', 'src', 'links.mjs'), 'utf8'))[1];
const globals = cat.global_variables.map((v) => v.name);
function primaryLink(e) {
  const f = join(ROOT, 'emails', e.template_html);
  if (!existsSync(f)) return null;
  for (const m of readFileSync(f, 'utf8').matchAll(/href="([^"]+)"/g)) {
    if (!m[1].startsWith(site)) continue;
    const p = m[1].slice(site.length) || '/';
    if (!['/', '/terms', '/privacy'].includes(p)) return p;
  }
  return null;
}
const rows = CODES.map((code) => {
  const e = cat.emails.find((x) => x.code === code);
  if (!e) throw new Error(`catalogue.json has no ${code}: run node emails/build.mjs`);
  const vars = e.variables.map((v) => {
    const o = { name: v.name, type: v.type };
    if (v.fields) o.fields = v.fields.map((f) => (typeof f === 'string' ? f : f.name));
    if (globals.includes(v.name)) o.global = true;
    return o;
  });
  return '  (' + [q(e.code), q(e.audience), arr(e.also_sent_to), q(e.category), e.digest ? 'true' : 'false', q(e.digest_slot ?? null),
    q(e.from), q(e.reply_to), q(e.subject), q(e.preheader), q(e.timing), q(e.trigger), q(e.source ?? null),
    q(primaryLink(e)), q(JSON.stringify(vars)) + '::jsonb', q(e.template_html), q(e.template_text)].join(', ') + ')';
});
const catalogue = [C_START,
  'insert into notification_catalogue (code, audience, also_sent_to, category, is_digest, digest_slot, from_address, reply_to,',
  '    subject, preheader, timing, trigger_text, replaces_template, link_path, variables, template_html, template_text) values',
  rows.join(',\n'),
  'on conflict (code) do update set',
  '  audience = excluded.audience, also_sent_to = excluded.also_sent_to, category = excluded.category,',
  '  is_digest = excluded.is_digest, digest_slot = excluded.digest_slot, from_address = excluded.from_address,',
  '  reply_to = excluded.reply_to, subject = excluded.subject, preheader = excluded.preheader, timing = excluded.timing,',
  '  trigger_text = excluded.trigger_text, replaces_template = excluded.replaces_template, link_path = excluded.link_path,',
  '  variables = excluded.variables, template_html = excluded.template_html, template_text = excluded.template_text,',
  '  in_catalogue = true, updated_at = now();',
  'select app.notification_catalogue_refresh();',
  C_END].join('\n');

// ---------------------------------------------------------------- the guide chapters
const G_START = '-- GUIDES 0135 START (generated by supabase/seed/0135_gen.mjs from docs/guides/content; do not edit by hand)';
const G_END = '-- GUIDES 0135 END';
const BASE = process.env.GUIDES_BASE || execFileSync('git', ['merge-base', 'HEAD', 'origin/main'], { cwd: ROOT, encoding: 'utf8' }).trim();
const lines = [];
for (const portal of ['renter', 'owner', 'admin', 'va', 'field', 'investor']) {
  const now = JSON.parse(readFileSync(join(ROOT, 'docs', 'guides', 'content', `${portal}.json`), 'utf8'));
  const base = JSON.parse(execFileSync('git', ['show', `${BASE}:docs/guides/content/${portal}.json`], { cwd: ROOT, encoding: 'utf8' }));
  let after = null;
  for (const s of now.sections) {
    const b = base.sections.find((x) => x.slug === s.slug);
    const prev = after; after = s.slug;
    if (b && b.body_md === s.body_md && b.title === s.title && (b.blurb ?? '') === (s.blurb ?? '')) continue;
    const { html, warnings } = renderGuide([{ ...s, id: 'x' }]);
    if (warnings.length) throw new Error(`${portal}/${s.slug}: ${warnings.join('; ')}`);
    lines.push(`select app.guide_release_section(${q(portal)}, ${q(s.slug)}, ${q(s.kind)}, ${q(prev)}, ${q(b?.body_md ?? null)}, ${q(s.title)}, ${q(s.blurb)},\n  ${q(s.body_md)},\n  ${q(html.x)});`);
  }
}
const guides = `${G_START}\n${lines.join('\n')}\n${G_END}`;

// ---------------------------------------------------------------- write or check
let sql = readFileSync(MIGRATION, 'utf8');
const put = (src, start, end, block) => {
  const a = src.indexOf(start), b = src.indexOf(end);
  if (a < 0 || b < 0) throw new Error(`${file}: markers missing (${start.slice(3, 20)})`);
  return src.slice(0, a) + block + src.slice(b + end.length);
};
const next = put(put(sql, C_START, C_END, catalogue), G_START, G_END, guides);
if (process.argv.includes('--check')) {
  if (next !== sql) { console.error(`${file}: a generated block is out of date (node supabase/seed/0135_gen.mjs)`); process.exit(1); }
  console.log(`${file}: catalogue and guides blocks up to date`);
} else {
  writeFileSync(MIGRATION, next);
  console.log(`${file}: ${CODES.length} catalogue row, ${lines.length} guide chapters`);
}
