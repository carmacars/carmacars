// the laid-out form: the three unnamed boxes of the signature row get their names; the signature itself is the label
// cell's empty part; the anchor at the top is not a field
function overlayFields(f) {
  const out = [];
  for (const x of f.fields) {
    if (x.name === 'Beginning of form') continue;
    if (x.name === 'Field on page 2') { out.push({ name: 'Section 1. Signature', type: 'signature', page: x.page, rect: [24, x.rect[1] - 13.8, 140, 14], label: 'Signature (electronic, digital or ink)' }); continue; }
    if (x.name === 'Field on page 2 (2)') { out.push({ ...x, name: 'Section 1. Signature. Name', label: 'Name' }); continue; }
    if (x.name === 'Field on page 2 (3)') { out.push({ ...x, name: 'Section 1. Signature. Date', label: 'Date (yyyy/mm/dd)' }); continue; }
    out.push(x);
  }
  return out;
}

const rows = REPORT.forms.map((f) => {
  if (!f.file_key) throw new Error(`${f.code}: no file_key in the report`);
  const fields = (f.kind === 'overlay' ? overlayFields(f) : f.fields.filter((x) => x.type !== 'button')).map((x) => {
    const o = { name: x.name, type: x.type };
    if (x.options?.length) o.options = x.options;
    if (x.page) o.page = x.page;
    if (x.rect) o.rect = x.rect;
    const label = x.label || x.tooltip;
    if (label) o.label = String(label).replace(/\s+/g, ' ').trim().slice(0, 200);
    if (x.max_length) o.max_length = x.max_length;
    return o;
  });
  const names = new Set(fields.map((x) => x.name));
  const map = {};
  for (const x of fields) {
    const m = MAP[f.code][x.name];
    if (!m) continue;
    map[x.name] = f.kind === 'overlay' ? { ...m, box: { page: x.page, rect: x.rect }, ...(x.type === 'checkbox' ? { type: 'checkbox' } : {}) } : m;
  }
  // every name the draft maps must exist in the form
  for (const k of Object.keys(MAP[f.code])) if (!names.has(k)) throw new Error(`${f.code}: no field ${k}`);
  const notes = `${PURPOSE[f.code]} Draft mapping from the official PDF (${f.pdf_url}, SHA-256 ${f.original_sha256}; template ${f.template_sha256}); check every field before use.`;
  return { code: f.code, title: plain(f.dataset_title || f.title), kind: f.kind, file_key: f.file_key, sha256: f.template_sha256, pages: f.pages,
           fields, map, notes, file_name: f.pdf_url.split('/').pop(), mapped: Object.keys(map).length };
});

const sql = [START,
  ...rows.map((r) => `select app.official_form_draft(${q(r.code)}, ${q(r.title)}, ${q(r.kind)}, ${q(r.file_key)}, ${q(r.sha256)}, ${r.pages}, ${q(r.file_name)},\n  ${q(js(r.fields))}::jsonb,\n  ${q(js(r.map))}::jsonb,\n  ${q(r.notes)});`),
  END].join('\n');
const src = readFileSync(MIGRATION, 'utf8');
const a = src.indexOf(START), b = src.indexOf(END);
if (a < 0 || b < 0) throw new Error('0047_official_forms_drafts.sql has no markers');
const current = src.slice(a, b + END.length);
if (process.argv.includes('--check')) {
  if (current !== sql) { console.error('out of date: the forms block in 0047_official_forms_drafts.sql'); process.exit(1); }
  console.log('0047 forms block is up to date');
} else {
  writeFileSync(MIGRATION, src.slice(0, a) + sql + src.slice(b + END.length));
  console.log(rows.map((r) => `${r.code}: ${r.kind}, ${r.fields.length} fields, ${r.mapped} mapped`).join('\n'));
}
