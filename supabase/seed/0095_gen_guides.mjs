#!/usr/bin/env node
// The guide chapters of this release (migration 0095: place pages for every place and term, detailing and body shop,
// requests from the place pages, one name, address and phone), from docs/guides/content (written by docs/guides/src/export.py),
// with the HTML of web/src/features/guides/markdown.ts. Every chapter that changed since the branch point (3c17a04, release 2)
// is published as 0059 does (an Admin's earlier text stays in the history, with Revert).
//   node supabase/seed/0095_gen_guides.mjs           rewrites the block in 0095_local_seo_places.sql
//   node supabase/seed/0095_gen_guides.mjs --check   exits 1 if the block is out of date (needs git for the base text)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderGuide } from '../../web/src/features/guides/markdown.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MIGRATION = join(ROOT, 'supabase', 'migrations', '0095_local_seo_places.sql');
const START = '-- GUIDES 0095 START (generated by supabase/seed/0095_gen_guides.mjs from docs/guides/content; do not edit by hand)';
const END = '-- GUIDES 0095 END';
const BASE = '3c17a04';
const FORCE = new Set();
const q = (v) => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");

const lines = [];
for (const portal of ['renter', 'owner', 'admin', 'va', 'field', 'investor']) {
  const now = JSON.parse(readFileSync(join(ROOT, 'docs', 'guides', 'content', `${portal}.json`), 'utf8'));
  const base = JSON.parse(execFileSync('git', ['show', `${BASE}:docs/guides/content/${portal}.json`], { cwd: ROOT, encoding: 'utf8' }));
  let after = null;
  for (const s of now.sections) {
    const b = base.sections.find((x) => x.slug === s.slug);
    const prev = after; after = s.slug;
    const force = FORCE.has(`${portal}/${s.slug}`);
    if (!force && b && b.body_md === s.body_md && b.title === s.title && (b.blurb ?? '') === (s.blurb ?? '')) continue;
    const { html, warnings } = renderGuide([{ ...s, id: 'x' }]);
    if (warnings.length) throw new Error(`${portal}/${s.slug}: ${warnings.join('; ')}`);
    lines.push(`select app.guide_release_0095(${q(portal)}, ${q(s.slug)}, ${q(s.kind)}, ${q(prev)}, ${q(b?.body_md ?? null)}, ${q(s.title)}, ${q(s.blurb)},\n  ${q(s.body_md)},\n  ${q(html.x)});`);
  }
}
const block = `${START}\n${lines.join('\n')}\n${END}`;
const sql = readFileSync(MIGRATION, 'utf8');
const a = sql.indexOf(START), b = sql.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers missing');
const next = sql.slice(0, a) + block + sql.slice(b + END.length);
if (process.argv.includes('--check')) { if (next !== sql) { console.error('0095 guides block is out of date'); process.exit(1); } console.log('0095 guides block up to date'); }
else { writeFileSync(MIGRATION, next); console.log(`0095: ${lines.length} chapters published or added`); }
