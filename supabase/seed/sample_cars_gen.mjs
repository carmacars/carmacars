#!/usr/bin/env node
// The 20 sample cars of the original seed (prototype/tools/src/data.mjs and prototype/assets/photos.json, the cars
// web/scripts/seed.mjs adds locally) as the catalogue rows of the migration *_sample_cars_back.sql, and their photos as
// static files of the site (web/public/sample-photos/cars/), so "Show sample cars" never depends on the photo bucket.
//   node supabase/seed/sample_cars_gen.mjs           rewrites the block in the migration and copies the photos
//   node supabase/seed/sample_cars_gen.mjs --check   exits 1 if the block or the photos are out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const MIG_DIR = path.join(ROOT, 'supabase', 'migrations');
const file = fs.readdirSync(MIG_DIR).find((f) => /^\d{4}_sample_cars_back\.sql$/.test(f));
if (!file) throw new Error('no *_sample_cars_back.sql migration');
const MIGRATION = path.join(MIG_DIR, file);
const START = '-- SAMPLE CARS START (generated by supabase/seed/sample_cars_gen.mjs; do not edit by hand)';
const END = '-- SAMPLE CARS END';
const PHOTO_DIR = path.join(ROOT, 'web', 'public', 'sample-photos', 'cars');
const check = process.argv.includes('--check');

const { CARS } = await import(path.join(ROOT, 'prototype', 'tools', 'src', 'data.mjs'));
const photos = JSON.parse(fs.readFileSync(path.join(ROOT, 'prototype', 'assets', 'photos.json'), 'utf8'));
// the same values as web/scripts/seed.mjs
const SHOT = { lead: 'front_left', side: 'left', rear34: 'rear_left', front: 'front', rear: 'rear', dash: 'dashboard', seats: 'front_seats', wheel: 'wheel' };
const FUEL = { Gasoline: 'gasoline', Electric: 'electric', Hybrid: 'hybrid', Diesel: 'diesel' };
const PRICING = ['economy', 'standard', 'premium', 'suv', 'luxury', 'exotic'];
const AREAS = ['Leslieville', 'The Annex', 'Liberty Village', 'Midtown', 'North York', 'Etobicoke', 'Scarborough', 'Yorkville', 'Danforth', 'Junction'];
const cents = (d) => Math.round(d * 100);
const q = (v) => "'" + String(v).replace(/'/g, "''") + "'";

const rows = [];
const files = [];
for (const [i, c] of CARS.entries()) {
  const lower = c.classes.map((k) => k.toLowerCase());
  const gallery = photos.cars[c.slug].gallery.map((g) => {
    const name = path.basename(g.src);
    files.push(name);
    return { shot: SHOT[g.shot], path: '/sample-photos/cars/' + name, alt: g.alt, width: g.width, height: g.height };
  });
  const d = {
    slug: c.slug, fleet_number: c.code, year: c.year, make: c.make, model: c.model, trim: c.trim, colour: c.colour,
    fuel: FUEL[c.fuel] || 'gasoline', vin: ('SAMPLE' + String(i + 1).padStart(2, '0') + 'X'.repeat(17)).slice(0, 17),
    plate: 'SMPL' + String(i + 1).padStart(3, '0'), class: lower.find((k) => PRICING.includes(k)) || 'standard', classes: lower,
    body: c.body, owner_pickup: Boolean(c.ownerPickup),
    rates: { daily: cents(c.rates.daily), weekend: cents(c.rates.weekend), weekly: cents(c.rates.weekly), monthly: cents(c.rates.monthly) },
    km_per_day: c.kmPerDay, overage: cents(c.overage), deposit: cents(c.deposit), delivery: cents(c.delivery),
    young: c.youngFees['18-20'] !== 35 ? { a: cents(c.youngFees['18-20']), b: cents(c.youngFees['21-25']) } : null,
    headline: `${c.year} ${c.make} ${c.model} ${c.trim} for rent in Toronto`.slice(0, 70), blurb: c.blurb, features: c.features,
    seats: c.seats, transmission: c.transmission, drive: c.drive, doors: c.doors, bags: c.bags, consumption: c.l100,
    area: AREAS[i % AREAS.length], featured: i < 7, photos: gallery
  };
  rows.push(`  (${q(c.slug)}, ${i + 1}, ${q(JSON.stringify(d))}::jsonb)`);
}
const block = `${START}\ninsert into sample_car_catalogue (slug, sort_order, data) values\n${rows.join(',\n')}\non conflict (slug) do update set sort_order = excluded.sort_order, data = excluded.data;\n${END}`;
const sql = fs.readFileSync(MIGRATION, 'utf8');
const a = sql.indexOf(START), b = sql.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers missing in ' + file);
const next = sql.slice(0, a) + block + sql.slice(b + END.length);

let stale = next !== sql;
for (const f of files) {
  const src = path.join(ROOT, 'prototype', 'assets', 'photos', f), dst = path.join(PHOTO_DIR, f);
  const same = fs.existsSync(dst) && fs.readFileSync(dst).equals(fs.readFileSync(src));
  if (!same) { stale = true; if (!check) { fs.mkdirSync(PHOTO_DIR, { recursive: true }); fs.copyFileSync(src, dst); } }
}
if (check) {
  if (stale) { console.error(`${file}: the sample car block or web/public/sample-photos/cars is out of date (node supabase/seed/sample_cars_gen.mjs)`); process.exit(1); }
  console.log(`${file}: sample cars up to date`);
} else {
  fs.writeFileSync(MIGRATION, next);
  console.log(`${file}: ${rows.length} sample cars, ${files.length} photos`);
}
