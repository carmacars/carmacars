#!/usr/bin/env node
// The guide chapters added by migration 0048, from docs/guides/content/<portal>.json (written by docs/guides/src/export.py),
// with the HTML of web/src/features/guides/markdown.ts (the renderer of an Admin's Publish). Written into the migration
// between its markers, before the migration is first applied:
//   node supabase/seed/0048_gen_guides.mjs           rewrites the block in 0048_guide_supply_sections.sql
//   node supabase/seed/0048_gen_guides.mjs --check   exits 1 if the block is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderGuide } from '../../web/src/features/guides/markdown.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MIGRATION = join(ROOT, 'supabase', 'migrations', '0048_guide_supply_sections.sql');
const START = '-- GUIDES 0048 START (generated by supabase/seed/0048_gen_guides.mjs from docs/guides/content; do not edit by hand)';
const END = '-- GUIDES 0048 END';
const NEW = [['admin', 'partners-company-cars-and-rentals-added-by-hand'], ['va', 'add-a-rental-by-hand'], ['owner', 'for-partner-rental-companies']];
const q = (v) => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");

const lines = [];
for (const [portal, slug] of NEW) {
  const g = JSON.parse(readFileSync(join(ROOT, 'docs', 'guides', 'content', `${portal}.json`), 'utf8'));
  const i = g.sections.findIndex((s) => s.slug === slug);
  if (i < 1) throw new Error(`${portal}: no section ${slug}`);
  const s = g.sections[i];
  const { html, warnings } = renderGuide([{ ...s, id: 'x' }]);
  if (warnings.length) throw new Error(`${portal}: ${warnings.join('; ')}`);
  lines.push(`select app.guide_add_published_section(${q(portal)}, ${q(g.sections[i - 1].slug)}, ${q(slug)}, ${q(s.title)}, ${q(s.blurb)},\n  ${q(s.body_md)},\n  ${q(html.x)});`);
}
const block = `${START}\n${lines.join('\n')}\n${END}`;
const sql = readFileSync(MIGRATION, 'utf8');
const a = sql.indexOf(START), b = sql.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers missing');
const next = sql.slice(0, a) + block + sql.slice(b + END.length);
if (process.argv.includes('--check')) { if (next !== sql) { console.error('0048 guides block is out of date'); process.exit(1); } console.log('0048 guides block up to date'); }
else { writeFileSync(MIGRATION, next); console.log(`0048: ${lines.length} chapters`); }
