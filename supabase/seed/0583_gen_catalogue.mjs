#!/usr/bin/env node
// The catalogue rows of migration 0583 (the staff email digest and the staff emails in plain words), generated from emails/catalogue.json the same way as 0018's
// generator, and written into the migration between its markers. Run after `node emails/build.mjs`:
//   node supabase/seed/0583_gen_catalogue.mjs           rewrites the block
//   node supabase/seed/0583_gen_catalogue.mjs --check   exits 1 if the block is out of date
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MIGRATIONS = join(ROOT, 'supabase', 'migrations');
const FILE = readdirSync(MIGRATIONS).find((f) => f.endsWith('_email_volume.sql'));
if (!FILE) throw new Error('no *_email_volume.sql migration');
const MIGRATION = join(MIGRATIONS, FILE);
// the digest (C3), a new row
const CODES = ['staff_digest_hourly'];
// the staff emails rewritten in plain words (C4): their subject, preheader and variables only (how each is sent, a digest
// or at once, stays as later migrations and the Admins set it)
const WORDS = ['staff_owner_debit_exception', 'staff_owner_invoice_failed', 'staff_owner_debit_run', 'staff_job_failed', 'staff_calendar_feed_failing', 'staff_usage_alert',
  // each amount of an owner-debit email in one plain line (0584): the owner's emails' variables
  'owner_debit_notice', 'owner_debit_setup_needed', 'owner_debit_returned', 'owner_payment_failed', 'owner_in_arrears'];
const START = '-- CATALOGUE 0583 START (generated by supabase/seed/0583_gen_catalogue.mjs; do not edit by hand)';
const END = '-- CATALOGUE 0583 END';
const q = (v) => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");
const arr = (a) => (a && a.length ? 'array[' + a.map(q).join(', ') + ']::text[]' : "'{}'::text[]");

const cat = JSON.parse(readFileSync(join(ROOT, 'emails', 'catalogue.json'), 'utf8'));
const site = /export const SITE = '([^']+)'/.exec(readFileSync(join(ROOT, 'emails', 'src', 'links.mjs'), 'utf8'))[1];
const globals = cat.global_variables.map((v) => v.name);
function primaryLink(e) {
  const f = join(ROOT, 'emails', e.template_html);
  if (!existsSync(f)) return null;
  for (const m of readFileSync(f, 'utf8').matchAll(/href="([^"]+)"/g)) {
    if (!m[1].startsWith(site)) continue;
    const p = m[1].slice(site.length) || '/';
    if (!['/', '/terms', '/privacy'].includes(p)) return p;
  }
  return null;
}
const entry = (code) => {
  const e = cat.emails.find((x) => x.code === code);
  if (!e) throw new Error(`catalogue.json has no ${code}: run node emails/build.mjs`);
  return e;
};
const varsOf = (e) => e.variables.map((v) => {
  const o = { name: v.name, type: v.type };
  if (v.fields) o.fields = v.fields.map((f) => (typeof f === 'string' ? f : f.name));
  if (globals.includes(v.name)) o.global = true;
  return o;
});
const words = WORDS.map((code) => {
  const e = entry(code);
  return `update notification_catalogue set subject = ${q(e.subject)}, preheader = ${q(e.preheader)}, variables = ${q(JSON.stringify(varsOf(e)))}::jsonb, updated_at = now() where code = ${q(code)};`;
});
const rows = CODES.map((code) => {
  const e = entry(code);
  const vars = varsOf(e);
  return '  (' + [q(e.code), q(e.audience), arr(e.also_sent_to), q(e.category), e.digest ? 'true' : 'false', q(e.digest_slot ?? null),
    q(e.from), q(e.reply_to), q(e.subject), q(e.preheader), q(e.timing), q(e.trigger), q(e.source ?? null),
    q(primaryLink(e)), q(JSON.stringify(vars)) + '::jsonb', q(e.template_html), q(e.template_text)].join(', ') + ')';
});
const sql = [START,
  'insert into notification_catalogue (code, audience, also_sent_to, category, is_digest, digest_slot, from_address, reply_to,',
  '    subject, preheader, timing, trigger_text, replaces_template, link_path, variables, template_html, template_text) values',
  rows.join(',\n'),
  'on conflict (code) do update set',
  '  audience = excluded.audience, also_sent_to = excluded.also_sent_to, category = excluded.category,',
  '  is_digest = excluded.is_digest, digest_slot = excluded.digest_slot, from_address = excluded.from_address,',
  '  reply_to = excluded.reply_to, subject = excluded.subject, preheader = excluded.preheader, timing = excluded.timing,',
  '  trigger_text = excluded.trigger_text, replaces_template = excluded.replaces_template, link_path = excluded.link_path,',
  '  variables = excluded.variables, template_html = excluded.template_html, template_text = excluded.template_text,',
  '  in_catalogue = true, updated_at = now();',
  ...words,
  'select app.notification_catalogue_refresh();',
  END].join('\n');
const src = readFileSync(MIGRATION, 'utf8');
const a = src.indexOf(START), b = src.indexOf(END);
if (a < 0 || b < 0) throw new Error(`${FILE} has no catalogue markers`);
const current = src.slice(a, b + END.length);
if (process.argv.includes('--check')) {
  if (current !== sql) { console.error(`out of date: the catalogue block in ${FILE}`); process.exit(1); }
  console.log(`${FILE} catalogue block is up to date`);
} else {
  writeFileSync(MIGRATION, src.slice(0, a) + sql + src.slice(b + END.length));
  console.log(`rewrote the catalogue block in ${FILE} (${CODES.length} new, ${WORDS.length} reworded)`);
}
