#!/usr/bin/env node
// The academy block of migration 2990 (release 48: the guides taught as worked examples for each role, and the shared path
// The renter's side), from supabase/seed/academy/r48.mjs. Each section names the guide chapters it was written from
// (portal/slug); they must exist in docs/guides/content, and every screenshot a scene shows must be a guide image
// (docs/guides/content/images.json) of a chapter the section names. Quiz integrity: at least 5 questions, 4 different
// options each, the right answer in range, a reason, no question twice.
//   node supabase/seed/2990_gen_academy.mjs           rewrites the block in the migration
//   node supabase/seed/2990_gen_academy.mjs --check   exits 1 if the block is out of date or the content breaks a rule
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROLE_SECTIONS, RENTER_SECTIONS, SECTIONS } from './academy/r48.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const file = '2990_r48_academy_guides.sql';
const MIGRATION = join(ROOT, 'supabase', 'migrations', file);
const START = '-- ACADEMY 2990 START (generated by supabase/seed/2990_gen_academy.mjs from supabase/seed/academy/r48.mjs; do not edit by hand)';
const END = '-- ACADEMY 2990 END';
const ROLE_PATHS = ['cs', 'fleet', 'finance', 'sales_in_person', 'sales_remote', 'field', 'admin'];
const PATHS = new Set([...ROLE_PATHS, 'renter_side']);
const KINDS = new Set(['title', 'chat', 'list', 'steps', 'money', 'rule', 'shot']);
const q = (v) => "'" + String(v).replace(/'/g, "''") + "'";
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;

const chapters = new Set();
for (const p of ['renter', 'owner', 'admin', 'va', 'field', 'investor']) {
  const d = JSON.parse(readFileSync(join(ROOT, 'docs', 'guides', 'content', `${p}.json`), 'utf8'));
  for (const s of d.sections) chapters.add(`${p}/${s.slug}`);
}
const images = new Set(JSON.parse(readFileSync(join(ROOT, 'docs', 'guides', 'content', 'images.json'), 'utf8')));

const problems = [];
const LONG = /[–—]/;
const VENDOR = /google|stripe|\bquo\b|openphone|cloudflare|claude|gemini/i;
const seen = new Set();
for (const s of SECTIONS) {
  if (!/^[a-z0-9-]{2,60}$/.test(s.slug)) problems.push(`${s.slug}: bad slug`);
  if (seen.has(s.slug)) problems.push(`${s.slug}: twice`); seen.add(s.slug);
  if (!s.guides.length) problems.push(`${s.slug}: names no guide chapter`);
  for (const g of s.guides) if (!chapters.has(g)) problems.push(`${s.slug}: guide chapter ${g} does not exist`);
  for (const p of s.paths) if (!PATHS.has(p)) problems.push(`${s.slug}: unknown path ${p}`);
  if (!s.lessons.length) problems.push(`${s.slug}: no lesson`);
  const scenes = s.lessons.flatMap((l) => l.scenes);
  for (const sc of scenes) {
    if (!sc.caption?.trim() || !sc.say?.trim()) problems.push(`${s.slug}: a scene without a caption or words`);
    const v = sc.visual;
    if (!KINDS.has(v.kind)) problems.push(`${s.slug}: unknown visual ${v.kind}`);
    if (v.kind === 'shot') {
      if (!s.guides.includes(v.guide)) problems.push(`${s.slug}: a screenshot of ${v.guide}, a chapter the section does not name`);
      if (v.img && !images.has(v.img)) problems.push(`${s.slug}: screenshot ${v.img} is not a guide image`);
    }
  }
  // the worked examples: a role section shows what is said (a chat); a renter step shows what the renter sees (a screenshot)
  if (ROLE_SECTIONS.includes(s) && !scenes.some((x) => x.visual.kind === 'chat')) problems.push(`${s.slug}: no worked example (chat)`);
  if (RENTER_SECTIONS.includes(s) && !scenes.some((x) => x.visual.kind === 'shot' && x.visual.guide.startsWith('renter/'))) problems.push(`${s.slug}: no renter guide page shown`);
  if (s.quiz.length < 5) problems.push(`${s.slug}: fewer than 5 questions`);
  const prompts = new Set();
  for (const x of s.quiz) {
    if (prompts.has(x.prompt)) problems.push(`${s.slug}: question twice: "${x.prompt}"`); prompts.add(x.prompt);
    if (x.options.length !== 4 || new Set(x.options).size !== 4) problems.push(`${s.slug}: "${x.prompt}" needs 4 different options`);
    if (!(Number.isInteger(x.answer) && x.answer >= 0 && x.answer < x.options.length)) problems.push(`${s.slug}: answer out of range in "${x.prompt}"`);
    if (!x.explain?.trim()) problems.push(`${s.slug}: no reason for "${x.prompt}"`);
  }
  if (LONG.test(JSON.stringify(s))) problems.push(`${s.slug}: a long dash`);
  if (VENDOR.test(JSON.stringify({ ...s, guides: [], lessons: s.lessons.map((l) => ({ ...l, scenes: l.scenes.map((x) => ({ ...x, visual: { ...x.visual, img: '' } })) })) }))) problems.push(`${s.slug}: a vendor name`);
}
for (const p of ROLE_PATHS) if (!ROLE_SECTIONS.some((s) => s.paths.includes(p))) problems.push(`no worked examples for ${p}`);
if (problems.length) { for (const p of problems) console.error(p); process.exit(1); }

const lines = [];
for (const s of SECTIONS) {
  lines.push(`insert into academy_sections (slug, title, blurb, guide_refs) values (${q(s.slug)}, ${q(s.title)}, ${q(s.blurb)}, ${arr(s.guides)}) on conflict (slug) do update set title = excluded.title, blurb = excluded.blurb, guide_refs = excluded.guide_refs, updated_at = now();`);
  s.lessons.forEach((l, i) => lines.push(`insert into academy_lessons (section_id, sort, title, scenes) values ((select id from academy_sections where slug = ${q(s.slug)}), ${i + 1}, ${q(l.title)}, ${q(JSON.stringify(l.scenes))}::jsonb) on conflict (section_id, sort) do update set title = excluded.title, scenes = excluded.scenes, updated_at = now();`));
  s.quiz.forEach((x, i) => lines.push(`insert into academy_questions (section_id, sort, prompt, options, answer, explain) values ((select id from academy_sections where slug = ${q(s.slug)}), ${i + 1}, ${q(x.prompt)}, ${q(JSON.stringify(x.options))}::jsonb, ${x.answer}, ${q(x.explain)}) on conflict (section_id, sort) do update set prompt = excluded.prompt, options = excluded.options, answer = excluded.answer, explain = excluded.explain, updated_at = now();`));
  for (const p of s.paths) lines.push(`insert into academy_path_sections (path_code, section_id, sort) select ${q(p)}, (select id from academy_sections where slug = ${q(s.slug)}), coalesce(max(sort), 0) + 1 from academy_path_sections where path_code = ${q(p)} on conflict (path_code, section_id) do nothing;`);
}

const block = `${START}\n${lines.join('\n')}\n${END}`;
const sql = readFileSync(MIGRATION, 'utf8');
const a = sql.indexOf(START), b = sql.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers missing');
const next = sql.slice(0, a) + block + sql.slice(b + END.length);
if (process.argv.includes('--check')) { if (next !== sql) { console.error(`${file}: academy block is out of date`); process.exit(1); } console.log(`${file}: academy block up to date (${SECTIONS.length} sections, ${SECTIONS.reduce((n, s) => n + s.quiz.length, 0)} questions)`); }
else { writeFileSync(MIGRATION, next); console.log(`${file}: ${SECTIONS.length} sections, ${lines.length} statements`); }
