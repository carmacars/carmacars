#!/usr/bin/env node
// The guide chapters whose text changed with migration 0049 (signing in one package, Forms C and D on paper with a phone
// photo, agreements generated from the records, the official forms' drafts, guide upkeep), from docs/guides/content
// (written by docs/guides/src/export.py), with the HTML of web/src/features/guides/markdown.ts. Each chapter's text
// before the change (the content of the October 16 deploy, commit dd04ef1) is recorded by its MD5: a live chapter still
// showing that text gets the new one, published; a chapter an Admin edited keeps the Admin's text and gets the new one
// as a suggestion to review (Admin > Settings > Guides). Chapters new in 0048 already carry the new text.
//   node supabase/seed/0049_gen_guides.mjs           rewrites the block in 0049_simple_signing_guide_upkeep.sql
//   node supabase/seed/0049_gen_guides.mjs --check   exits 1 if the block is out of date (needs git for the base text)
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderGuide } from '../../web/src/features/guides/markdown.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MIGRATION = join(ROOT, 'supabase', 'migrations', '0049_simple_signing_guide_upkeep.sql');
const START = '-- GUIDES 0049 START (generated by supabase/seed/0049_gen_guides.mjs from docs/guides/content; do not edit by hand)';
const END = '-- GUIDES 0049 END';
const BASE = 'dd04ef1';
const NEW_IN_0048 = new Set(['admin/partners-company-cars-and-rentals-added-by-hand', 'va/add-a-rental-by-hand', 'owner/for-partner-rental-companies']);
const q = (v) => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");
const md5 = (s) => createHash('md5').update(s).digest('hex');

const lines = [];
for (const portal of ['renter', 'owner', 'admin', 'va', 'field', 'investor']) {
  const now = JSON.parse(readFileSync(join(ROOT, 'docs', 'guides', 'content', `${portal}.json`), 'utf8'));
  const base = JSON.parse(execFileSync('git', ['show', `${BASE}:docs/guides/content/${portal}.json`], { cwd: ROOT, encoding: 'utf8' }));
  for (const s of now.sections) {
    if (NEW_IN_0048.has(`${portal}/${s.slug}`)) continue;
    const b = base.sections.find((x) => x.slug === s.slug);
    if (!b || (b.body_md === s.body_md && b.title === s.title && (b.blurb ?? '') === (s.blurb ?? ''))) continue;
    const { html, warnings } = renderGuide([{ ...s, id: 'x' }]);
    if (warnings.length) throw new Error(`${portal}/${s.slug}: ${warnings.join('; ')}`);
    lines.push(`select app.guide_update_published_section(${q(portal)}, ${q(s.slug)}, ${q(md5(b.body_md))}, ${q(s.title)}, ${q(s.blurb)},\n  ${q(s.body_md)},\n  ${q(html.x)});`);
  }
}
const block = `${START}\n${lines.join('\n')}\n${END}`;
const sql = readFileSync(MIGRATION, 'utf8');
const a = sql.indexOf(START), b = sql.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers missing');
const next = sql.slice(0, a) + block + sql.slice(b + END.length);
if (process.argv.includes('--check')) { if (next !== sql) { console.error('0049 guides block is out of date'); process.exit(1); } console.log('0049 guides block up to date'); }
else { writeFileSync(MIGRATION, next); console.log(`0049: ${lines.length} chapters updated`); }
