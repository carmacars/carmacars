#!/usr/bin/env node
// Builds the SQL that loads the email catalogue into the database (migration 0018).
//
//   node supabase/seed/0018_gen_catalogue.mjs            writes supabase/seed/0018_catalogue.sql
//   node supabase/seed/0018_gen_catalogue.mjs --check    exits 1 if 0018_catalogue.sql, or the copy of it
//                                                        inside the migration, is out of date
//   node supabase/seed/0018_gen_catalogue.mjs --embed    also rewrites the copy inside the migration
//                                                        (only before the migration is first applied)
//
// Reads emails/catalogue.json, emails/src/links.mjs and emails/templates/<code>.html.
// Node built-ins only. The output is an upsert, so it can be run again on a live database when
// the catalogue changes: see docs/changes/0018_notifications.md, "When the catalogue changes".

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CATALOGUE = join(ROOT, 'emails', 'catalogue.json');
const LINKS = join(ROOT, 'emails', 'src', 'links.mjs');
const TEMPLATES = join(ROOT, 'emails');
const OUT = join(ROOT, 'supabase', 'seed', '0018_catalogue.sql');
const MIGRATION = join(ROOT, 'supabase', 'migrations', '0018_notifications.sql');
const START = '-- CATALOGUE START (generated by supabase/seed/0018_gen_catalogue.mjs; do not edit by hand)';
const END = '-- CATALOGUE END';

const q = (v) => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");
const arr = (a) => (a && a.length ? 'array[' + a.map(q).join(', ') + ']::text[]' : "'{}'::text[]");

// The paths, read from the source text so this file needs nothing but Node.
function readPaths() {
  const src = readFileSync(LINKS, 'utf8');
  const site = /export const SITE = '([^']+)'/.exec(src);
  const block = /export const PATHS = \{([\s\S]*?)\n\};/.exec(src);
  if (!site || !block) throw new Error('Could not read SITE or PATHS from emails/src/links.mjs');
  const paths = [];
  for (const m of block[1].matchAll(/^\s*([a-z0-9_]+):\s*'([^']*)'/gm)) paths.push({ key: m[1], path: m[2] });
  if (!paths.length) throw new Error('No paths found in emails/src/links.mjs');
  return { site: site[1], paths };
}

// The link a reader is sent to: the first link in the template that is not the home page,
// the terms or the privacy page. Null when the email has none (it links only by merge variable).
function primaryLink(entry, site) {
  const file = join(TEMPLATES, entry.template_html);
  if (!existsSync(file)) return null;
  const html = readFileSync(file, 'utf8');
  for (const m of html.matchAll(/href="([^"]+)"/g)) {
    const href = m[1];
    if (!href.startsWith(site)) continue;
    const path = href.slice(site.length) || '/';
    if (path === '/' || path === '/terms' || path === '/privacy') continue;
    return path;
  }
  return null;
}

function build() {
  const cat = JSON.parse(readFileSync(CATALOGUE, 'utf8'));
  const { site, paths } = readPaths();
  if (cat.count !== cat.emails.length) throw new Error('catalogue.json: count does not match the number of emails');
  const globals = cat.global_variables.map((v) => v.name);
  const lines = [];
  lines.push(START);
  lines.push(`-- Source: emails/catalogue.json (${cat.emails.length} emails), emails/src/links.mjs (${paths.length} paths).`);
  lines.push('insert into notification_link_paths (key, path) values');
  lines.push(paths.map((p) => `  (${q(p.key)}, ${q(p.path)})`).join(',\n'));
  lines.push('on conflict (key) do update set path = excluded.path;');
  lines.push('');
  lines.push('insert into notification_catalogue (code, audience, also_sent_to, category, is_digest, digest_slot, from_address, reply_to,');
  lines.push('    subject, preheader, timing, trigger_text, replaces_template, link_path, variables, template_html, template_text) values');
  const rows = cat.emails.map((e) => {
    const vars = e.variables.map((v) => {
      const o = { name: v.name, type: v.type };
      if (v.fields) o.fields = v.fields.map((f) => (typeof f === 'string' ? f : f.name));
      if (globals.includes(v.name)) o.global = true;
      return o;
    });
    return '  (' + [
      q(e.code), q(e.audience), arr(e.also_sent_to), q(e.category), e.digest ? 'true' : 'false', q(e.digest_slot ?? null),
      q(e.from), q(e.reply_to), q(e.subject), q(e.preheader), q(e.timing), q(e.trigger), q(e.source ?? null),
      q(primaryLink(e, site)), q(JSON.stringify(vars)) + '::jsonb', q(e.template_html), q(e.template_text),
    ].join(', ') + ')';
  });
  lines.push(rows.join(',\n'));
  lines.push('on conflict (code) do update set');
  lines.push('  audience = excluded.audience, also_sent_to = excluded.also_sent_to, category = excluded.category,');
  lines.push('  is_digest = excluded.is_digest, digest_slot = excluded.digest_slot, from_address = excluded.from_address,');
  lines.push('  reply_to = excluded.reply_to, subject = excluded.subject, preheader = excluded.preheader, timing = excluded.timing,');
  lines.push('  trigger_text = excluded.trigger_text, replaces_template = excluded.replaces_template, link_path = excluded.link_path,');
  lines.push('  variables = excluded.variables, template_html = excluded.template_html, template_text = excluded.template_text,');
  lines.push('  in_catalogue = true, updated_at = now();');
  lines.push('');
  lines.push('-- A code that has left the catalogue is kept (old outbox rows point at it) but is marked.');
  lines.push('update notification_catalogue set in_catalogue = false, updated_at = now()');
  lines.push(' where in_catalogue and has_email and code not in (');
  lines.push(cat.emails.map((e) => '  ' + q(e.code)).join(',\n'));
  lines.push(' );');
  lines.push('-- Sending class, urgency and what emits each code are worked out in SQL, not here.');
  lines.push('select app.notification_catalogue_refresh();');
  lines.push(END);
  return lines.join('\n') + '\n';
}

const sql = build();
const header = '-- 0018_catalogue.sql\n'
  + '-- The email catalogue as rows. Generated; do not edit by hand. Regenerate with\n'
  + '--   node supabase/seed/0018_gen_catalogue.mjs\n'
  + '-- Migration 0018 carries a copy of this block. After the catalogue changes, run this file\n'
  + '-- against the database (it is an upsert), or copy it into a new migration.\n';
const args = process.argv.slice(2);

function embedded() {
  if (!existsSync(MIGRATION)) return null;
  const src = readFileSync(MIGRATION, 'utf8');
  const a = src.indexOf(START);
  const b = src.indexOf(END);
  if (a < 0 || b < 0) return null;
  return { src, a, b: b + END.length + 1 };
}

if (args.includes('--check')) {
  let bad = 0;
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== header + sql) { console.error('out of date: supabase/seed/0018_catalogue.sql'); bad = 1; }
  const e = embedded();
  if (args.includes('--migration') && (!e || e.src.slice(e.a, e.b) !== sql)) { console.error('out of date: the catalogue block in 0018_notifications.sql'); bad = 1; }
  if (bad) process.exit(1);
  console.log('catalogue SQL is up to date');
} else {
  writeFileSync(OUT, header + sql);
  console.log('wrote supabase/seed/0018_catalogue.sql');
  if (args.includes('--embed')) {
    const e = embedded();
    if (!e) throw new Error('The migration has no catalogue block markers');
    writeFileSync(MIGRATION, e.src.slice(0, e.a) + sql + e.src.slice(e.b));
    console.log('rewrote the catalogue block in supabase/migrations/0018_notifications.sql');
  }
}
