#!/usr/bin/env node
// The academy block of migration 2321 (release 37: calls first, texts after), from supabase/seed/academy/r37calls.mjs. Each section
// names the guide chapters it was written from (portal/slug); they must exist in docs/guides/content.
//   node supabase/seed/2321_gen_academy.mjs           rewrites the block in the migration
//   node supabase/seed/2321_gen_academy.mjs --check   exits 1 if the block is out of date or a chapter is missing
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SECTIONS } from './academy/r37calls.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const file = '2321_r37_calls_first.sql';
const MIGRATION = join(ROOT, 'supabase', 'migrations', file);
const START = '-- ACADEMY 2321 START (generated by supabase/seed/2321_gen_academy.mjs from supabase/seed/academy/r37calls.mjs; do not edit by hand)';
const END = '-- ACADEMY 2321 END';
const PATHS = new Set(['cs', 'fleet', 'finance', 'sales_in_person', 'sales_remote', 'field', 'admin']);
const KINDS = new Set(['title', 'chat', 'list', 'steps', 'money', 'rule']);
const q = (v) => "'" + String(v).replace(/'/g, "''") + "'";
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;

const chapters = new Set();
for (const p of ['renter', 'owner', 'admin', 'va', 'field', 'investor']) {
  const d = JSON.parse(readFileSync(join(ROOT, 'docs', 'guides', 'content', `${p}.json`), 'utf8'));
  for (const s of d.sections) chapters.add(`${p}/${s.slug}`);
}
const problems = [];
const LONG = /[–—]/;
for (const s of SECTIONS) {
  if (!/^[a-z0-9-]{2,60}$/.test(s.slug)) problems.push(`${s.slug}: bad slug`);
  for (const g of s.guides) if (!chapters.has(g)) problems.push(`${s.slug}: guide chapter ${g} does not exist`);
  for (const p of s.paths) if (!PATHS.has(p)) problems.push(`${s.slug}: unknown path ${p}`);
  if (!s.quiz.length) problems.push(`${s.slug}: no quiz`);
  for (const l of s.lessons) for (const sc of l.scenes) if (!KINDS.has(sc.visual.kind)) problems.push(`${s.slug}: unknown visual ${sc.visual.kind}`);
  for (const x of s.quiz) if (!(x.answer >= 0 && x.answer < x.options.length)) problems.push(`${s.slug}: answer out of range in "${x.prompt}"`);
  if (LONG.test(JSON.stringify(s))) problems.push(`${s.slug}: a long dash`);
}
if (problems.length) { for (const p of problems) console.error(p); process.exit(1); }

const lines = [];
for (const s of SECTIONS) {
  lines.push(`insert into academy_sections (slug, title, blurb, guide_refs) values (${q(s.slug)}, ${q(s.title)}, ${q(s.blurb)}, ${arr(s.guides)}) on conflict (slug) do update set title = excluded.title, blurb = excluded.blurb, guide_refs = excluded.guide_refs, updated_at = now();`);
  s.lessons.forEach((l, i) => lines.push(`insert into academy_lessons (section_id, sort, title, scenes) values ((select id from academy_sections where slug = ${q(s.slug)}), ${i + 1}, ${q(l.title)}, ${q(JSON.stringify(l.scenes))}::jsonb) on conflict (section_id, sort) do update set title = excluded.title, scenes = excluded.scenes, updated_at = now();`));
  s.quiz.forEach((x, i) => lines.push(`insert into academy_questions (section_id, sort, prompt, options, answer, explain) values ((select id from academy_sections where slug = ${q(s.slug)}), ${i + 1}, ${q(x.prompt)}, ${q(JSON.stringify(x.options))}::jsonb, ${x.answer}, ${q(x.explain)}) on conflict (section_id, sort) do update set prompt = excluded.prompt, options = excluded.options, answer = excluded.answer, explain = excluded.explain, updated_at = now();`));
  for (const p of s.paths) lines.push(`insert into academy_path_sections (path_code, section_id, sort) select ${q(p)}, (select id from academy_sections where slug = ${q(s.slug)}), coalesce(max(sort), 0) + 1 from academy_path_sections where path_code = ${q(p)} on conflict (path_code, section_id) do nothing;`);
}

const block = `${START}\n${lines.join('\n')}\n${END}`;
const sql = readFileSync(MIGRATION, 'utf8');
const a = sql.indexOf(START), b = sql.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers missing');
const next = sql.slice(0, a) + block + sql.slice(b + END.length);
if (process.argv.includes('--check')) { if (next !== sql) { console.error(`${file}: academy block is out of date`); process.exit(1); } console.log(`${file}: academy block up to date`); }
else { writeFileSync(MIGRATION, next); console.log(`${file}: ${SECTIONS.length} sections, ${lines.length} statements`); }
