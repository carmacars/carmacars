#!/usr/bin/env node
// The guide chapters of the guided actions release (0078_guided_actions.sql: Admin > To do as prompts with pop-ups,
// Insurer confirmed, renter documents reviewed from the booking, the To do lines that replace the menu paths, the
// assistants' task links), from docs/guides/content (written by docs/guides/src/export.py), with the HTML of
// web/src/features/guides/markdown.ts. Every chapter that changed since BASE (the main this release is built on) is
// published as 0059 does (an Admin's earlier text stays in the history, with Revert).
//   node supabase/seed/0078_gen_guides.mjs           rewrites the block
//   node supabase/seed/0078_gen_guides.mjs --check   exits 1 if the block is out of date (needs git for the base text)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderGuide } from '../../web/src/features/guides/markdown.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const FILE = readdirSync(join(ROOT, 'supabase', 'migrations')).find((f) => f.startsWith('0078_'));
const MIGRATION = join(ROOT, 'supabase', 'migrations', FILE);
const START = '-- GUIDES 0078 START (generated by supabase/seed/0078_gen_guides.mjs from docs/guides/content; do not edit by hand)';
const END = '-- GUIDES 0078 END';
const BASE = process.env.GUIDES_BASE || 'db53997';
const FORCE = new Set();
const q = (v) => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");

const lines = [];
for (const portal of ['renter', 'owner', 'admin', 'va', 'field', 'investor']) {
  const now = JSON.parse(readFileSync(join(ROOT, 'docs', 'guides', 'content', `${portal}.json`), 'utf8'));
  const base = JSON.parse(execFileSync('git', ['show', `${BASE}:docs/guides/content/${portal}.json`], { cwd: ROOT, encoding: 'utf8' }));
  let after = null;
  for (const s of now.sections) {
    const b = base.sections.find((x) => x.slug === s.slug);
    const prev = after; after = s.slug;
    const force = FORCE.has(`${portal}/${s.slug}`);
    if (!force && b && b.body_md === s.body_md && b.title === s.title && (b.blurb ?? '') === (s.blurb ?? '')) continue;
    const { html, warnings } = renderGuide([{ ...s, id: 'x' }]);
    if (warnings.length) throw new Error(`${portal}/${s.slug}: ${warnings.join('; ')}`);
    lines.push(`select app.guide_release_section(${q(portal)}, ${q(s.slug)}, ${q(s.kind)}, ${q(prev)}, ${q(b?.body_md ?? null)}, ${q(s.title)}, ${q(s.blurb)},\n  ${q(s.body_md)},\n  ${q(html.x)});`);
  }
}
const block = `${START}\n${lines.join('\n')}\n${END}`;
const sql = readFileSync(MIGRATION, 'utf8');
const a = sql.indexOf(START), b = sql.indexOf(END);
if (a < 0 || b < 0) throw new Error('markers missing');
const next = sql.slice(0, a) + block + sql.slice(b + END.length);
if (process.argv.includes('--check')) { if (next !== sql) { console.error(`${FILE}: guides block is out of date`); process.exit(1); } console.log(`${FILE}: guides block up to date`); }
else { writeFileSync(MIGRATION, next); console.log(`${FILE}: ${lines.length} chapters published or added`); }
