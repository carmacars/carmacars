// Release 45 (migrations 2840 to 2842): one listing photo standard, r45.1. The owner (Nov 14): the plates still wrong, the
// backgrounds not removed, only one or two photos on many cars, an interior first, and the photos made with Cloudflare's
// cut-out "look like shit": "use the photos directly and use Gemini to edit them directly". So, for every listing photo:
//   * Gemini edits the ORIGINAL upload (never a Cloudflare cut-out, composite or resize): an outside photo gets the whole
//     background replaced by the CarmaCars showroom (the empty room is sent as the second image), an inside photo is cleaned
//     up and made sharp;
//   * a missing standard angle is GENERATED by Gemini from the car's own photos, in the same room (marked ai_generated);
//   * every plate is blurred so no character can be read (Gemini is told to, and the site blurs the plate boxes the check
//     finds on top); no text is drawn on a plate, ever, and no text may appear anywhere else;
//   * a second Gemini pass (the vision check) compares the result with the original and refuses original background, a
//     warped body, another colour or model, parts added or missing, readable plate text, text anywhere else, a blurred or
//     cluttered interior; the site also checks the edges of an outside photo are the dark room (backgroundReplaced). Refused:
//     made again (two more tries), then kept off the site and flagged, never published.
// Pure: no I/O, so the unit tests cover the words, the plan of the angles, the check's verdict, the plate blur and the order.
