/** The words for one photo: generated, an outside view, a standard inside view, or another detail. */
export function promptFor(o: { car: CarFacts; shot: string; generated: boolean; sources?: number }): string {
  if (o.generated) return generatePrompt({ car: o.car, shot: o.shot, sources: o.sources ?? 1 });
  if (isExterior(o.shot)) return exteriorPrompt(o);
  return angleOf(o.shot) ? interiorPrompt(o) : detailPrompt(o);
}

