// Builds src/features/owner-agreement/source.generated.ts from the owner agreements in
// ../docs/source/v2_enrollment.md and ../docs/source/v2_title_holding.md, so the Worker carries the
// text without reading files at run time. The same replacements as the rental agreement
// (scripts/gen-agreement.mjs): the numbered company name becomes CarmaCars and dashes follow the
// copy rules. The cover summary, the schedule entries and the signature block are built from the
// owner's records (src/features/owner-agreement/model.ts); the articles and Schedule B are fixed.
//   node scripts/gen-owner-agreements.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(path.join(WEB, '../docs/source', f), 'utf8');
const clean = (s) => s
  .replace(/\d{6,} Canada Inc\.,? operating as CarmaCars( and CarmaCars\.ca)?/g, 'CarmaCars')
  .replace(/\d{6,} Canada Inc\.( \(CarmaCars\))?/g, 'CarmaCars')
  .replace(/ – /g, ': ').replace(/[–—]/g, '-');

function between(raw, start, end) {
  const a = raw.indexOf(start);
  const b = end ? raw.indexOf(end, a + start.length) : raw.length;
  if (a < 0 || b < 0) throw new Error(`section not found: ${start}`);
  return raw.slice(a, b).trim();
}
// "## 3. Eligibility" becomes a sub-heading inside the document; "**Part 1 - ...**" stays bold
const body = (s) => clean(s).replace(/^## /gm, '### ');

const ea = read('v2_enrollment.md');
const ta = read('v2_title_holding.md');
const out = {
  enrollment: body(between(ea, '## 1. Definitions', '## Signatures')),
  scheduleB: body(between(ea, '## Schedule B', null)).replace(/^### Schedule B[^\n]*\n+/, ''),
  title: body(between(ta, '## 1. Definitions', '## Signatures'))
};
for (const [k, v] of Object.entries(out)) {
  if (v.includes('[●]')) throw new Error(`${k} still has a blank`);
  if (/Canada Inc|[–—]/.test(v)) throw new Error(`${k} still has the numbered name or a long dash`);
}
const sha = createHash('sha256').update(ea).update(ta).digest('hex');
mkdirSync(path.join(WEB, 'src/features/owner-agreement'), { recursive: true });
writeFileSync(path.join(WEB, 'src/features/owner-agreement/source.generated.ts'), `// GENERATED by scripts/gen-owner-agreements.mjs from docs/source/v2_enrollment.md and v2_title_holding.md. Do not edit.
export const OWNER_AGREEMENTS_SHA = '${sha}';
export const OWNER_TEMPLATE_VERSION = 'owner-v3-${sha.slice(0, 10)}';
export const ENROLLMENT_ARTICLES = ${JSON.stringify(out.enrollment)};
export const ENROLLMENT_SCHEDULE_B = ${JSON.stringify(out.scheduleB)};
export const TITLE_ARTICLES = ${JSON.stringify(out.title)};
`);
// Forms C and D of the Title Agreement (migration 0040): signed on paper with witnesses, pre-filled from the owner's
// records. The company is named as the law needs on a power of attorney: its legal name, filled from settings ({{company}}).
const forms = {
  C: between(ta, '## Form C', '## Form D').replace(/^## [^\n]*\n+/, ''),
  D: between(ta, '## Form D', '## Form E').replace(/^## [^\n]*\n+/, '')
};
// the company is named by its legal name alone, no "operating as" (the owner's decision of October 23, 2026)
const formText = (s) => s.replace(/\d{6,} Canada Inc\.,? operating as CarmaCars(?: and CarmaCars\.ca)?,?/g, '{{company}}').replace(/\d{6,} Canada Inc\./g, '{{company}}').replace(/ – /g, ': ').replace(/[–—]/g, '-');
const formSha = createHash('sha256').update(forms.C).update(forms.D).digest('hex');
writeFileSync(path.join(WEB, 'src/features/owner-agreement/forms.generated.ts'), `// GENERATED by scripts/gen-owner-agreements.mjs from docs/source/v2_title_holding.md (Forms C and D). Do not edit.
export const WITNESSED_FORMS_VERSION = 'forms-cd-${formSha.slice(0, 10)}';
export const FORM_C = ${JSON.stringify(formText(forms.C))};
export const FORM_D = ${JSON.stringify(formText(forms.D))};
`);
// Forms A and B (migration 0044): no witness, signed on screen in the owner portal with the built-in signature (or on
// paper, recorded by an Admin). Their own file and version, so Forms C and D keep theirs.
const formsAB = {
  A: between(ta, '## Form A', '## Form B').replace(/^## [^\n]*\n+/, ''),
  B: between(ta, '## Form B', '## Form C').replace(/^## [^\n]*\n+/, '')
};
const abSha = createHash('sha256').update(formsAB.A).update(formsAB.B).digest('hex');
writeFileSync(path.join(WEB, 'src/features/owner-agreement/forms-ab.generated.ts'), `// GENERATED by scripts/gen-owner-agreements.mjs from docs/source/v2_title_holding.md (Forms A and B). Do not edit.
export const SCREEN_FORMS_VERSION = 'forms-ab-${abSha.slice(0, 10)}';
export const FORM_A = ${JSON.stringify(formText(formsAB.A))};
export const FORM_B = ${JSON.stringify(formText(formsAB.B))};
`);
// The Flat-Rate Vehicle Enrollment Agreement (0205), for owners paid a flat monthly amount per car (0196): its own file and
// version. The company is named by its legal name and defined as "the Company" (no "operating as"); only dashes change.
const fr = read('v2_flat_rate_enrollment.md');
const flat = between(fr, '## 1. Definitions', '## Signatures').replace(/ – /g, ': ').replace(/[–—]/g, '-').replace(/^## /gm, '### ');
if (/operating as|\[●\]/.test(flat)) throw new Error('flat-rate agreement: no "operating as" and no blank');
const flatSha = createHash('sha256').update(fr).digest('hex');
writeFileSync(path.join(WEB, 'src/features/owner-agreement/flat-rate.generated.ts'), `// GENERATED by scripts/gen-owner-agreements.mjs from docs/source/v2_flat_rate_enrollment.md. Do not edit.
export const FLAT_TEMPLATE_VERSION = 'owner-flat-v1-${flatSha.slice(0, 10)}';
export const FLAT_ARTICLES = ${JSON.stringify(flat)};
`);
console.log(`owner agreements: version owner-v3-${sha.slice(0, 10)}; forms C and D ${formSha.slice(0, 10)}; forms A and B ${abSha.slice(0, 10)}; flat-rate ${flatSha.slice(0, 10)}`);
