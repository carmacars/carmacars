// Generates src/lib/db/types.ts from the local database, in the shape of
// `supabase gen types typescript` (the Database type supabase-js expects).
// The Supabase CLI does the same against a Supabase project; it cannot be downloaded in this
// environment, so this script reads the catalog directly. Never edit the output by hand.
//
//   DATABASE_URL=postgresql://postgres@127.0.0.1:54322/carmacars node scripts/gen-types.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postgres from 'postgres';

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sql = postgres(process.env.DATABASE_URL || 'postgresql://postgres@127.0.0.1:54322/carmacars', { max: 1, onnotice: () => {} });

const enums = await sql`
  select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
   where n.nspname = 'public' group by t.typname order by t.typname`;
const enumNames = new Set(enums.map((e) => e.name));

function tsType(udt, isArray) {
  const base = (() => {
    if (enumNames.has(udt)) return `Database["public"]["Enums"]["${udt}"]`;
    switch (udt) {
      case 'int2': case 'int4': case 'float4': case 'float8': case 'numeric': case 'int8': case 'oid': return 'number';
      case 'bool': return 'boolean';
      case 'json': case 'jsonb': return 'Json';
      case 'void': return 'undefined';
      case 'record': return 'Record<string, unknown>';
      default: return 'string';
    }
  })();
  return isArray ? `${base}[]` : base;
}

const cols = await sql`
  select c.relname as rel, c.relkind as kind, a.attname as col, a.attnum,
         coalesce(et.typname, t.typname) as udt, t.typcategory = 'A' as is_array,
         not a.attnotnull as nullable, a.atthasdef or a.attidentity <> '' or a.attgenerated <> '' as has_default
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
    join pg_type t on t.oid = a.atttypid left join pg_type et on et.oid = t.typelem and t.typcategory = 'A'
   where n.nspname = 'public' and c.relkind in ('r', 'v', 'm', 'p')
   order by c.relname, a.attnum`;

const rels = new Map();
for (const r of cols) {
  if (!rels.has(r.rel)) rels.set(r.rel, { kind: r.kind, cols: [] });
  rels.get(r.rel).cols.push(r);
}

const fns = await sql`
  select p.proname as name, p.proretset as setof, coalesce(p.proargnames, '{}') as argnames,
         coalesce(p.proallargtypes, string_to_array(nullif(p.proargtypes::text, ''), ' ')::oid[], '{}') as argtypes, coalesce(p.proargmodes, '{}') as modes,
         p.pronargdefaults as ndefaults, p.pronargs as nargs, rt.typname as rettype, rt.typtype as rettyptype,
         rt.typcategory = 'A' as ret_array, coalesce(ret.typname, rt.typname) as ret_elem
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    join pg_type rt on rt.oid = p.prorettype left join pg_type ret on ret.oid = rt.typelem and rt.typcategory = 'A'
   where n.nspname = 'public' and p.prokind = 'f'
     and p.proname !~ '^(gbt_|gbtreekey)' and p.proname !~ '_dist$'
     and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
   order by p.proname, p.oid`;
const typeNames = new Map((await sql`select oid, typname, typcategory, typelem from pg_type`).map((t) => [Number(t.oid), t]));
const tname = (oid) => {
  const t = typeNames.get(Number(oid));
  if (!t) return ['text', false];
  if (t.typcategory === 'A') return [typeNames.get(Number(t.typelem))?.typname ?? 'text', true];
  return [t.typname, false];
};

const ind = (n) => '  '.repeat(n);
let out = `// Generated by scripts/gen-types.mjs from the local database. Do not edit.\n// Regenerate after each migration: npm run db:types\n\n`;
out += `export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\n`;
out += `export type Database = {\n${ind(1)}public: {\n${ind(2)}Tables: {\n`;
const relBlock = (name, r, withWrite) => {
  let s = `${ind(3)}${name}: {\n${ind(4)}Row: {\n`;
  for (const c of r.cols) s += `${ind(5)}${c.col}: ${tsType(c.udt, c.is_array)}${c.nullable ? ' | null' : ''};\n`;
  s += `${ind(4)}};\n`;
  if (withWrite) {
    s += `${ind(4)}Insert: {\n`;
    for (const c of r.cols) s += `${ind(5)}${c.col}${c.nullable || c.has_default ? '?' : ''}: ${tsType(c.udt, c.is_array)}${c.nullable ? ' | null' : ''};\n`;
    s += `${ind(4)}};\n${ind(4)}Update: {\n`;
    for (const c of r.cols) s += `${ind(5)}${c.col}?: ${tsType(c.udt, c.is_array)}${c.nullable ? ' | null' : ''};\n`;
    s += `${ind(4)}};\n`;
  }
  s += `${ind(4)}Relationships: [];\n${ind(3)}};\n`;
  return s;
};
for (const [name, r] of rels) if (r.kind === 'r' || r.kind === 'p') out += relBlock(name, r, true);
out += `${ind(2)}};\n${ind(2)}Views: {\n`;
for (const [name, r] of rels) if (r.kind === 'v' || r.kind === 'm') out += relBlock(name, r, false);
out += `${ind(2)}};\n${ind(2)}Functions: {\n`;

const byName = new Map();
for (const f of fns) { if (!byName.has(f.name)) byName.set(f.name, []); byName.get(f.name).push(f); }
for (const [name, list] of byName) {
  const sigs = list.map((f) => {
    const ins = []; const outs = [];
    f.argtypes.forEach((oid, i) => {
      const mode = f.modes[i] ?? 'i'; const nm = f.argnames[i] ?? `arg${i}`; const [u, arr] = tname(oid);
      if (mode === 'i' || mode === 'b') ins.push({ nm, u, arr });
      if (mode === 't' || mode === 'o' || mode === 'b') outs.push({ nm, u, arr });
    });
    const firstDefault = ins.length - Number(f.ndefaults);
    const args = ins.length ? `{ ${ins.map((a, i) => `${a.nm}${i >= firstDefault ? '?' : ''}: ${tsType(a.u, a.arr)}`).join('; ')} }` : 'never';
    let ret;
    if (outs.length) ret = `{ ${outs.map((o) => `${o.nm}: ${tsType(o.u, o.arr)}`).join('; ')} }[]`;
    else { ret = tsType(f.ret_elem, f.ret_array); if (f.setof) ret = `${ret}[]`; }
    return `{ Args: ${args}; Returns: ${ret} }`;
  });
  out += `${ind(3)}${name}: ${sigs.join(' | ')};\n`;
}
out += `${ind(2)}};\n${ind(2)}Enums: {\n`;
for (const e of enums) out += `${ind(3)}${e.name}: ${e.labels.map((l) => JSON.stringify(l)).join(' | ')};\n`;
out += `${ind(2)}};\n${ind(2)}CompositeTypes: Record<string, never>;\n${ind(1)}};\n};\n`;

fs.writeFileSync(path.join(WEB, 'src/lib/db/types.ts'), out);
console.log(`types: ${rels.size} tables and views, ${byName.size} functions, ${enums.length} enums`);
await sql.end();
