// Builds src/features/agreement/source.generated.ts from the rental agreement in
// ../docs/source/v2_rental.md, so the Worker carries the text without reading files at run time.
// The same replacements as the legal pages of the seed (scripts/seed.mjs): the numbered company name
// becomes CarmaCars and dashes follow the copy rules. Parts 2, 3, 5 and 6 are kept; Part 1 (the
// summary) is built from the booking, Part 4 (the Condition Report) is a separate document.
//   node scripts/gen-agreement.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(WEB, '../docs/source/v2_rental.md');
const raw = readFileSync(SRC, 'utf8');
const clean = (s) => s
  .replace(/\d{6,} Canada Inc\.,? operating as CarmaCars/g, 'CarmaCars')
  .replace(/\d{6,} Canada Inc\.( \(CarmaCars\))?/g, 'CarmaCars')
  .replace(/ – /g, ': ').replace(/[–—]/g, '-');

const parts = {};
let closing = '';
for (const chunk of raw.split('<!--PART-->').slice(1)) {
  const m = chunk.match(/^\s*## Part (\d) [–-] (.+)\n([\s\S]*)$/);
  if (!m) continue;
  const [, n, title, body] = m;
  if (n === '1') {
    // the closing lines of Part 1: the sentence above the signature table
    const sign = body.match(/\n(By signing, [^\n]+)/);
    closing = sign ? clean(sign[1]) : '';
    continue;
  }
  if (n === '4') continue;
  parts[n] = { title: clean(title.trim()), body: clean(body.trim()) };
}
parts['2'].body = parts['2'].body.replace('See our Privacy Policy at [●].', 'See our Privacy Policy at {{privacyUrl}}.');
for (const [n, p] of Object.entries(parts)) if (p.body.includes('[●]')) throw new Error(`Part ${n} still has a blank`);
const sha = createHash('sha256').update(raw).digest('hex');
const out = `// GENERATED by scripts/gen-agreement.mjs from docs/source/v2_rental.md. Do not edit.
export const AGREEMENT_SOURCE_SHA = '${sha}';
export const AGREEMENT_TEMPLATE_VERSION = 'rental-v2-${sha.slice(0, 10)}';
export const AGREEMENT_CLOSING = ${JSON.stringify(closing)};
export const AGREEMENT_PARTS: Record<'2' | '3' | '5' | '6', { title: string; body: string }> = ${JSON.stringify(parts, null, 2)};
`;
writeFileSync(path.join(WEB, 'src/features/agreement/source.generated.ts'), out);
console.log(`agreement: parts ${Object.keys(parts).join(', ')}; version rental-v2-${sha.slice(0, 10)}`);
