#!/usr/bin/env node
// Release 48 O (3080): the section photos' plates and the place of their sample car.
// prototype/tools/make-standins.mjs draws each section photo that shows a sample car twice more: without the car (the plate
// a real car's cutout stands on) and the car alone. This copies the plates to public/site-plates/ and measures each car
// alone (its box, in percent of the frame) into src/lib/slot-cars-data.ts, so the cutout stands exactly where, and as big
// as, the sample car stood.
//   node scripts/slot-plates.mjs           writes both
//   node scripts/slot-plates.mjs --check   exits 1 when either is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(WEB, '..', 'prototype', 'assets', 'photos', 'plates');
const OUT = path.join(WEB, 'public', 'site-plates');
const DATA = path.join(WEB, 'src', 'lib', 'slot-cars-data.ts');
// where the sample car's nose points (the delivery scenes draw it mirrored)
const FACING = { 'home-delivery': 'right', 'delivery-hero': 'right' };
const check = process.argv.includes('--check');

const files = fs.readdirSync(SRC).filter((f) => f.endsWith('.svg')).sort();
const slots = {};
let stale = false;
for (const f of files.filter((x) => x.endsWith('-plate.svg'))) {
  const dst = path.join(OUT, f);
  const body = fs.readFileSync(path.join(SRC, f));
  if (check) { if (!fs.existsSync(dst) || !fs.readFileSync(dst).equals(body)) { console.error(`stale: public/site-plates/${f}`); stale = true; } }
  else { fs.mkdirSync(OUT, { recursive: true }); fs.writeFileSync(dst, body); }
}
for (const f of files.filter((x) => /-car\d\.svg$/.test(x))) {
  const [, base, form] = f.match(/^(.+)-(wide|tall)-car\d\.svg$/);
  const svg = fs.readFileSync(path.join(SRC, f));
  const { width: W, height: H } = await sharp(svg).metadata();
  const { info } = await sharp(svg).trim({ threshold: 1 }).png().toBuffer({ resolveWithObject: true });
  const left = -(info.trimOffsetLeft ?? 0), top = -(info.trimOffsetTop ?? 0);
  const r = (v) => Math.round(v * 10000) / 100;
  const slot = base.replace('-', '.');
  slots[slot] ??= { facing: FACING[base] ?? 'left', wide: [], tall: [] };
  slots[slot][form].push({ left: r(left / W), top: r(top / H), width: r(info.width / W), height: r(info.height / H) });
}
const boxes = (a) => `[${a.map((b) => `{ left: ${b.left}, top: ${b.top}, width: ${b.width}, height: ${b.height} }`).join(', ')}]`;
const ts = `// Generated by scripts/slot-plates.mjs from prototype/assets/photos/plates (do not edit by hand).
// Each section photo with a sample car: its plate (the photo without the car) and the box of each sample car, in percent of
// the frame (left, top, width, height), for the wide and the tall photo; facing: where the sample car's nose points.
export interface SlotCarBox { left: number; top: number; width: number; height: number }
export interface SlotCarPlace { facing: 'left' | 'right'; wide: SlotCarBox[]; tall: SlotCarBox[] }
export const SLOT_CARS: Readonly<Record<string, SlotCarPlace>> = {
${Object.entries(slots).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  '${k}': { facing: '${v.facing}', wide: ${boxes(v.wide)}, tall: ${boxes(v.tall)} }`).join(',\n')}
};
`;
if (check) {
  if (!fs.existsSync(DATA) || fs.readFileSync(DATA, 'utf8') !== ts) { console.error('stale: src/lib/slot-cars-data.ts'); stale = true; }
  if (stale) process.exit(1);
  console.log('slot plates up to date');
} else {
  fs.writeFileSync(DATA, ts);
  console.log(`slot plates: ${Object.keys(slots).length} sections`);
}
